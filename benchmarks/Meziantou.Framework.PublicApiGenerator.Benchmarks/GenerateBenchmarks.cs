using System.Text.Json;
using BenchmarkDotNet.Attributes;

namespace Meziantou.Framework.PublicApiGenerator.Benchmarks;

/// <summary>
/// Generates the public API of assemblies of increasing size. The multi-target case reads the same assembly for two target
/// frameworks, as for a library whose builds are mostly identical (the common case when generating the files of a multi-targeted project).
/// </summary>
[MemoryDiagnoser]
public class GenerateBenchmarks
{
    private static readonly PublicApiOptions Options = new() { IncludeAutoGeneratedComment = false };

    private AssemblySource[] _sources = null!;

    [Params("PublicApiGenerator", "PublicApiGenerator (2 TFMs)", "System.Text.Json", "System.Private.CoreLib")]
    public string Assembly { get; set; } = null!;

    [GlobalSetup]
    public void Setup()
    {
        _sources = Assembly switch
        {
            "PublicApiGenerator" => [new AssemblySource(typeof(PublicApi).Assembly.Location)],
            "PublicApiGenerator (2 TFMs)" =>
            [
                new AssemblySource(typeof(PublicApi).Assembly.Location, ".NETCoreApp,Version=v10.0"),
                new AssemblySource(typeof(PublicApi).Assembly.Location, ".NETCoreApp,Version=v11.0"),
            ],
            "System.Text.Json" => [new AssemblySource(typeof(JsonSerializer).Assembly.Location)],
            "System.Private.CoreLib" => [new AssemblySource(typeof(object).Assembly.Location)],
            _ => throw new InvalidOperationException("Unknown assembly: " + Assembly),
        };
    }

    [Benchmark]
    public IReadOnlyList<PublicApiFile> Generate() => PublicApi.Generate(_sources, Options);

    [Benchmark]
    public PublicApiAssembly ReadAssembly() => PublicApi.ReadAssembly(_sources[0].Path!);
}
