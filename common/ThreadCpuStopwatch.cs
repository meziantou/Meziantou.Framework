using System.Runtime.InteropServices;

namespace Meziantou.Framework;

/// <summary>
/// Measures the CPU time of the current thread, for the tests that check that an operation does not take quadratic time.
/// Unlike wall-clock time, it does not include the time spent waiting for a core, which is most of the time of a test
/// on a busy CI runner where the other tests and test processes compete for the cores. It must be started, stopped and read
/// on the same thread.
/// </summary>
internal sealed partial class ThreadCpuStopwatch
{
    // CLOCK_THREAD_CPUTIME_ID
    private const int LinuxThreadCpuTimeClock = 3;
    private const int MacOSThreadCpuTimeClock = 16;

    private readonly TimeSpan _start;
    private TimeSpan? _elapsed;

    private ThreadCpuStopwatch()
    {
        _start = GetCurrentThreadCpuTime();
    }

    public TimeSpan Elapsed => _elapsed ?? GetCurrentThreadCpuTime() - _start;

    public static ThreadCpuStopwatch StartNew() => new();

    public void Stop()
    {
        _elapsed ??= GetCurrentThreadCpuTime() - _start;
    }

    public static TimeSpan GetCurrentThreadCpuTime()
    {
        if (OperatingSystem.IsWindows())
        {
            // FILETIMEs: 100-nanosecond units, like ticks.
            if (!GetThreadTimes(GetCurrentThread(), out _, out _, out var kernelTime, out var userTime))
                throw new InvalidOperationException("GetThreadTimes failed.");

            return TimeSpan.FromTicks(kernelTime + userTime);
        }

        if (ClockGetTime(OperatingSystem.IsMacOS() ? MacOSThreadCpuTimeClock : LinuxThreadCpuTimeClock, out var time) is not 0)
            throw new InvalidOperationException("clock_gettime failed.");

        return TimeSpan.FromTicks((time.Seconds * TimeSpan.TicksPerSecond) + (time.Nanoseconds / 100));
    }

#if NET11_0_OR_GREATER
    [LibraryImport("kernel32.dll")]
    [DefaultDllImportSearchPaths(DllImportSearchPath.System32)]
    private static safe partial nint GetCurrentThread();

    [LibraryImport("kernel32.dll")]
    [DefaultDllImportSearchPaths(DllImportSearchPath.System32)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static safe partial bool GetThreadTimes(nint thread, out long creationTime, out long exitTime, out long kernelTime, out long userTime);

    [LibraryImport("libc", EntryPoint = "clock_gettime")]
    [DefaultDllImportSearchPaths(DllImportSearchPath.SafeDirectories)]
    private static safe partial int ClockGetTime(int clockId, out TimeSpec time);
#else
    // The LibraryImport generator of .NET 10 marks the class 'unsafe', which the memory safety rules reject (CS9377).
    private const string LibraryImportJustification = "The code generated by the LibraryImport generator of .NET 10 does not compile under the updated memory safety rules";

    [DllImport("kernel32.dll", ExactSpelling = true)]
    [DefaultDllImportSearchPaths(DllImportSearchPath.System32)]
    [SuppressMessage("Interoperability", "SYSLIB1054:Use 'LibraryImportAttribute' instead of 'DllImportAttribute' to generate P/Invoke marshalling code at compile time", Justification = LibraryImportJustification)]
    private static safe extern nint GetCurrentThread();

    [DllImport("kernel32.dll", ExactSpelling = true)]
    [DefaultDllImportSearchPaths(DllImportSearchPath.System32)]
    [SuppressMessage("Interoperability", "SYSLIB1054:Use 'LibraryImportAttribute' instead of 'DllImportAttribute' to generate P/Invoke marshalling code at compile time", Justification = LibraryImportJustification)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static safe extern bool GetThreadTimes(nint thread, out long creationTime, out long exitTime, out long kernelTime, out long userTime);

    [DllImport("libc", EntryPoint = "clock_gettime", ExactSpelling = true)]
    [DefaultDllImportSearchPaths(DllImportSearchPath.SafeDirectories)]
    [SuppressMessage("Interoperability", "SYSLIB1054:Use 'LibraryImportAttribute' instead of 'DllImportAttribute' to generate P/Invoke marshalling code at compile time", Justification = LibraryImportJustification)]
    private static safe extern int ClockGetTime(int clockId, out TimeSpec time);
#endif

    [StructLayout(LayoutKind.Sequential)]
    private struct TimeSpec
    {
        public long Seconds;
        public long Nanoseconds;
    }
}
