namespace Meziantou.AspNetCore.Testing;

/// <summary>A mouse button (the value of <c>MouseEvent.button</c>).</summary>
public enum MouseButton
{
    /// <summary>The main button, usually the left button.</summary>
    Left = 0,

    /// <summary>The auxiliary button, usually the wheel.</summary>
    Middle = 1,

    /// <summary>The secondary button, usually the right button.</summary>
    Right = 2,
}
