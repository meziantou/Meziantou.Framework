using System.Reflection;
using Meziantou.Framework.Assertions.Architecture.Reading;

namespace Meziantou.Framework.Assertions.Architecture;

/// <summary>An assembly of the architecture.</summary>
public sealed class AssemblyElement
{
    private readonly Lazy<IReadOnlyList<AssemblyName>> _references;
    private readonly Lazy<IReadOnlyList<AttributeElement>> _attributes;

    internal AssemblyElement(ArchitectureModel architecture, AssemblyImage image)
    {
        Architecture = architecture;
        Image = image;
        _references = new(() => [.. Image.Reader.AssemblyReferences.Select(handle => Image.Reader.GetAssemblyReference(handle).GetAssemblyName())]);
        _attributes = new(() => Image.Reader.IsAssembly ? AttributeElement.Create(Architecture.GetProvider(Image), Image.Reader, Image.Reader.GetAssemblyDefinition().GetCustomAttributes()) : []);
    }

    internal AssemblyImage Image { get; }

    /// <summary>Gets the architecture that contains the assembly.</summary>
    public ArchitectureModel Architecture { get; }

    /// <summary>Gets the simple name of the assembly.</summary>
    public string Name => Image.Name;

    /// <summary>Gets the version of the assembly.</summary>
    public Version Version => Image.Version;

    /// <summary>Gets the path of the file the assembly was loaded from, or <see langword="null"/> when it was loaded from memory.</summary>
    public string? FilePath => Image.FilePath;

    /// <summary>Gets the types of the assembly, including the nested types. The types generated by the compiler are not included.</summary>
    public IReadOnlyList<TypeElement> Types { get; internal set; } = [];

    /// <summary>Gets the assemblies the assembly references.</summary>
    public IReadOnlyList<AssemblyName> References => _references.Value;

    /// <summary>Gets the attributes applied to the assembly.</summary>
    public IReadOnlyList<AttributeElement> Attributes => _attributes.Value;

    /// <summary>Returns the name of the assembly.</summary>
    /// <returns>The name of the assembly.</returns>
    public override string ToString() => Name;
}
