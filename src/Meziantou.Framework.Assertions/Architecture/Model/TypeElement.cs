using System.Reflection;
using System.Reflection.Metadata;
using System.Text;
using Meziantou.Framework.Assertions.Architecture.Reading;

namespace Meziantou.Framework.Assertions.Architecture;

/// <summary>A type defined in an assembly of the architecture.</summary>
public sealed class TypeElement
{
    private const int MaxHierarchyDepth = 128;

    private readonly TypeAttributes _attributes;
    private readonly Lazy<TypeMembers> _members;
    private readonly Lazy<DependencyCollector.Result> _dependencies;
    private readonly Lazy<IReadOnlyList<AttributeElement>> _customAttributes;
    private readonly Lazy<TypeReference?> _baseType;
    private readonly Lazy<IReadOnlyList<TypeReference>> _interfaces;
    private readonly Lazy<(IReadOnlyList<string> BaseTypes, HashSet<string> Interfaces)> _hierarchy;
    private readonly Lazy<(TypeElementKind Kind, bool IsRecord)> _kind;
    private readonly Lazy<SourceLocation?> _location;
    private readonly List<TypeElement> _nestedTypes = [];

    internal TypeElement(ArchitectureModel architecture, AssemblyElement assembly, TypeDefinitionHandle handle, TypeElement? declaringType)
    {
        Architecture = architecture;
        Assembly = assembly;
        Handle = handle;
        DeclaringType = declaringType;

        var reader = Image.Reader;
        var definition = reader.GetTypeDefinition(handle);
        _attributes = definition.Attributes;
        MetadataName = reader.GetString(definition.Name);
        Name = MetadataNames.RemoveArity(MetadataName);
        Namespace = declaringType?.Namespace ?? (definition.Namespace.IsNil ? string.Empty : reader.GetString(definition.Namespace));
        FullName = declaringType is not null ? declaringType.FullName + "+" + MetadataName : Namespace.Length == 0 ? MetadataName : Namespace + "." + MetadataName;
        GenericParameters = [.. definition.GetGenericParameters().Select(parameter => reader.GetString(reader.GetGenericParameter(parameter).Name))];
        GenericContext = new GenericContext([.. GenericParameters], []);

        _members = new(() => new TypeMembers(this));
        _dependencies = new(() => new DependencyCollector(this).Collect());
        _customAttributes = new(() => AttributeElement.Create(Provider, Image.Reader, Image.Reader.GetTypeDefinition(Handle).GetCustomAttributes()));
        _baseType = new(() => Image.Reader.GetTypeDefinition(Handle).BaseType is { IsNil: false } baseType ? DependencyCollector.DecodeType(Provider, Image.Reader, baseType, GenericContext) : null);
        _interfaces = new(() => [.. Image.Reader.GetTypeDefinition(Handle).GetInterfaceImplementations().Select(handle => DependencyCollector.DecodeType(Provider, Image.Reader, Image.Reader.GetInterfaceImplementation(handle).Interface, GenericContext))]);
        _hierarchy = new(ComputeHierarchy);
        _kind = new(ComputeKind);
        _location = new(ComputeLocation);
    }

    internal AssemblyImage Image => Assembly.Image;

    internal TypeDefinitionHandle Handle { get; }

    internal GenericContext GenericContext { get; }

    internal TypeReferenceProvider Provider => Architecture.GetProvider(Image);

    // The types the compiler generated for the code of this type (closures, lambdas, state machines, extension blocks)
    internal List<TypeDefinitionHandle> GeneratedTypes { get; } = [];

    /// <summary>Gets the architecture that contains the type.</summary>
    public ArchitectureModel Architecture { get; }

    /// <summary>Gets the assembly that defines the type.</summary>
    public AssemblyElement Assembly { get; }

    /// <summary>Gets the name of the type, without the namespace, the containing type and the generic arity (<c>Repository</c> for <c>Repository&lt;T&gt;</c>).</summary>
    public string Name { get; }

    /// <summary>Gets the name of the type as written in metadata, with the generic arity (<c>Repository`1</c>).</summary>
    public string MetadataName { get; }

    /// <summary>Gets the namespace of the type, or of its outermost containing type for a nested type.</summary>
    public string Namespace { get; }

    /// <summary>Gets the full name of the type as written in metadata (<c>MyApp.Repository`1</c>, <c>MyApp.Outer+Inner</c>), which is also the value of <see cref="Type.FullName"/>.</summary>
    public string FullName { get; }

    /// <summary>Gets the containing type of a nested type, or <see langword="null"/>.</summary>
    public TypeElement? DeclaringType { get; }

    /// <summary>Gets the nested types, except the ones generated by the compiler.</summary>
    public IReadOnlyList<TypeElement> NestedTypes => _nestedTypes;

    /// <summary>Gets the names of the generic parameters of the type, including the ones of its containing types.</summary>
    public IReadOnlyList<string> GenericParameters { get; }

    /// <summary>Gets the kind of the type.</summary>
    public TypeElementKind Kind => _kind.Value.Kind;

    /// <summary>Gets the declared accessibility of the type.</summary>
    public ElementAccessibility Accessibility => (_attributes & TypeAttributes.VisibilityMask) switch
    {
        TypeAttributes.Public or TypeAttributes.NestedPublic => ElementAccessibility.Public,
        TypeAttributes.NestedFamily => ElementAccessibility.Protected,
        TypeAttributes.NestedFamORAssem => ElementAccessibility.ProtectedInternal,
        TypeAttributes.NestedFamANDAssem => ElementAccessibility.PrivateProtected,
        TypeAttributes.NestedPrivate => ElementAccessibility.Private,
        _ => ElementAccessibility.Internal,
    };

    /// <summary>Gets a value indicating whether the type is an abstract class. Interfaces and static classes are not abstract classes.</summary>
    public bool IsAbstract => Kind == TypeElementKind.Class && _attributes.HasFlag(TypeAttributes.Abstract) && !_attributes.HasFlag(TypeAttributes.Sealed);

    /// <summary>Gets a value indicating whether no type can inherit from the type: a sealed class, a struct, an enum or a delegate. Static classes are not sealed.</summary>
    public bool IsSealed => _attributes.HasFlag(TypeAttributes.Sealed) && !IsStatic;

    /// <summary>Gets a value indicating whether the type is a static class.</summary>
    public bool IsStatic => _attributes.HasFlag(TypeAttributes.Abstract) && _attributes.HasFlag(TypeAttributes.Sealed) && !_attributes.HasFlag(TypeAttributes.Interface);

    /// <summary>Gets a value indicating whether the type is a record class or a record struct.</summary>
    public bool IsRecord => _kind.Value.IsRecord;

    /// <summary>Gets a value indicating whether the type has generic parameters, including the ones of its containing types.</summary>
    public bool IsGeneric => GenericParameters.Count > 0;

    /// <summary>Gets a value indicating whether the type is nested in another type.</summary>
    public bool IsNested => DeclaringType is not null;

    /// <summary>Gets a value indicating whether the type is a class, including a record class.</summary>
    public bool IsClass => Kind == TypeElementKind.Class;

    /// <summary>Gets a value indicating whether the type is an interface.</summary>
    public bool IsInterface => Kind == TypeElementKind.Interface;

    /// <summary>Gets a value indicating whether the type is a struct, including a record struct.</summary>
    public bool IsStruct => Kind == TypeElementKind.Struct;

    /// <summary>Gets a value indicating whether the type is an enum.</summary>
    public bool IsEnum => Kind == TypeElementKind.Enum;

    /// <summary>Gets a value indicating whether the type is a delegate.</summary>
    public bool IsDelegate => Kind == TypeElementKind.Delegate;

    /// <summary>Gets a value indicating whether the type is declared <c>public</c>. A public type nested in a non-public type is public.</summary>
    public bool IsPublic => Accessibility == ElementAccessibility.Public;

    /// <summary>Gets the base type, or <see langword="null"/> for an interface and for <see cref="object"/>.</summary>
    public TypeReference? BaseType => _baseType.Value;

    /// <summary>Gets the interfaces the type declares. Use <see cref="Implements(Type)"/> to include the interfaces of the base types.</summary>
    public IReadOnlyList<TypeReference> Interfaces => _interfaces.Value;

    /// <summary>Gets the attributes applied to the type.</summary>
    public IReadOnlyList<AttributeElement> Attributes => _customAttributes.Value;

    /// <summary>Gets the instance and static constructors.</summary>
    public IReadOnlyList<MethodElement> Constructors => _members.Value.Constructors;

    /// <summary>Gets the methods, except the constructors, the accessors of the properties and events, and the methods generated by the compiler (lambdas, local functions).</summary>
    public IReadOnlyList<MethodElement> Methods => _members.Value.Methods;

    /// <summary>Gets the properties and indexers.</summary>
    public IReadOnlyList<PropertyElement> Properties => _members.Value.Properties;

    /// <summary>Gets the fields, except the ones generated by the compiler (backing fields of auto-properties).</summary>
    public IReadOnlyList<FieldElement> Fields => _members.Value.Fields;

    /// <summary>Gets the events.</summary>
    public IReadOnlyList<EventElement> Events => _members.Value.Events;

    /// <summary>Gets all the members: constructors, methods, properties, fields and events.</summary>
    public IReadOnlyList<MemberElement> Members => _members.Value.All;

    /// <summary>
    /// Gets the types the type uses, in its declaration, the declarations of its members, and the code of its methods, lambdas, local functions, iterators and async methods.
    /// A type used several times by a member in the same way gives one dependency. The type itself and the types generated by the compiler are not included.
    /// </summary>
    public IReadOnlyList<Dependency> Dependencies => _dependencies.Value.Dependencies;

    /// <summary>
    /// Gets a value indicating whether the instances of the type cannot be modified: its instance fields are <c>readonly</c> or constant,
    /// and its instance properties have no setter, or an <c>init</c> setter. The types of the fields are not checked.
    /// </summary>
    public bool IsImmutable => Fields.All(fieldElement => fieldElement.IsStatic || fieldElement.IsReadOnly || fieldElement.IsConstant)
        && Properties.All(property => property.IsStatic || property.Setter is null || property.IsInitOnly);

    /// <summary>Gets the first statement of the type when the PDB is available, or <see langword="null"/>.</summary>
    public SourceLocation? Location => _location.Value;

    /// <summary>Determines whether the type is in the namespace <paramref name="namespace"/>, not in one of its child namespaces.</summary>
    /// <param name="namespace">The namespace (<c>MyApp.Domain</c>).</param>
    /// <returns><see langword="true"/> when <see cref="Namespace"/> is <paramref name="namespace"/>.</returns>
    /// <seealso cref="IsInNamespaceOrChildren"/>
    public bool IsInNamespace(string @namespace)
    {
        ArgumentNullException.ThrowIfNull(@namespace);
        return string.Equals(Namespace, @namespace, StringComparison.Ordinal);
    }

    /// <summary>
    /// Determines whether the type is in the namespace <paramref name="namespace"/> or in one of its child namespaces:
    /// <c>MyApp.Domain</c> matches <c>MyApp.Domain</c> and <c>MyApp.Domain.Events</c>, not <c>MyApp.DomainEvents</c>.
    /// </summary>
    /// <param name="namespace">The namespace (<c>MyApp.Domain</c>).</param>
    /// <returns><see langword="true"/> when <see cref="Namespace"/> is <paramref name="namespace"/> or starts with <paramref name="namespace"/> followed by a dot.</returns>
    /// <seealso cref="IsInNamespace"/>
    public bool IsInNamespaceOrChildren(string @namespace)
    {
        ArgumentNullException.ThrowIfNull(@namespace);
        return MetadataNames.IsInNamespaceOrChildren(Namespace, @namespace);
    }

    /// <summary>Determines whether the type inherits, directly or not, from <typeparamref name="T"/>. The base types are resolved in the referenced assemblies.</summary>
    /// <typeparam name="T">The base type. For a generic type, all its instantiations match.</typeparam>
    /// <returns><see langword="true"/> when one of the base types is <typeparamref name="T"/>.</returns>
    public bool InheritsFrom<T>() => InheritsFrom(typeof(T));

    /// <summary>Determines whether the type, one of its base types, or one of their interfaces implements <typeparamref name="T"/>.</summary>
    /// <typeparam name="T">The interface. For a generic interface, all its instantiations match.</typeparam>
    /// <returns><see langword="true"/> when the type implements the interface.</returns>
    public bool Implements<T>() => Implements(typeof(T));

    /// <summary>Determines whether the type is <typeparamref name="T"/>, inherits from it, or implements it.</summary>
    /// <typeparam name="T">The type.</typeparam>
    /// <returns><see langword="true"/> when a value of this type can be assigned to a variable of <typeparamref name="T"/>.</returns>
    public bool IsAssignableTo<T>() => IsAssignableTo(typeof(T));

    /// <summary>Determines whether the type has an attribute of type <typeparamref name="T"/>.</summary>
    /// <typeparam name="T">The type of the attribute.</typeparam>
    /// <returns><see langword="true"/> when one of the attributes of the type is of this type.</returns>
    public bool HasAttribute<T>()
        where T : Attribute => HasAttribute(typeof(T));

    /// <summary>Determines whether the type inherits, directly or not, from <paramref name="baseType"/>. The base types are resolved in the referenced assemblies.</summary>
    /// <param name="baseType">The base type, or a generic type definition (<c>typeof(Repository&lt;&gt;)</c>) to match all its instantiations.</param>
    /// <returns><see langword="true"/> when one of the base types is <paramref name="baseType"/>.</returns>
    public bool InheritsFrom(Type baseType) => InheritsFrom(MetadataNames.GetFullName(baseType ?? throw new ArgumentNullException(nameof(baseType))));

    /// <summary>Determines whether the type inherits, directly or not, from the type whose metadata name is <paramref name="fullName"/>.</summary>
    /// <param name="fullName">The full name of the base type as written in metadata (<c>MyApp.Repository`1</c>).</param>
    /// <returns><see langword="true"/> when one of the base types has this name.</returns>
    public bool InheritsFrom(string fullName)
    {
        ArgumentNullException.ThrowIfNull(fullName);
        return _hierarchy.Value.BaseTypes.Contains(fullName, StringComparer.Ordinal);
    }

    /// <summary>Determines whether the type, one of its base types, or one of their interfaces implements <paramref name="interfaceType"/>.</summary>
    /// <param name="interfaceType">The interface, or a generic type definition (<c>typeof(IHandler&lt;&gt;)</c>) to match all its instantiations.</param>
    /// <returns><see langword="true"/> when the type implements the interface.</returns>
    public bool Implements(Type interfaceType) => Implements(MetadataNames.GetFullName(interfaceType ?? throw new ArgumentNullException(nameof(interfaceType))));

    /// <summary>Determines whether the type, one of its base types, or one of their interfaces implements the interface whose metadata name is <paramref name="fullName"/>.</summary>
    /// <param name="fullName">The full name of the interface as written in metadata (<c>MyApp.IHandler`1</c>).</param>
    /// <returns><see langword="true"/> when the type implements the interface.</returns>
    public bool Implements(string fullName)
    {
        ArgumentNullException.ThrowIfNull(fullName);
        return _hierarchy.Value.Interfaces.Contains(fullName);
    }

    /// <summary>Determines whether the type is <paramref name="type"/>, inherits from it, or implements it.</summary>
    /// <param name="type">The type, or a generic type definition.</param>
    /// <returns><see langword="true"/> when a value of this type can be assigned to a variable of <paramref name="type"/>.</returns>
    public bool IsAssignableTo(Type type) => IsAssignableTo(MetadataNames.GetFullName(type ?? throw new ArgumentNullException(nameof(type))));

    /// <summary>Determines whether the type is the type whose metadata name is <paramref name="fullName"/>, inherits from it, or implements it.</summary>
    /// <param name="fullName">The full name of the type as written in metadata.</param>
    /// <returns><see langword="true"/> when a value of this type can be assigned to a variable of this type.</returns>
    public bool IsAssignableTo(string fullName) => string.Equals(FullName, fullName, StringComparison.Ordinal) || InheritsFrom(fullName) || Implements(fullName);

    /// <summary>Determines whether the type has an attribute of the given type.</summary>
    /// <param name="attributeType">The type of the attribute.</param>
    /// <returns><see langword="true"/> when one of the attributes of the type is of this type.</returns>
    public bool HasAttribute(Type attributeType)
    {
        ArgumentNullException.ThrowIfNull(attributeType);
        return Attributes.Any(attribute => attribute.Type.Is(attributeType));
    }

    /// <summary>Determines whether the type is <paramref name="type"/>, or its generic type definition.</summary>
    /// <param name="type">The type to compare with.</param>
    /// <returns><see langword="true"/> when the full names match.</returns>
    public bool Is(Type type)
    {
        ArgumentNullException.ThrowIfNull(type);
        return string.Equals(FullName, MetadataNames.GetFullName(type), StringComparison.Ordinal);
    }

    /// <summary>Returns the type as written in C#: <c>MyApp.Repository&lt;T&gt;</c>, <c>MyApp.Outer.Inner</c>.</summary>
    /// <returns>The type as written in C#.</returns>
    public override string ToString()
    {
        var sb = new StringBuilder();
        if (DeclaringType is not null)
        {
            sb.Append(DeclaringType).Append('.');
        }
        else if (Namespace.Length > 0)
        {
            sb.Append(Namespace).Append('.');
        }

        sb.Append(Name);
        var arity = MetadataNames.GetArity(MetadataName);
        if (arity > 0 && arity <= GenericParameters.Count)
        {
            sb.Append('<').AppendJoin(", ", GenericParameters.Skip(GenericParameters.Count - arity)).Append('>');
        }

        return sb.ToString();
    }

    internal void AddNestedType(TypeElement type) => _nestedTypes.Add(type);

    internal MemberElement? GetSourceMember(MethodDefinitionHandle handle) => _members.Value.GetSourceMember(handle);

    internal MemberElement? FindMemberByMethodName(string name) => _members.Value.FindByMethodName(name);

    internal MethodElement? GetAccessor(MethodDefinitionHandle handle) => _members.Value.GetAccessor(handle);

    internal MethodElement? FindAccessorByMethodName(string name) => _members.Value.FindAccessorByMethodName(name);

    internal IReadOnlyList<Dependency> GetAccessorDependencies(MethodElement accessor) => _dependencies.Value.AccessorDependencies.GetValueOrDefault(accessor) ?? [];

    internal FieldElement? GetField(FieldDefinitionHandle handle) => _members.Value.GetField(handle);

    // The name of the member a generated type belongs to: "<GetAsync>d__3" → "GetAsync". The containing generated types are searched too.
    internal string? GetGeneratedTypeOwnerName(TypeDefinitionHandle handle)
    {
        var reader = Image.Reader;
        while (!handle.IsNil && handle != Handle)
        {
            var definition = reader.GetTypeDefinition(handle);
            if (MetadataNames.GetGeneratedCodeOwnerName(reader.GetString(definition.Name)) is { } name)
                return name;

            handle = definition.GetDeclaringType();
        }

        return null;
    }

    // The source location of the code generated for a member: the state machine of an async method or an iterator has the statements of the method
    internal SourceLocation? FindGeneratedCodeLocation(string memberName)
    {
        var reader = Image.Reader;
        SourceLocation? result = null;
        foreach (var generatedType in GeneratedTypes)
        {
            if (!string.Equals(GetGeneratedTypeOwnerName(generatedType), memberName, StringComparison.Ordinal))
                continue;

            foreach (var methodHandle in reader.GetTypeDefinition(generatedType).GetMethods())
            {
                if (SequencePointMap.Create(Image, methodHandle)?.First is { } location && (result is null || location.Line < result.Value.Line))
                {
                    result = location;
                }
            }
        }

        return result;
    }

    private (TypeElementKind Kind, bool IsRecord) ComputeKind()
    {
        var reader = Image.Reader;
        var definition = reader.GetTypeDefinition(Handle);
        if (_attributes.HasFlag(TypeAttributes.Interface))
            return (TypeElementKind.Interface, false);

        var baseTypeName = definition.BaseType.IsNil ? string.Empty : MetadataNames.GetFullName(reader, definition.BaseType);
        var kind = baseTypeName switch
        {
            "System.Enum" => TypeElementKind.Enum,
            "System.ValueType" when FullName is not "System.Enum" => TypeElementKind.Struct,
            "System.MulticastDelegate" => TypeElementKind.Delegate,
            _ => TypeElementKind.Class,
        };

        var isRecord = false;
        if (kind is TypeElementKind.Class or TypeElementKind.Struct)
        {
            foreach (var methodHandle in definition.GetMethods())
            {
                var method = reader.GetMethodDefinition(methodHandle);
                var name = reader.GetString(method.Name);
                if ((kind == TypeElementKind.Class && name is "<Clone>$")
                    || (kind == TypeElementKind.Struct && name is "PrintMembers" && MetadataNames.HasAttribute(reader, method.GetCustomAttributes(), "System.Runtime.CompilerServices.CompilerGeneratedAttribute")))
                {
                    isRecord = true;
                    break;
                }
            }
        }

        return (kind, isRecord);
    }

    private (IReadOnlyList<string> BaseTypes, HashSet<string> Interfaces) ComputeHierarchy()
    {
        var resolver = Architecture.Resolver;
        var baseTypes = new List<string>();
        var interfaces = new HashSet<string>(StringComparer.Ordinal);
        var visitedInterfaces = new HashSet<string>(StringComparer.Ordinal);

        ResolvedTypeDefinition? current = new ResolvedTypeDefinition(Image, Handle);
        for (var depth = 0; current is { } type && depth < MaxHierarchyDepth; depth++)
        {
            var reader = type.Image.Reader;
            var definition = reader.GetTypeDefinition(type.Handle);
            AddInterfaces(type, depth: 0);
            if (definition.BaseType.IsNil)
                break;

            baseTypes.Add(MetadataNames.GetFullName(reader, definition.BaseType));
            current = resolver.Resolve(type.Image, definition.BaseType);
        }

        return (baseTypes, interfaces);

        void AddInterfaces(ResolvedTypeDefinition type, int depth)
        {
            if (depth > MaxHierarchyDepth)
                return;

            var reader = type.Image.Reader;
            foreach (var handle in reader.GetTypeDefinition(type.Handle).GetInterfaceImplementations())
            {
                var interfaceHandle = reader.GetInterfaceImplementation(handle).Interface;
                var name = MetadataNames.GetFullName(reader, interfaceHandle);
                interfaces.Add(name);
                if (visitedInterfaces.Add(name) && resolver.Resolve(type.Image, interfaceHandle) is { } resolved)
                {
                    AddInterfaces(resolved, depth + 1);
                }
            }
        }
    }

    private SourceLocation? ComputeLocation()
    {
        SourceLocation? result = null;
        foreach (var member in Members)
        {
            if (member.Location is not { } location)
                continue;

            if (result is null)
            {
                result = location;
            }
            else if (string.Equals(location.FilePath, result.Value.FilePath, StringComparison.Ordinal) && location.Line < result.Value.Line)
            {
                result = location;
            }
        }

        return result;
    }

    private sealed class TypeMembers
    {
        private readonly Dictionary<MethodDefinitionHandle, MemberElement> _sourceMembers = [];
        private readonly Dictionary<string, MemberElement> _membersByMethodName = new(StringComparer.Ordinal);
        private readonly Dictionary<FieldDefinitionHandle, FieldElement> _fields = [];
        private readonly Dictionary<MethodDefinitionHandle, MethodElement> _accessors = [];
        private readonly Dictionary<string, MethodElement> _accessorsByName = new(StringComparer.Ordinal);

        public TypeMembers(TypeElement type)
        {
            var reader = type.Image.Reader;
            var definition = reader.GetTypeDefinition(type.Handle);

            var methodElements = new Dictionary<MethodDefinitionHandle, MethodElement>();
            foreach (var handle in definition.GetMethods())
            {
                var name = reader.GetString(reader.GetMethodDefinition(handle).Name);
                if (!MetadataNames.IsCompilerGeneratedMemberName(name))
                {
                    methodElements.Add(handle, new MethodElement(type, handle));
                }
            }

            var accessors = new HashSet<MethodDefinitionHandle>();
            var properties = new List<PropertyElement>();
            foreach (var handle in definition.GetProperties())
            {
                var propertyAccessors = reader.GetPropertyDefinition(handle).GetAccessors();
                var property = new PropertyElement(type, handle, GetMethod(propertyAccessors.Getter), GetMethod(propertyAccessors.Setter));
                properties.Add(property);
                AddAccessor(propertyAccessors.Getter, property);
                AddAccessor(propertyAccessors.Setter, property);
                foreach (var other in propertyAccessors.Others)
                {
                    AddAccessor(other, property);
                }
            }

            var events = new List<EventElement>();
            foreach (var handle in definition.GetEvents())
            {
                var eventAccessors = reader.GetEventDefinition(handle).GetAccessors();
                var @event = new EventElement(type, handle, GetMethod(eventAccessors.Adder), GetMethod(eventAccessors.Remover));
                events.Add(@event);
                AddAccessor(eventAccessors.Adder, @event);
                AddAccessor(eventAccessors.Remover, @event);
                AddAccessor(eventAccessors.Raiser, @event);
                foreach (var other in eventAccessors.Others)
                {
                    AddAccessor(other, @event);
                }
            }

            var constructors = new List<MethodElement>();
            var methods = new List<MethodElement>();
            foreach (var (handle, method) in methodElements)
            {
                if (accessors.Contains(handle))
                    continue;

                (method.IsConstructor ? constructors : methods).Add(method);
                _sourceMembers.Add(handle, method);
                _membersByMethodName.TryAdd(method.Name, method);
            }

            var fields = new List<FieldElement>();
            foreach (var handle in definition.GetFields())
            {
                var name = reader.GetString(reader.GetFieldDefinition(handle).Name);
                if (MetadataNames.IsGeneratedName(name))
                    continue;

                var field = new FieldElement(type, handle);
                fields.Add(field);
                _fields.Add(handle, field);
            }

            Constructors = constructors;
            Methods = methods;
            Properties = properties;
            Fields = fields;
            Events = events;
            All = [.. constructors, .. methods, .. properties, .. fields, .. events];

            MethodElement? GetMethod(MethodDefinitionHandle handle) => !handle.IsNil && methodElements.TryGetValue(handle, out var method) ? method : null;

            void AddAccessor(MethodDefinitionHandle handle, MemberElement member)
            {
                if (handle.IsNil)
                    return;

                accessors.Add(handle);
                _sourceMembers.TryAdd(handle, member);
                if (GetMethod(handle) is { } accessor && _accessors.TryAdd(handle, accessor))
                {
                    accessor.AccessorOwner = member;
                    _accessorsByName.TryAdd(accessor.Name, accessor);
                }

                _membersByMethodName.TryAdd(reader.GetString(reader.GetMethodDefinition(handle).Name), member);
            }
        }

        public IReadOnlyList<MethodElement> Constructors { get; }

        public IReadOnlyList<MethodElement> Methods { get; }

        public IReadOnlyList<PropertyElement> Properties { get; }

        public IReadOnlyList<FieldElement> Fields { get; }

        public IReadOnlyList<EventElement> Events { get; }

        public IReadOnlyList<MemberElement> All { get; }

        public MemberElement? GetSourceMember(MethodDefinitionHandle handle) => _sourceMembers.GetValueOrDefault(handle);

        public MemberElement? FindByMethodName(string name) => _membersByMethodName.GetValueOrDefault(name);

        public FieldElement? GetField(FieldDefinitionHandle handle) => _fields.GetValueOrDefault(handle);

        public MethodElement? GetAccessor(MethodDefinitionHandle handle) => _accessors.GetValueOrDefault(handle);

        public MethodElement? FindAccessorByMethodName(string name) => _accessorsByName.GetValueOrDefault(name);
    }
}
