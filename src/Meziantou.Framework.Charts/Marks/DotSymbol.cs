namespace Meziantou.Framework.Charts;

/// <summary>The shape of the dots of a <see cref="DotMark{T}"/>. The shapes have about the same area for a radius.</summary>
public enum DotSymbol
{
    /// <summary>A circle.</summary>
    Circle,

    /// <summary>A square.</summary>
    Square,

    /// <summary>A triangle pointing up.</summary>
    Triangle,

    /// <summary>A square rotated by 45 degrees.</summary>
    Diamond,

    /// <summary>A plus sign.</summary>
    Cross,
}
