namespace Meziantou.Framework.Diagrams;

/// <summary>A unit of time of a Gantt chart.</summary>
public enum GanttTimeUnit
{
    /// <summary>A millisecond (Mermaid <c>ms</c>).</summary>
    Millisecond,

    /// <summary>A second (Mermaid <c>s</c>).</summary>
    Second,

    /// <summary>A minute (Mermaid <c>m</c>).</summary>
    Minute,

    /// <summary>An hour (Mermaid <c>h</c>).</summary>
    Hour,

    /// <summary>A day (Mermaid <c>d</c>).</summary>
    Day,

    /// <summary>A week (Mermaid <c>w</c>).</summary>
    Week,

    /// <summary>A month (Mermaid <c>M</c>).</summary>
    Month,

    /// <summary>A year (Mermaid <c>y</c>).</summary>
    Year,
}
