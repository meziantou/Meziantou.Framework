using System.Collections.Immutable;
using System.Reflection;
using Meziantou.Framework.Collections;
using Meziantou.Framework.Roslyn;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Meziantou.Framework.FastEnumGenerator;

[Generator]
public sealed class FastEnumSourceGenerator : IIncrementalGenerator
{
    private static readonly string GeneratorVersion = GetGeneratorVersion();

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static context =>
        {
            context.AddSource("Microsoft.CodeAnalysis.EmbeddedAttribute.g.cs", SourceText.From($$"""
                // <auto-generated/>
                #pragma warning disable
                namespace Microsoft.CodeAnalysis
                {
                    [global::System.Runtime.CompilerServices.CompilerGenerated]
                    [global::System.CodeDom.Compiler.GeneratedCode("Meziantou.Framework.FastEnumGenerator", "{{GeneratorVersion}}")]
                    internal sealed partial class EmbeddedAttribute : global::System.Attribute
                    {
                    }
                }
                """, encoding: Encoding.UTF8));

            context.AddSource("Meziantou.Framework.Annotations.FastEnumAttribute.g.cs", SourceText.From($$"""
                // <auto-generated/>
                #pragma warning disable
                namespace Meziantou.Framework.Annotations
                {
                    [global::Microsoft.CodeAnalysis.Embedded]
                    [global::System.Runtime.CompilerServices.CompilerGenerated]
                    [global::System.CodeDom.Compiler.GeneratedCode("Meziantou.Framework.FastEnumGenerator", "{{GeneratorVersion}}")]
                    [global::System.Diagnostics.Conditional("FastEnum_Attributes")]
                    [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = true)]
                    internal sealed class FastEnumAttribute : global::System.Attribute
                    {
                        public FastEnumAttribute(global::System.Type enumType)
                        {
                            EnumType = enumType;
                        }

                        public bool IsPublic { get; set; } = true;

                        public string? ExtensionMethodNamespace { get; set; }

                        public global::System.Type EnumType { get; }
                    }

                }
                """, encoding: Encoding.UTF8));
        });

        // ForAttributeWithMetadataName lets the driver do the attribute-name filtering instead of
        // running a semantic transform over every attribute application in the compilation.
        var enums = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                FastEnumAnalyzerCommon.FastEnumAttributeMetadataName,
                predicate: static (_, _) => true,
                transform: static (ctx, cancellationToken) => GetEnumsToProcess(ctx, cancellationToken))
            .SelectMany(static (items, _) => items);

        // Only the language version is needed, so depend on the parse options rather than the whole
        // compilation, which is invalidated on every edit.
        var languageFeatures = context.ParseOptionsProvider.Select(static (options, _) =>
        {
            var languageVersion = options.GetCSharpLanguageVersion();
            return new LanguageFeatures(languageVersion.IsCSharp12OrGreater(), languageVersion.IsCSharp14OrGreater());
        });

        // Interceptors rewrite call sites in place, so they only run when the project opts in.
        var interceptorsEnabled = context.AnalyzerConfigOptionsProvider
            .Select(static (provider, _) => provider.GlobalOptions.TryGetValue("build_property.MeziantouFastEnumInterceptors", out var value) && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase))
            .Combine(languageFeatures)
            .Select(static (item, _) => item.Left && item.Right.SupportsInterceptors);

        var generationInput = enums.Collect().Combine(languageFeatures).Combine(interceptorsEnabled);
        context.RegisterSourceOutput(generationInput, static (spc, source) => GenerateCode(spc, source.Left.Left, source.Left.Right.SupportsExtensionMembers, source.Right));

        var interceptionCandidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsInterceptionCandidateSyntax(node),
                transform: static (ctx, cancellationToken) => GetInterceptionCandidate(ctx, cancellationToken))
            .Where(static candidate => candidate is not null)
            .Select(static (candidate, _) => candidate!);

        var interceptionInput = enums.Collect().Combine(interceptionCandidates.Collect()).Combine(interceptorsEnabled);
        context.RegisterSourceOutput(interceptionInput, static (spc, source) => GenerateInterceptors(spc, source.Left.Left, source.Left.Right, source.Right));
    }

    /// <summary>
    /// Cheap syntactic filter so the semantic model is only asked about invocations that could possibly
    /// be one of the intercepted <see cref="Enum"/> calls.
    /// </summary>
    private static bool IsInterceptionCandidateSyntax(SyntaxNode node)
    {
        if (node is not InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax memberAccess } invocation)
            return false;

        return memberAccess.Name.Identifier.ValueText switch
        {
            nameof(object.ToString) => invocation.ArgumentList.Arguments.Count == 0,
            nameof(Enum.HasFlag) => invocation.ArgumentList.Arguments.Count == 1,
            nameof(Enum.IsDefined) or nameof(Enum.GetName) => invocation.ArgumentList.Arguments.Count == 1,
            nameof(Enum.GetNames) or nameof(Enum.GetValues) => invocation.ArgumentList.Arguments.Count == 0,
            _ => false,
        };
    }

    private static InterceptionCandidate? GetInterceptionCandidate(GeneratorSyntaxContext ctx, CancellationToken cancellationToken)
    {
        var invocation = (InvocationExpressionSyntax)ctx.Node;
        var memberAccess = (MemberAccessExpressionSyntax)invocation.Expression;

        if (ctx.SemanticModel.GetSymbolInfo(invocation, cancellationToken).Symbol is not IMethodSymbol method)
            return null;

        INamedTypeSymbol enumType;
        FastEnumInterceptKind kind;

        if (method.IsStatic)
        {
            if (method.ContainingType?.SpecialType is not SpecialType.System_Enum)
                return null;

            // Only the generic overloads are intercepted: the Type-based ones return object/Array and
            // would need a different signature.
            if (!method.IsGenericMethod || method.TypeArguments.Length != 1 || method.TypeArguments[0] is not INamedTypeSymbol { TypeKind: TypeKind.Enum } typeArgument)
                return null;

            enumType = typeArgument;
            kind = method.Name switch
            {
                nameof(Enum.IsDefined) when method.Parameters.Length == 1 => FastEnumInterceptKind.IsDefined,
                nameof(Enum.GetName) when method.Parameters.Length == 1 => FastEnumInterceptKind.GetName,
                nameof(Enum.GetNames) when method.Parameters.Length == 0 => FastEnumInterceptKind.GetNames,
                nameof(Enum.GetValues) when method.Parameters.Length == 0 => FastEnumInterceptKind.GetValues,
                _ => FastEnumInterceptKind.None,
            };
        }
        else
        {
            // ToString resolves to System.Enum's override; HasFlag is declared on System.Enum.
            if (method.ContainingType?.SpecialType is not (SpecialType.System_Enum or SpecialType.System_Object))
                return null;

            if (ctx.SemanticModel.GetTypeInfo(memberAccess.Expression, cancellationToken).Type is not INamedTypeSymbol { TypeKind: TypeKind.Enum } receiverType)
                return null;

            enumType = receiverType;
            kind = method.Name switch
            {
                nameof(object.ToString) when method.Parameters.Length == 0 => FastEnumInterceptKind.ToString,
                nameof(Enum.HasFlag) when method.Parameters.Length == 1 => FastEnumInterceptKind.HasFlag,
                _ => FastEnumInterceptKind.None,
            };
        }

        if (kind is FastEnumInterceptKind.None)
            return null;

        var location = ctx.SemanticModel.GetInterceptableLocation(invocation, cancellationToken);
        if (location is null)
            return null;

        return new InterceptionCandidate(enumType.ToDisplayString(), kind, location.GetInterceptsLocationAttributeSyntax());
    }

    private static string GetGeneratorVersion()
    {
        var assembly = typeof(FastEnumSourceGenerator).Assembly;
        var informationalVersion = assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;
        if (!string.IsNullOrEmpty(informationalVersion))
        {
            // Strip the SemVer build metadata (e.g. "3.0.2+abcdef") so the value stays stable across builds.
            var separatorIndex = informationalVersion.IndexOf("+", StringComparison.Ordinal);
            return separatorIndex < 0 ? informationalVersion : informationalVersion.Substring(0, separatorIndex);
        }

        return assembly.GetName().Version?.ToString() ?? "0.0.0.0";
    }

    private static ImmutableEquatableArray<EnumToProcess> GetEnumsToProcess(GeneratorAttributeSyntaxContext ctx, CancellationToken cancellationToken)
    {
        var flagsAttributeSymbol = ctx.SemanticModel.Compilation.GetTypeByMetadataName("System.FlagsAttribute");
        var builder = ImmutableArray.CreateBuilder<EnumToProcess>();

        foreach (var attribute in ctx.Attributes)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (attribute.ConstructorArguments.Length != 1)
                continue;

            if (attribute.ConstructorArguments[0].Value is not INamedTypeSymbol enumType)
                continue;

            if (!FastEnumAnalyzerCommon.IsSupportedEnumType(enumType))
                continue;

            var members = GetMembers(enumType);
            if (members.Length == 0)
                continue;

            var isPublic = GetIsPublic(attribute, enumType);
            var extensionNamespace = GetExtensionNamespace(attribute);
            var isFlags = flagsAttributeSymbol is not null &&
                          enumType.GetAttributes().Any(item => SymbolEqualityComparer.Default.Equals(item.AttributeClass, flagsAttributeSymbol));
            var isZeroBasedConsecutive = !isFlags && IsZeroBasedConsecutive(members);
            var enumUnderlyingType = enumType.EnumUnderlyingType;
            var underlyingType = enumUnderlyingType?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) ?? "global::System.Int32";
            var isUnderlyingTypeSigned = enumUnderlyingType is not null && IsSignedIntegralType(enumUnderlyingType.SpecialType);
            var fullCsharpName = enumType.ToDisplayString();

            builder.Add(new EnumToProcess(
                fullCsharpName,
                extensionNamespace ?? GetNamespace(enumType),
                ImmutableEquatableArray.Create(members),
                isPublic,
                isFlags,
                isZeroBasedConsecutive,
                underlyingType,
                isUnderlyingTypeSigned,
                CreateNameToken(fullCsharpName)));
        }

        return ImmutableEquatableArray.Create(builder.ToImmutable());
    }

    /// <summary>
    /// Builds a stable, unique suffix for the generated class from the enum's identity. Using the enum's
    /// position instead would rename the generated types whenever another enum is added, which is a
    /// binary-breaking change for assemblies already compiled against them.
    /// </summary>
    private static string CreateNameToken(string fullCsharpName)
    {
        var sb = new StringBuilder(fullCsharpName.Length + 9);
        foreach (var c in fullCsharpName)
        {
            sb.Append(char.IsLetterOrDigit(c) ? c : '_');
        }

        // The sanitization is lossy ("A.B" and "A_B" collapse), so append a hash of the original name.
        sb.Append('_').Append(ComputeStableHash(fullCsharpName).ToString("x8", CultureInfo.InvariantCulture));
        return sb.ToString();
    }

    private static uint ComputeStableHash(string value)
    {
        // FNV-1a. Must not use string.GetHashCode, which is randomized per process.
        var hash = 2166136261;
        foreach (var c in value)
        {
            hash = unchecked((hash ^ c) * 16777619);
        }

        return hash;
    }

    private static ImmutableArray<EnumMemberToProcess> GetMembers(INamedTypeSymbol enumType)
    {
        var members = ImmutableArray.CreateBuilder<EnumMemberToProcess>();
        foreach (var member in enumType.GetMembers())
        {
            if (member is not IFieldSymbol field || field.ConstantValue is null)
                continue;

            members.Add(new EnumMemberToProcess(field.Name, EscapeIdentifier(field.Name), ConvertToUInt64(field.ConstantValue), GetMetadataName(field)));
        }

        // Enum.GetNames/GetValues order by the underlying value, keeping declaration order for aliases.
        // The generated GetNames/GetValues are advertised as replacements, so they must match.
        return [.. members.OrderBy(static member => member.UInt64Value)];
    }

    /// <summary>Enum members may be named after C# keywords (<c>@class</c>), which must stay escaped when referenced.</summary>
    private static string EscapeIdentifier(string name)
    {
        var kind = SyntaxFacts.GetKeywordKind(name);
        if (kind is SyntaxKind.None)
            return name;

        return "@" + name;
    }

    private static bool GetIsPublic(AttributeData attr, INamedTypeSymbol enumType)
    {
        var isPublic = enumType.IsVisibleOutsideOfAssembly();
        foreach (var argument in attr.NamedArguments)
        {
            if (argument is { Key: "IsPublic", Value.Value: bool value })
                return isPublic && value;
        }

        return isPublic;
    }

    private static string? GetExtensionNamespace(AttributeData attr)
    {
        foreach (var argument in attr.NamedArguments)
        {
            if (argument is { Key: "ExtensionMethodNamespace", Value.Value: string value })
                return value;
        }

        return null;
    }

    private static string? GetNamespace(ITypeSymbol symbol)
    {
        string? result = null;
        var ns = symbol.ContainingNamespace;
        while (ns is not null && !ns.IsGlobalNamespace)
        {
            result = result is null ? ns.Name : ns.Name + "." + result;
            ns = ns.ContainingNamespace;
        }

        return result;
    }

    private static string? GetMetadataName(IFieldSymbol field)
    {
        foreach (var attribute in field.GetAttributes())
        {
            if (!string.Equals(attribute.AttributeClass?.ToDisplayString(), "System.ComponentModel.DataAnnotations.DisplayAttribute", StringComparison.Ordinal))
                continue;

            foreach (var namedArgument in attribute.NamedArguments)
            {
                if (namedArgument is { Key: "Name", Value.Value: string value } && !string.IsNullOrEmpty(value))
                    return value;
            }
        }

        foreach (var attribute in field.GetAttributes())
        {
            if (!string.Equals(attribute.AttributeClass?.ToDisplayString(), "System.ComponentModel.DisplayNameAttribute", StringComparison.Ordinal))
                continue;

            if (attribute.ConstructorArguments is [{ Value: string value }] && !string.IsNullOrEmpty(value))
                return value;
        }

        foreach (var attribute in field.GetAttributes())
        {
            if (!string.Equals(attribute.AttributeClass?.ToDisplayString(), "System.Runtime.Serialization.EnumMemberAttribute", StringComparison.Ordinal))
                continue;

            foreach (var namedArgument in attribute.NamedArguments)
            {
                if (namedArgument is { Key: "Value", Value.Value: string value } && !string.IsNullOrEmpty(value))
                    return value;
            }
        }

        return null;
    }

    private static bool IsSignedIntegralType(SpecialType specialType)
    {
        return specialType is SpecialType.System_SByte or SpecialType.System_Int16 or SpecialType.System_Int32 or SpecialType.System_Int64;
    }

    private static ulong ConvertToUInt64(object value)
    {
        return value switch
        {
            byte byteValue => byteValue,
            sbyte sbyteValue => unchecked((ulong)sbyteValue),
            short shortValue => unchecked((ulong)shortValue),
            ushort ushortValue => ushortValue,
            int intValue => unchecked((ulong)intValue),
            uint uintValue => uintValue,
            long longValue => unchecked((ulong)longValue),
            ulong ulongValue => ulongValue,
            _ => 0,
        };
    }

    private static bool IsZeroBasedConsecutive(ImmutableArray<EnumMemberToProcess> members)
    {
        var values = new HashSet<ulong>();
        foreach (var member in members)
        {
            _ = values.Add(member.UInt64Value);
        }

        if (!values.Contains(0))
            return false;

        var count = values.Count;
        for (ulong i = 0; i < (ulong)count; i++)
        {
            if (!values.Contains(i))
                return false;
        }

        return true;
    }

    private static void GenerateCode(SourceProductionContext context, ImmutableArray<EnumToProcess> enumToProcess, bool supportsExtensionMembers, bool interceptorsEnabled)
    {
        if (enumToProcess.Length == 0)
            return;

        // The attribute is AllowMultiple, so the same enum can be registered twice. Emitting it twice
        // produces two classes with identical members and makes every call site ambiguous (CS0121).
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var enums = new List<EnumToProcess>(enumToProcess.Length);
        foreach (var enumeration in enumToProcess)
        {
            if (seen.Add(enumeration.FullNamespace + "|" + enumeration.FullCsharpName))
            {
                enums.Add(enumeration);
            }
        }

        foreach (var enumeration in enums.OrderBy(static item => item.FullNamespace, StringComparer.Ordinal).ThenBy(static item => item.FullCsharpName, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();

            var sb = new StringBuilder(4096);
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine("#nullable enable");
            AppendEnumCode(sb, enumeration, supportsExtensionMembers, interceptorsEnabled, context.CancellationToken);

            // One file per enum keeps unchanged enums byte-identical when another enum is added or edited.
            context.AddSource("FastEnumExtensions." + enumeration.NameToken + ".g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }

    private static void GenerateInterceptors(SourceProductionContext context, ImmutableArray<EnumToProcess> enumToProcess, ImmutableArray<InterceptionCandidate> candidates, bool interceptorsEnabled)
    {
        if (!interceptorsEnabled || candidates.Length == 0 || enumToProcess.Length == 0)
            return;

        var enums = new Dictionary<string, EnumToProcess>(StringComparer.Ordinal);
        foreach (var enumeration in enumToProcess)
        {
            if (!enums.ContainsKey(enumeration.FullCsharpName))
            {
                enums.Add(enumeration.FullCsharpName, enumeration);
            }
        }

        // A call site can be reported once per compilation pass, and the same enum may be called from
        // many places, so group by enum then by kind and drop duplicate locations.
        var grouped = new SortedDictionary<string, SortedDictionary<FastEnumInterceptKind, SortedSet<string>>>(StringComparer.Ordinal);
        foreach (var candidate in candidates)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            if (!enums.ContainsKey(candidate.EnumFullName))
                continue;

            if (!grouped.TryGetValue(candidate.EnumFullName, out var byKind))
            {
                byKind = new SortedDictionary<FastEnumInterceptKind, SortedSet<string>>();
                grouped.Add(candidate.EnumFullName, byKind);
            }

            if (!byKind.TryGetValue(candidate.Kind, out var locations))
            {
                locations = new SortedSet<string>(StringComparer.Ordinal);
                byKind.Add(candidate.Kind, locations);
            }

            _ = locations.Add(candidate.InterceptsLocationAttribute);
        }

        if (grouped.Count == 0)
            return;

        var sb = new StringBuilder(4096);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        // File-scoped so it cannot collide with another generator's or the consumer's declaration.
        sb.AppendLine("namespace System.Runtime.CompilerServices");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
        sb.AppendLine("    file sealed class InterceptsLocationAttribute : global::System.Attribute");
        sb.AppendLine("    {");
        sb.AppendLine("        public InterceptsLocationAttribute(int version, string data)");
        sb.AppendLine("        {");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        sb.AppendLine("namespace Meziantou.Framework.Annotations.FastEnumInterceptors");
        sb.AppendLine("{");

        foreach (var pair in grouped)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            AppendInterceptorClass(sb, enums[pair.Key], pair.Value);
        }

        sb.AppendLine("}");
        context.AddSource("FastEnumInterceptors.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void AppendInterceptorClass(StringBuilder sb, EnumToProcess enumeration, SortedDictionary<FastEnumInterceptKind, SortedSet<string>> byKind)
    {
        var token = enumeration.NameToken;
        var enumTypeName = "global::" + enumeration.FullCsharpName;
        var extensions = string.IsNullOrEmpty(enumeration.FullNamespace)
            ? "global::FastEnumExtensions_" + token
            : "global::" + enumeration.FullNamespace + ".FastEnumExtensions_" + token;

        sb.Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"Meziantou.Framework.FastEnumGenerator\", ").Append(ToLiteral(GeneratorVersion)).AppendLine(")]");
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.Append("    internal static class FastEnumInterceptors_").Append(token).AppendLine();
        sb.AppendLine("    {");

        foreach (var pair in byKind)
        {
            foreach (var location in pair.Value)
            {
                sb.Append("        ").AppendLine(location);
            }

            switch (pair.Key)
            {
                case FastEnumInterceptKind.ToString:
                    // The intercepted method is declared on System.Enum, so the receiver must be typed as
                    // System.Enum (CS9148). The call site already boxes for Enum.ToString today.
                    sb.AppendLine("        public static string ToStringFast(this global::System.Enum value)");
                    sb.AppendLine("        {");
                    sb.Append("            return ").Append(extensions).Append(".ToStringFast((").Append(enumTypeName).AppendLine(")value);");
                    sb.AppendLine("        }");
                    break;

                case FastEnumInterceptKind.HasFlag:
                    sb.AppendLine("        public static bool HasFlagFast(this global::System.Enum value, global::System.Enum flag)");
                    sb.AppendLine("        {");
                    sb.AppendLine("            if (flag is null)");
                    sb.AppendLine("                throw new global::System.ArgumentNullException(nameof(flag));");
                    sb.AppendLine();
                    // Enum.HasFlag rejects a flag of a different enum type; keep that behavior.
                    sb.Append("            if (flag is not ").Append(enumTypeName).AppendLine(" typedFlag)");
                    sb.Append("                throw new global::System.ArgumentException(\"The argument type must be ").Append(enumeration.FullCsharpName).AppendLine(".\", nameof(flag));");
                    sb.AppendLine();
                    sb.Append("            return ").Append(extensions).Append(".HasFlagFast((").Append(enumTypeName).AppendLine(")value, typedFlag);");
                    sb.AppendLine("        }");
                    break;

                case FastEnumInterceptKind.IsDefined:
                    sb.Append("        public static bool IsDefinedFast(").Append(enumTypeName).AppendLine(" value)");
                    sb.AppendLine("        {");
                    sb.Append("            return ").Append(extensions).Append(".IsDefinedCore_").Append(token).AppendLine("(value);");
                    sb.AppendLine("        }");
                    break;

                case FastEnumInterceptKind.GetName:
                    sb.Append("        public static string? GetNameFast(").Append(enumTypeName).AppendLine(" value)");
                    sb.AppendLine("        {");
                    sb.Append("            return ").Append(extensions).AppendLine(".GetName(value);");
                    sb.AppendLine("        }");
                    break;

                case FastEnumInterceptKind.GetNames:
                    sb.AppendLine("        public static string[] GetNamesFast()");
                    sb.AppendLine("        {");
                    sb.Append("            return ").Append(extensions).Append(".GetNamesArray_").Append(token).AppendLine("(useMetadata: false);");
                    sb.AppendLine("        }");
                    break;

                case FastEnumInterceptKind.GetValues:
                    sb.Append("        public static ").Append(enumTypeName).AppendLine("[] GetValuesFast()");
                    sb.AppendLine("        {");
                    sb.Append("            return ").Append(extensions).Append(".GetValuesArray_").Append(token).AppendLine("();");
                    sb.AppendLine("        }");
                    break;
            }

            sb.AppendLine();
        }

        sb.AppendLine("    }");
    }

    private static void AppendEnumCode(StringBuilder sb, EnumToProcess enumeration, bool supportsExtensionMembers, bool interceptorsEnabled, CancellationToken cancellationToken)
    {
        var visibility = enumeration.IsPublic ? "public" : "internal";
        var enumTypeName = "global::" + enumeration.FullCsharpName;
        var token = enumeration.NameToken;
        var members = enumeration.Members;

        var uniqueMembers = GetUniqueMembers(members);
        var hasDistinctMetadata = members.Any(static item => item.MetadataName is not null && !string.Equals(item.MetadataName, item.Name, StringComparison.Ordinal));
        var denseMembers = enumeration.IsZeroBasedConsecutive ? uniqueMembers : [];
        var canUseMainArraysForDenseLookup = denseMembers.Count > 0 && IsDenseMembersAligned(members);
        var denseNamesArrayName = canUseMainArraysForDenseLookup ? "s_names_" + token : "s_definedNames_" + token;
        var denseMetadataNamesArrayName = canUseMainArraysForDenseLookup ? "s_metadataNames_" + token : "s_definedMetadataNames_" + token;

        // Enum.ToString decomposes a flags value using every defined non-zero member, largest first.
        var flagMembers = enumeration.IsFlags
            ? uniqueMembers.Where(static item => item.UInt64Value != 0).OrderByDescending(static item => item.UInt64Value).ToList()
            : [];
        var emitFlagsFormatting = flagMembers.Count > 0;

        var needsNamesArray = supportsExtensionMembers || interceptorsEnabled || (denseMembers.Count > 0 && canUseMainArraysForDenseLookup);
        var needsMetadataNamesArray = supportsExtensionMembers || interceptorsEnabled;
        var needsValuesArray = supportsExtensionMembers || interceptorsEnabled;
        var needsToUInt64Helper = emitFlagsFormatting || (enumeration.IsFlags && supportsExtensionMembers);
        var needsFromUInt64Helper = enumeration.IsFlags && supportsExtensionMembers;

        if (!string.IsNullOrEmpty(enumeration.FullNamespace))
        {
            sb.Append("namespace ").Append(enumeration.FullNamespace).AppendLine();
            sb.AppendLine("{");
        }

        sb.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Meziantou.Framework.FastEnumGenerator\", ").Append(ToLiteral(GeneratorVersion)).AppendLine(")]");
        sb.AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.Append(visibility).Append(" static class FastEnumExtensions_").Append(token).AppendLine();
        sb.AppendLine("{");

        AppendMemberArrays(sb, enumTypeName, token, members, needsNamesArray, needsMetadataNamesArray, needsValuesArray);
        if (denseMembers.Count > 0 && !canUseMainArraysForDenseLookup)
        {
            AppendDenseArrays(sb, denseMembers, token, hasDistinctMetadata);
        }

        if (emitFlagsFormatting)
        {
            AppendFlagsArrays(sb, flagMembers, token, hasDistinctMetadata);
        }

        sb.Append("    ").Append(visibility).Append(" static string ToStringFast(this ").Append(enumTypeName).AppendLine(" value)");
        sb.AppendLine("    {");
        sb.AppendLine("        return ToStringFast(value, useMetadata: false);");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.Append("    ").Append(visibility).Append(" static string ToStringFast(this ").Append(enumTypeName).AppendLine(" value, bool useMetadata)");
        sb.AppendLine("    {");
        sb.Append("        var name = GetNameCore_").Append(token).AppendLine("(value, useMetadata);");
        sb.AppendLine("        if (name is not null)");
        sb.AppendLine("            return name;");
        sb.AppendLine();
        if (emitFlagsFormatting)
        {
            sb.Append("        name = FormatFlagsName_").Append(token).AppendLine("(value, useMetadata);");
            sb.AppendLine("        if (name is not null)");
            sb.AppendLine("            return name;");
            sb.AppendLine();
        }

        sb.Append("        return FormatNumeric_").Append(token).AppendLine("(value);");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.Append("    ").Append(visibility).Append(" static bool HasFlagFast(this ").Append(enumTypeName).Append(" instance, ").Append(enumTypeName).AppendLine(" flag)");
        sb.AppendLine("    {");
        sb.AppendLine("        return (instance & flag) == flag;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Matches Enum.GetName, which returns null for a value that is not a declared member.
        sb.Append("    ").Append(visibility).Append(" static string? GetName(this ").Append(enumTypeName).AppendLine(" instance)");
        sb.AppendLine("    {");
        sb.Append("        return GetNameCore_").Append(token).AppendLine("(instance, useMetadata: false);");
        sb.AppendLine("    }");
        sb.AppendLine();

        AppendGetNameCore(sb, enumTypeName, token, uniqueMembers, denseMembers, denseNamesArrayName, denseMetadataNamesArrayName, hasDistinctMetadata, cancellationToken);
        AppendFormatNumeric(sb, enumTypeName, enumeration, token);

        if (denseMembers.Count > 0)
        {
            AppendTryGetDenseIndex(sb, enumTypeName, enumeration, token, denseNamesArrayName);
        }

        if (needsToUInt64Helper)
        {
            sb.Append("    private static ulong ToUInt64_").Append(token).Append('(').Append(enumTypeName).AppendLine(" value)");
            sb.AppendLine("    {");
            sb.Append("        return unchecked((ulong)((").Append(enumeration.UnderlyingTypeName).AppendLine(")value));");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        if (needsFromUInt64Helper)
        {
            sb.Append("    private static ").Append(enumTypeName).Append(" FromUInt64_").Append(token).AppendLine("(ulong value)");
            sb.AppendLine("    {");
            sb.Append("        return unchecked((").Append(enumTypeName).Append(")((").Append(enumeration.UnderlyingTypeName).AppendLine(")value));");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        if (emitFlagsFormatting)
        {
            AppendFormatFlagsName(sb, enumTypeName, token, hasDistinctMetadata);
        }

        if (supportsExtensionMembers || interceptorsEnabled)
        {
            AppendIsDefinedCore(sb, enumTypeName, token, uniqueMembers, denseMembers);
        }

        if (interceptorsEnabled)
        {
            AppendInterceptorAccessors(sb, enumTypeName, token, needsMetadataNamesArray);
        }

        if (supportsExtensionMembers)
        {
            AppendEqualsTokenHelper(sb, token);
            AppendTryParseHelpers(sb, enumTypeName, enumeration, token, hasDistinctMetadata, members, cancellationToken);
            AppendExtensionMembers(sb, enumTypeName, visibility, token, hasDistinctMetadata, needsMetadataNamesArray);
        }

        sb.AppendLine("}");
        if (!string.IsNullOrEmpty(enumeration.FullNamespace))
        {
            sb.AppendLine("}");
        }
    }

    private static void AppendGetNameCore(StringBuilder sb, string enumTypeName, string token, List<EnumMemberToProcess> uniqueMembers, List<EnumMemberToProcess> denseMembers, string denseNamesArrayName, string denseMetadataNamesArrayName, bool hasDistinctMetadata, CancellationToken cancellationToken)
    {
        sb.Append("    private static string? GetNameCore_").Append(token).Append('(').Append(enumTypeName).AppendLine(" value, bool useMetadata)");
        sb.AppendLine("    {");
        if (denseMembers.Count > 0)
        {
            sb.Append("        if (TryGetDenseIndex_").Append(token).AppendLine("(value, out var index))");
            sb.AppendLine("        {");
            if (hasDistinctMetadata)
            {
                sb.Append("            return useMetadata ? ").Append(denseMetadataNamesArrayName).Append("[index] : ").Append(denseNamesArrayName).AppendLine("[index];");
            }
            else
            {
                sb.Append("            return ").Append(denseNamesArrayName).AppendLine("[index];");
            }

            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        return null;");
        }
        else
        {
            sb.AppendLine("        switch (value)");
            sb.AppendLine("        {");
            foreach (var member in uniqueMembers)
            {
                cancellationToken.ThrowIfCancellationRequested();
                sb.Append("            case ").Append(enumTypeName).Append('.').Append(member.EscapedName).AppendLine(":");
                if (member.MetadataName is not null && !string.Equals(member.MetadataName, member.Name, StringComparison.Ordinal))
                {
                    sb.Append("                return useMetadata ? ").Append(ToLiteral(member.MetadataName)).Append(" : ").Append(ToLiteral(member.Name)).AppendLine(";");
                }
                else
                {
                    sb.Append("                return ").Append(ToLiteral(member.Name)).AppendLine(";");
                }
            }

            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        return null;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendFormatNumeric(StringBuilder sb, string enumTypeName, EnumToProcess enumeration, string token)
    {
        // Enum.ToString formats an undefined value as its underlying number using the invariant culture.
        // Formatting it directly avoids the reflection-based Enum.ToString entirely.
        sb.Append("    private static string FormatNumeric_").Append(token).Append('(').Append(enumTypeName).AppendLine(" value)");
        sb.AppendLine("    {");
        sb.Append("        return unchecked((").Append(enumeration.UnderlyingTypeName).AppendLine(")value).ToString(global::System.Globalization.CultureInfo.InvariantCulture);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendTryGetDenseIndex(StringBuilder sb, string enumTypeName, EnumToProcess enumeration, string token, string denseNamesArrayName)
    {
        sb.Append("    private static bool TryGetDenseIndex_").Append(token).Append('(').Append(enumTypeName).AppendLine(" value, out int index)");
        sb.AppendLine("    {");
        sb.Append("        var numericValue = unchecked((").Append(enumeration.UnderlyingTypeName).AppendLine(")value);");

        // Compare in ulong: narrowing Length to the underlying type wraps for enums with more members
        // than the underlying type can hold (a 256-member byte enum yields (byte)256 == 0).
        if (enumeration.IsUnderlyingTypeSigned)
        {
            sb.Append("        if (numericValue < 0 || (ulong)numericValue >= (ulong)").Append(denseNamesArrayName).AppendLine(".Length)");
        }
        else
        {
            sb.Append("        if ((ulong)numericValue >= (ulong)").Append(denseNamesArrayName).AppendLine(".Length)");
        }

        sb.AppendLine("        {");
        sb.AppendLine("            index = default;");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        index = unchecked((int)numericValue);");
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendIsDefinedCore(StringBuilder sb, string enumTypeName, string token, List<EnumMemberToProcess> uniqueMembers, List<EnumMemberToProcess> denseMembers)
    {
        sb.Append("    internal static bool IsDefinedCore_").Append(token).Append('(').Append(enumTypeName).AppendLine(" value)");
        sb.AppendLine("    {");
        if (denseMembers.Count > 0)
        {
            sb.Append("        return TryGetDenseIndex_").Append(token).AppendLine("(value, out _);");
        }
        else
        {
            sb.AppendLine("        return value switch");
            sb.AppendLine("        {");
            foreach (var member in uniqueMembers)
            {
                sb.Append("            ").Append(enumTypeName).Append('.').Append(member.EscapedName).AppendLine(" => true,");
            }

            sb.AppendLine("            _ => false,");
            sb.AppendLine("        };");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>
    /// Members the generated interceptors call. They are internal because the interceptors live in a
    /// dedicated namespace, and they clone so <c>Enum.GetNames</c>/<c>Enum.GetValues</c> keep returning a
    /// caller-owned array.
    /// </summary>
    private static void AppendInterceptorAccessors(StringBuilder sb, string enumTypeName, string token, bool hasMetadataNamesArray)
    {
        sb.Append("    internal static string[] GetNamesArray_").Append(token).AppendLine("(bool useMetadata)");
        sb.AppendLine("    {");
        if (hasMetadataNamesArray)
        {
            sb.Append("        return (string[])(useMetadata ? s_metadataNames_").Append(token).Append(" : s_names_").Append(token).AppendLine(").Clone();");
        }
        else
        {
            sb.Append("        return (string[])s_names_").Append(token).AppendLine(".Clone();");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        sb.Append("    internal static ").Append(enumTypeName).Append("[] GetValuesArray_").Append(token).AppendLine("()");
        sb.AppendLine("    {");
        sb.Append("        return (").Append(enumTypeName).Append("[])s_values_").Append(token).AppendLine(".Clone();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendMemberArrays(StringBuilder sb, string enumTypeName, string token, ImmutableEquatableArray<EnumMemberToProcess> members, bool needsNamesArray, bool needsMetadataNamesArray, bool needsValuesArray)
    {
        var emitted = false;
        if (needsNamesArray)
        {
            sb.Append("    private static readonly string[] s_names_").Append(token).Append(" = new string[] { ");
            AppendCommaSeparated(sb, members.Select(static member => ToLiteral(member.Name)));
            sb.AppendLine(" };");
            emitted = true;
        }

        if (needsMetadataNamesArray)
        {
            sb.Append("    private static readonly string[] s_metadataNames_").Append(token).Append(" = new string[] { ");
            AppendCommaSeparated(sb, members.Select(static member => ToLiteral(member.MetadataName ?? member.Name)));
            sb.AppendLine(" };");
            emitted = true;
        }

        if (needsValuesArray)
        {
            sb.Append("    private static readonly ").Append(enumTypeName).Append("[] s_values_").Append(token).Append(" = new ").Append(enumTypeName).Append("[] { ");
            AppendCommaSeparated(sb, members.Select(member => enumTypeName + "." + member.EscapedName));
            sb.AppendLine(" };");
            emitted = true;
        }

        if (emitted)
        {
            sb.AppendLine();
        }
    }

    private static void AppendDenseArrays(StringBuilder sb, List<EnumMemberToProcess> denseMembers, string token, bool hasDistinctMetadata)
    {
        sb.Append("    private static readonly string[] s_definedNames_").Append(token).Append(" = new string[] { ");
        AppendCommaSeparated(sb, denseMembers.Select(static member => ToLiteral(member.Name)));
        sb.AppendLine(" };");

        if (hasDistinctMetadata)
        {
            sb.Append("    private static readonly string[] s_definedMetadataNames_").Append(token).Append(" = new string[] { ");
            AppendCommaSeparated(sb, denseMembers.Select(static member => ToLiteral(member.MetadataName ?? member.Name)));
            sb.AppendLine(" };");
        }

        sb.AppendLine();
    }

    private static void AppendFlagsArrays(StringBuilder sb, List<EnumMemberToProcess> flagMembers, string token, bool hasDistinctMetadata)
    {
        sb.Append("    private static readonly ulong[] s_flagValues_").Append(token).Append(" = new ulong[] { ");
        AppendCommaSeparated(sb, flagMembers.Select(static member => ToUInt64Literal(member.UInt64Value)));
        sb.AppendLine(" };");

        sb.Append("    private static readonly string[] s_flagNames_").Append(token).Append(" = new string[] { ");
        AppendCommaSeparated(sb, flagMembers.Select(static member => ToLiteral(member.Name)));
        sb.AppendLine(" };");

        if (hasDistinctMetadata)
        {
            sb.Append("    private static readonly string[] s_flagMetadataNames_").Append(token).Append(" = new string[] { ");
            AppendCommaSeparated(sb, flagMembers.Select(static member => ToLiteral(member.MetadataName ?? member.Name)));
            sb.AppendLine(" };");
        }

        sb.AppendLine();
    }

    private static void AppendFormatFlagsName(StringBuilder sb, string enumTypeName, string token, bool hasDistinctMetadata)
    {
        var flagValues = "s_flagValues_" + token;
        sb.Append("    private static string? FormatFlagsName_").Append(token).Append('(').Append(enumTypeName).AppendLine(" value, bool useMetadata)");
        sb.AppendLine("    {");
        sb.Append("        var remaining = ToUInt64_").Append(token).AppendLine("(value);");
        sb.AppendLine("        if (remaining == 0)");
        sb.AppendLine("            return null;");
        sb.AppendLine();

        // First pass only validates, so a value that cannot be decomposed allocates nothing.
        sb.AppendLine("        var matchCount = 0;");
        sb.Append("        for (var i = 0; i < ").Append(flagValues).AppendLine(".Length; i++)");
        sb.AppendLine("        {");
        sb.Append("            var flagValue = ").Append(flagValues).AppendLine("[i];");
        sb.AppendLine("            if ((remaining & flagValue) != flagValue)");
        sb.AppendLine("                continue;");
        sb.AppendLine();
        sb.AppendLine("            remaining &= ~flagValue;");
        sb.AppendLine("            matchCount++;");
        sb.AppendLine("            if (remaining == 0)");
        sb.AppendLine("                break;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        if (remaining != 0 || matchCount == 0)");
        sb.AppendLine("            return null;");
        sb.AppendLine();
        if (hasDistinctMetadata)
        {
            sb.Append("        var names = useMetadata ? s_flagMetadataNames_").Append(token).Append(" : s_flagNames_").Append(token).AppendLine(";");
        }
        else
        {
            sb.Append("        var names = s_flagNames_").Append(token).AppendLine(";");
        }

        sb.AppendLine("        var matches = new int[matchCount];");
        sb.AppendLine("        var matchIndex = 0;");
        sb.Append("        remaining = ToUInt64_").Append(token).AppendLine("(value);");
        sb.Append("        for (var i = 0; i < ").Append(flagValues).AppendLine(".Length; i++)");
        sb.AppendLine("        {");
        sb.Append("            var flagValue = ").Append(flagValues).AppendLine("[i];");
        sb.AppendLine("            if ((remaining & flagValue) != flagValue)");
        sb.AppendLine("                continue;");
        sb.AppendLine();
        sb.AppendLine("            remaining &= ~flagValue;");
        sb.AppendLine("            matches[matchIndex++] = i;");
        sb.AppendLine("            if (remaining == 0)");
        sb.AppendLine("                break;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        if (matchCount == 1)");
        sb.AppendLine("            return names[matches[0]];");
        sb.AppendLine();

        // s_flagValues_ is ordered descending, and Enum.ToString lists the members ascending.
        sb.AppendLine("        var sb = new global::System.Text.StringBuilder();");
        sb.AppendLine("        for (var i = matchCount - 1; i >= 0; i--)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (i != matchCount - 1)");
        sb.AppendLine("                sb.Append(\", \");");
        sb.AppendLine();
        sb.AppendLine("            sb.Append(names[matches[i]]);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return sb.ToString();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendEqualsTokenHelper(StringBuilder sb, string token)
    {
        sb.Append("    private static bool EqualsToken_").Append(token).AppendLine("(global::System.ReadOnlySpan<char> value, string token, bool ignoreCase)");
        sb.AppendLine("    {");
        sb.AppendLine("        return global::System.MemoryExtensions.Equals(value, (global::System.ReadOnlySpan<char>)token, ignoreCase ? global::System.StringComparison.OrdinalIgnoreCase : global::System.StringComparison.Ordinal);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendTryParseHelpers(StringBuilder sb, string enumTypeName, EnumToProcess enumeration, string token, bool hasDistinctMetadata, ImmutableEquatableArray<EnumMemberToProcess> members, CancellationToken cancellationToken)
    {
        AppendTryParseSingleHelperMethod(sb, enumTypeName, token, "TryParseSingle_" + token, GetParseTokens(members, useMetadata: false), cancellationToken);
        if (hasDistinctMetadata)
        {
            AppendTryParseSingleHelperMethod(sb, enumTypeName, token, "TryParseSingleMetadata_" + token, GetParseTokens(members, useMetadata: true), cancellationToken);
        }

        if (enumeration.IsFlags)
        {
            AppendTryParseFlagsHelperMethod(sb, enumTypeName, token, "TryParseFlags_" + token, "TryParseSingle_" + token);
            if (hasDistinctMetadata)
            {
                AppendTryParseFlagsHelperMethod(sb, enumTypeName, token, "TryParseFlagsMetadata_" + token, "TryParseSingleMetadata_" + token);
            }
        }

        AppendTryParseDispatchHelperMethod(sb, enumTypeName, token, "TryParseCore_" + token, "TryParseSingle_" + token, enumeration.IsFlags ? "TryParseFlags_" + token : null);
        if (hasDistinctMetadata)
        {
            AppendTryParseDispatchHelperMethod(sb, enumTypeName, token, "TryParseMetadataCore_" + token, "TryParseSingleMetadata_" + token, enumeration.IsFlags ? "TryParseFlagsMetadata_" + token : null);
        }

        sb.Append("    private static bool IsNumericToken_").Append(token).AppendLine("(global::System.ReadOnlySpan<char> value)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (value.IsEmpty)");
        sb.AppendLine("            return false;");
        sb.AppendLine();
        sb.AppendLine("        var first = value[0];");
        sb.AppendLine("        if (first is '+' or '-')");
        sb.AppendLine("        {");
        sb.AppendLine("            if (value.Length == 1)");
        sb.AppendLine("                return false;");
        sb.AppendLine();
        sb.AppendLine("            first = value[1];");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return (uint)(first - '0') <= 9;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendTryParseSingleHelperMethod(StringBuilder sb, string enumTypeName, string token, string methodName, List<ParseTokenToProcess> parseTokens, CancellationToken cancellationToken)
    {
        sb.Append("    private static bool ").Append(methodName).Append("(global::System.ReadOnlySpan<char> value, bool ignoreCase, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("    {");

        // Dispatching on the length first avoids comparing against every name. Ordinal and
        // OrdinalIgnoreCase span comparisons both require equal lengths, so this is safe for both.
        sb.AppendLine("        switch (value.Length)");
        sb.AppendLine("        {");
        foreach (var group in parseTokens.GroupBy(static item => item.Token.Length).OrderBy(static group => group.Key))
        {
            cancellationToken.ThrowIfCancellationRequested();
            sb.Append("            case ").Append(group.Key.ToString(CultureInfo.InvariantCulture)).AppendLine(":");
            foreach (var parseToken in group)
            {
                sb.Append("                if (EqualsToken_").Append(token).Append("(value, ").Append(ToLiteral(parseToken.Token)).AppendLine(", ignoreCase))");
                sb.AppendLine("                {");
                sb.Append("                    result = ").Append(enumTypeName).Append('.').Append(parseToken.EscapedMemberName).AppendLine(";");
                sb.AppendLine("                    return true;");
                sb.AppendLine("                }");
                sb.AppendLine();
            }

            sb.AppendLine("                break;");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        result = default;");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendTryParseFlagsHelperMethod(StringBuilder sb, string enumTypeName, string token, string methodName, string tryParseSingleMethodName)
    {
        sb.Append("    private static bool ").Append(methodName).Append("(global::System.ReadOnlySpan<char> value, bool ignoreCase, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("    {");
        sb.AppendLine("        var remaining = value;");
        sb.AppendLine("        var hasToken = false;");
        sb.AppendLine("        var parsedValue = 0UL;");
        sb.AppendLine();
        sb.AppendLine("        while (true)");
        sb.AppendLine("        {");
        sb.AppendLine("            var separatorIndex = global::System.MemoryExtensions.IndexOf(remaining, ',');");
        sb.AppendLine("            var item = separatorIndex >= 0 ? remaining[..separatorIndex] : remaining;");
        sb.AppendLine("            item = global::System.MemoryExtensions.Trim(item);");
        sb.AppendLine("            if (item.IsEmpty)");
        sb.AppendLine("            {");
        sb.AppendLine("                result = default;");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.Append("            if (!").Append(tryParseSingleMethodName).AppendLine("(item, ignoreCase, out var itemValue))");
        sb.AppendLine("            {");
        sb.AppendLine("                result = default;");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.Append("            parsedValue |= ToUInt64_").Append(token).AppendLine("(itemValue);");
        sb.AppendLine("            hasToken = true;");
        sb.AppendLine("            if (separatorIndex < 0)");
        sb.AppendLine("                break;");
        sb.AppendLine();
        sb.AppendLine("            remaining = remaining[(separatorIndex + 1)..];");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        if (!hasToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            result = default;");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.Append("        result = FromUInt64_").Append(token).AppendLine("(parsedValue);");
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendTryParseDispatchHelperMethod(StringBuilder sb, string enumTypeName, string token, string methodName, string tryParseSingleMethodName, string? tryParseFlagsMethodName)
    {
        sb.Append("    private static bool ").Append(methodName).Append("(global::System.ReadOnlySpan<char> value, bool ignoreCase, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("    {");
        sb.AppendLine("        var trimmed = global::System.MemoryExtensions.Trim(value);");
        if (tryParseFlagsMethodName is not null)
        {
            sb.AppendLine("        if (global::System.MemoryExtensions.IndexOf(trimmed, ',') >= 0)");
            sb.AppendLine("        {");
            sb.Append("            if (").Append(tryParseFlagsMethodName).AppendLine("(trimmed, ignoreCase, out result))");
            sb.AppendLine("                return true;");
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
            sb.Append("            if (").Append(tryParseSingleMethodName).AppendLine("(trimmed, ignoreCase, out result))");
            sb.AppendLine("                return true;");
            sb.AppendLine("        }");
            sb.AppendLine();
        }
        else
        {
            sb.Append("        if (").Append(tryParseSingleMethodName).AppendLine("(trimmed, ignoreCase, out result))");
            sb.AppendLine("            return true;");
            sb.AppendLine();
        }

        // The generated tables cover every declared name, so only a numeric form still needs the BCL.
        sb.Append("        if (IsNumericToken_").Append(token).AppendLine("(trimmed))");
        sb.AppendLine("        {");
        sb.Append("            return global::System.Enum.TryParse<").Append(enumTypeName).AppendLine(">(trimmed, ignoreCase, out result);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        result = default;");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendExtensionMembers(StringBuilder sb, string enumTypeName, string visibility, string token, bool hasDistinctMetadata, bool needsMetadataNamesArray)
    {
        var metadataDispatch = hasDistinctMetadata ? "TryParseMetadataCore_" + token : "TryParseCore_" + token;

        sb.Append("    extension(").Append(enumTypeName).AppendLine(")");
        sb.AppendLine("    {");
        sb.Append("        ").Append(visibility).Append(" static ").Append(enumTypeName).AppendLine(" Parse(string value, bool ignoreCase)");
        sb.AppendLine("        {");
        sb.AppendLine("            return Parse(value, ignoreCase, useMetadata: false);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static ").Append(enumTypeName).AppendLine(" Parse(global::System.ReadOnlySpan<char> value, bool ignoreCase)");
        sb.AppendLine("        {");
        sb.AppendLine("            return Parse(value, ignoreCase, useMetadata: false);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static ").Append(enumTypeName).AppendLine(" Parse(string value, bool ignoreCase, bool useMetadata)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (value is null)");
        sb.AppendLine("                throw new global::System.ArgumentNullException(nameof(value));");
        sb.AppendLine();
        sb.AppendLine("            return Parse((global::System.ReadOnlySpan<char>)value, ignoreCase, useMetadata);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static ").Append(enumTypeName).AppendLine(" Parse(global::System.ReadOnlySpan<char> value, bool ignoreCase, bool useMetadata)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (TryParse(value, ignoreCase, useMetadata, out var result))");
        sb.AppendLine("                return result;");
        sb.AppendLine();

        // Enum.Parse reports OverflowException (not ArgumentException) for an out-of-range numeric
        // value, so defer to it rather than reporting a generic failure.
        sb.Append("            if (IsNumericToken_").Append(token).AppendLine("(global::System.MemoryExtensions.Trim(value)))");
        sb.AppendLine("            {");
        sb.Append("                return global::System.Enum.Parse<").Append(enumTypeName).AppendLine(">(value, ignoreCase);");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            throw new global::System.ArgumentException(\"The specified value is not a valid enum name.\", nameof(value));");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static bool TryParse(string? value, bool ignoreCase, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("        {");
        sb.AppendLine("            return TryParse(value, ignoreCase, useMetadata: false, out result);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static bool TryParse(global::System.ReadOnlySpan<char> value, bool ignoreCase, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("        {");
        sb.AppendLine("            return TryParse(value, ignoreCase, useMetadata: false, out result);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static bool TryParse(string? value, bool ignoreCase, bool useMetadata, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (value is null)");
        sb.AppendLine("            {");
        sb.AppendLine("                result = default;");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            return TryParse((global::System.ReadOnlySpan<char>)value, ignoreCase, useMetadata, out result);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static bool TryParse(global::System.ReadOnlySpan<char> value, bool ignoreCase, bool useMetadata, out ").Append(enumTypeName).AppendLine(" result)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (useMetadata)");
        sb.AppendLine("            {");
        sb.Append("                return ").Append(metadataDispatch).AppendLine("(value, ignoreCase, out result);");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.Append("            return TryParseCore_").Append(token).AppendLine("(value, ignoreCase, out result);");
        sb.AppendLine("        }");
        sb.AppendLine();

        // Named IsDefinedFast: a member named IsDefined would be shadowed by the inherited
        // System.Enum.IsDefined<TEnum>, which always wins overload resolution.
        sb.Append("        ").Append(visibility).Append(" static bool IsDefinedFast(").Append(enumTypeName).AppendLine(" value)");
        sb.AppendLine("        {");
        sb.Append("            return IsDefinedCore_").Append(token).AppendLine("(value);");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).AppendLine(" static global::System.ReadOnlySpan<string> GetNames(bool useMetadata)");
        sb.AppendLine("        {");
        if (needsMetadataNamesArray)
        {
            sb.Append("            return useMetadata ? s_metadataNames_").Append(token).Append(" : s_names_").Append(token).AppendLine(";");
        }
        else
        {
            sb.Append("            return s_names_").Append(token).AppendLine(";");
        }

        sb.AppendLine("        }");
        sb.AppendLine();

        sb.Append("        ").Append(visibility).Append(" static global::System.ReadOnlySpan<").Append(enumTypeName).AppendLine("> GetValues()");
        sb.AppendLine("        {");
        sb.Append("            return s_values_").Append(token).AppendLine(";");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static List<EnumMemberToProcess> GetUniqueMembers(ImmutableEquatableArray<EnumMemberToProcess> members)
    {
        var result = new List<EnumMemberToProcess>(members.Length);
        var values = new HashSet<ulong>();
        foreach (var member in members)
        {
            if (values.Add(member.UInt64Value))
            {
                result.Add(member);
            }
        }

        return result;
    }

    private static List<ParseTokenToProcess> GetParseTokens(ImmutableEquatableArray<EnumMemberToProcess> members, bool useMetadata)
    {
        var tokens = new List<ParseTokenToProcess>(members.Length);

        // Ordinal, not OrdinalIgnoreCase: members differing only by case are distinct and must each be
        // parseable, otherwise a case-sensitive parse of the dropped name would fail.
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var member in members)
        {
            var token = useMetadata ? (member.MetadataName ?? member.Name) : member.Name;
            if (string.IsNullOrEmpty(token))
                continue;

            if (!seen.Add(token))
                continue;

            tokens.Add(new ParseTokenToProcess(token, member.EscapedName));
        }

        return tokens;
    }

    private static bool IsDenseMembersAligned(ImmutableEquatableArray<EnumMemberToProcess> members)
    {
        for (var i = 0; i < members.Length; i++)
        {
            if (members[i].UInt64Value != unchecked((ulong)i))
                return false;
        }

        return true;
    }

    private static string ToLiteral(string value)
    {
        return SymbolDisplay.FormatLiteral(value, quote: true);
    }

    private static string ToUInt64Literal(ulong value)
    {
        return "0x" + value.ToString("X", CultureInfo.InvariantCulture) + "UL";
    }

    private static void AppendCommaSeparated(StringBuilder sb, IEnumerable<string> values)
    {
        var isFirst = true;
        foreach (var value in values)
        {
            if (!isFirst)
            {
                sb.Append(", ");
            }

            sb.Append(value);
            isFirst = false;
        }
    }

