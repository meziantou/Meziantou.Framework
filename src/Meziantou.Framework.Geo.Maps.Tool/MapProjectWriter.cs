using System.Globalization;
using System.Security;
using System.Text;

namespace Meziantou.Framework.Geo.Maps.Tool;

/// <summary>
/// Writes the project of the NuGet package of a bundle, that the .NET SDK builds: an assembly with the layers of the map as
/// embedded resources, and a static extension property of <see cref="Map"/>, such as <c>Map.Region_France</c>, that opens it.
/// </summary>
/// <remarks>
/// The layers are read in place, from the memory of the loaded assembly: no file is copied next to the application, and
/// no layer is copied to read it. The metadata of the map is written as C# code, so nothing is parsed when the map is
/// opened. The project references the builds of Meziantou.Framework.Geo.Maps that the tool embeds, so that the build needs no
/// package feed, and its .nuspec file declares the dependency on the package.
/// </remarks>
internal static class MapProjectWriter
{
    /// <summary>The target framework of the assemblies: the oldest one of Meziantou.Framework.Geo.Maps.</summary>
    public const string TargetFramework = "net10.0";

    /// <summary>Writes the project of a region, and returns the path of its project file.</summary>
    /// <param name="region">The region.</param>
    /// <param name="format">The format of the map: a folder format.</param>
    /// <param name="mapPath">The folder of the map, as <see cref="RegionBuilder.Write"/> wrote it.</param>
    /// <param name="options">The options of the packages.</param>
    /// <param name="directory">The folder of the projects.</param>
    public static FullPath Write(Region region, MapFormat format, string mapPath, PackageOptions options, FullPath directory)
    {
        var id = options.IdPrefix + "." + region.Key;
        var map = format.Open(mapPath);
        var layers = map.Layers;
        var mapAssembly = typeof(Map).Assembly;
        var dependencyId = mapAssembly.GetName().Name!;
        var dependencyVersion = mapAssembly.GetName().Version!.ToString(3);
        var member = "Region_" + region.Key;
        var description = $"The map of {region.Name}: {NuGetPackageWriter.GetLayerList(layers)}, as {format.Name}, embedded in an assembly for {dependencyId}: use Map.{member}. Generated by Meziantou.Framework.Geo.Maps.Tool. {RegionBuilder.Attribution}";

        var projectDirectory = directory / id;
        Directory.CreateDirectory(projectDirectory);

        // The project does not import the files of the folders above it, such as the Directory.Build.props of a repository
        File.WriteAllText(projectDirectory / "Directory.Build.props", "<Project />\n");
        File.WriteAllText(projectDirectory / "Directory.Build.targets", "<Project />\n");
        File.WriteAllText(projectDirectory / "Directory.Packages.props", "<Project />\n");

        // The assemblies of the target framework of the package, that the tool embeds: the tool may run on a later framework
        var references = new StringBuilder();
        foreach (var assembly in new[] { typeof(GeoFeature).Assembly, mapAssembly })
        {
            var fileName = assembly.GetName().Name + ".dll";
            var referencePath = projectDirectory / "references" / fileName;
            Directory.CreateDirectory(referencePath.Parent);
            using (var resource = typeof(MapProjectWriter).Assembly.GetManifestResourceStream("References." + fileName) ?? throw new InvalidOperationException($"The tool does not embed the {TargetFramework} build of {fileName}."))
            using (var file = File.Create(referencePath))
            {
                resource.CopyTo(file);
            }

            references.Append(CultureInfo.InvariantCulture, $"""    <Reference Include="references/{Escape(fileName)}" Private="false" />""").Append('\n');
        }

        var resources = new StringBuilder();
        foreach (var layer in layers)
        {
            var file = Path.Combine(mapPath, GetResourceName(format, layer));
            resources.Append(CultureInfo.InvariantCulture, $"""    <EmbeddedResource Include="{Escape(file)}" LogicalName="{GetResourceName(format, layer)}" />""").Append('\n');
        }

        File.WriteAllText(projectDirectory / (id + ".csproj"), $"""
            <Project Sdk="Microsoft.NET.Sdk">

              <PropertyGroup>
                <TargetFramework>{TargetFramework}</TargetFramework>
                <AssemblyName>{Escape(id)}</AssemblyName>
                <RootNamespace>{Escape(options.IdPrefix)}</RootNamespace>
                <LangVersion>14.0</LangVersion>
                <Nullable>enable</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
                <IsTrimmable>true</IsTrimmable>
                <IsAotCompatible>true</IsAotCompatible>
                <Deterministic>true</Deterministic>
                <DebugType>none</DebugType>
                <GenerateDocumentationFile>true</GenerateDocumentationFile>
                <OutputPath>bin/</OutputPath>
                <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
                <Version>{Escape(options.Version)}</Version>
                <Authors>{Escape(options.Authors)}</Authors>
                <Description>{Escape(description)}</Description>
                <NuspecFile>{Escape(id)}.nuspec</NuspecFile>
                <PackageOutputPath>{Escape(options.OutputDirectory)}</PackageOutputPath>
              </PropertyGroup>

              <ItemGroup>
            {references}  </ItemGroup>

              <ItemGroup>
            {resources}  </ItemGroup>

            </Project>

            """);

        File.WriteAllText(projectDirectory / (id + ".nuspec"), $"""
            <?xml version="1.0" encoding="utf-8"?>
            <package xmlns="http://schemas.microsoft.com/packaging/2013/05/nuspec.xsd">
              <metadata>
                <id>{Escape(id)}</id>
                <version>{Escape(options.Version)}</version>
                <authors>{Escape(options.Authors)}</authors>
                <description>{Escape(description)}</description>
                <license type="expression">ODbL-1.0</license>
                <projectUrl>https://github.com/meziantou/Meziantou.Framework</projectUrl>
                <tags>map maps geo gis offline borders cities {format.Name.ToLowerInvariant()} openstreetmap natural-earth</tags>
                <dependencies>
                  <group targetFramework="{TargetFramework}">
                    <dependency id="{dependencyId}" version="{dependencyVersion}" exclude="Build,Analyzers" />
                  </group>
                </dependencies>
              </metadata>
              <files>
                <file src="bin/{Escape(id)}.dll" target="lib/{TargetFramework}" />
                <file src="bin/{Escape(id)}.xml" target="lib/{TargetFramework}" />
              </files>
            </package>

            """);

        File.WriteAllText(projectDirectory / (region.Key + "Map.g.cs"), GenerateCode(region, format, map, options.IdPrefix, description));
        return projectDirectory / (id + ".csproj");
    }

    /// <summary>Gets the name of the resource of a layer: the name of its file in the folder of the map, such as <c>borders.fgb</c>.</summary>
    public static string GetResourceName(MapFormat format, MapLayer layer) => MapFormat.GetLayerName(layer) + (format == MapFormat.FlatGeobuf ? ".fgb" : ".geojson");

    private static string GenerateCode(Region region, MapFormat format, Map map, string idPrefix, string description)
    {
        var metadata = map.Metadata;
        var className = region.Key + "Map";
        var member = "Region_" + region.Key;
        var flatGeobuf = format == MapFormat.FlatGeobuf;

        var code = new StringBuilder();
        code.Append("// <auto-generated>Generated by Meziantou.Framework.Geo.Maps.Tool</auto-generated>\n");
        code.Append("#nullable enable\n\n");
        code.Append("namespace ").Append(string.Join('.', idPrefix.Split('.').Select(GetIdentifier))).Append(";\n\n");

        code.Append("/// <summary>The map of ").Append(SecurityElement.Escape(region.Name)).Append(", embedded in this assembly.</summary>\n");
        code.Append("public static class ").Append(className).Append("Extensions\n{\n");
        code.Append("    extension(global::Meziantou.Framework.Geo.Maps.Map)\n    {\n");
        code.Append("        /// <summary>Gets the map of ").Append(SecurityElement.Escape(region.Name)).Append(": ").Append(SecurityElement.Escape(NuGetPackageWriter.GetLayerList(map.Layers))).Append(". Its layers are read from the memory of this assembly.</summary>\n");
        code.Append("        /// <remarks>").Append(SecurityElement.Escape(metadata.Attribution ?? description)).Append("</remarks>\n");
        code.Append("        public static global::Meziantou.Framework.Geo.Maps.Map ").Append(GetIdentifier(member)).Append(" => ").Append(className).Append(".Instance;\n");
        code.Append("    }\n}\n\n");

        code.Append("internal sealed class ").Append(className).Append(" : global::Meziantou.Framework.Geo.Maps.Map\n{\n");
        code.Append("    private ").Append(className).Append("()\n        : base(new global::Meziantou.Framework.Geo.Maps.MapMetadata(").Append(Literal(metadata.Region)).Append(")\n        {\n");
        if (metadata.Name is not null)
        {
            code.Append("            Name = ").Append(Literal(metadata.Name)).Append(",\n");
        }

        if (metadata.Attribution is not null)
        {
            code.Append("            Attribution = ").Append(Literal(metadata.Attribution)).Append(",\n");
        }

        if (metadata.Bounds is { } bounds)
        {
            code.Append("            Bounds = new global::Meziantou.Framework.Geo.GeoBounds(").Append(Literal(bounds.West)).Append(", ").Append(Literal(bounds.South)).Append(", ").Append(Literal(bounds.East)).Append(", ").Append(Literal(bounds.North)).Append("),\n");
        }

        if (metadata.LastModified is { } lastModified)
        {
            code.Append("            LastModified = new global::System.DateTimeOffset(").Append(lastModified.UtcTicks.ToString(CultureInfo.InvariantCulture)).Append("L, global::System.TimeSpan.Zero),\n");
        }

        code.Append("            Sources =\n            [\n");
        foreach (var source in metadata.Sources)
        {
            code.Append("                new global::Meziantou.Framework.Geo.Maps.MapSource(").Append(Literal(source.Name))
                .Append(", ").Append(source.Url is null ? "null" : "new global::System.Uri(" + Literal(source.Url.OriginalString) + ")")
                .Append(", ").Append(source.License is null ? "null" : Literal(source.License)).Append("),\n");
        }

        code.Append("            ],\n        })\n    {\n    }\n\n");
        code.Append("    public static ").Append(className).Append(" Instance { get; } = new();\n\n");

        code.Append("    public override bool HasLayer(global::Meziantou.Framework.Geo.Maps.MapLayer layer) => layer is ")
            .Append(string.Join(" or ", map.Layers.Select(layer => "global::Meziantou.Framework.Geo.Maps.MapLayer." + layer)))
            .Append(";\n\n");

        code.Append("    protected override global::System.Collections.Generic.IEnumerable<global::Meziantou.Framework.Geo.GeoFeature> LoadLayer(global::Meziantou.Framework.Geo.Maps.MapLayer layer, global::Meziantou.Framework.Geo.GeoBounds? bounds) => layer switch\n    {\n");
        foreach (var layer in map.Layers)
        {
            code.Append("        global::Meziantou.Framework.Geo.Maps.MapLayer.").Append(layer).Append(" => Read(").Append(Literal(GetResourceName(format, layer))).Append(", bounds),\n");
        }

        code.Append("        _ => throw new global::System.ArgumentOutOfRangeException(nameof(layer)),\n    };\n\n");

        if (flatGeobuf)
        {
            code.Append("""
                    // The layer is read in place: the memory of the resource is the memory of the loaded assembly
                    private static unsafe global::Meziantou.Framework.Geo.GeoFeatureCollection Read(string name, global::Meziantou.Framework.Geo.GeoBounds? bounds)
                    {
                        var options = new global::Meziantou.Framework.Geo.FlatGeobufReaderOptions { Bounds = bounds };
                        using var stream = typeof(
                """).Append(className).Append("""
                ).Assembly.GetManifestResourceStream(name) ?? throw new global::System.InvalidOperationException("The resource '" + name + "' is missing.");
                        if (stream is global::System.IO.UnmanagedMemoryStream unmanagedStream)
                        {
                            using var memory = new UnmanagedMemoryManager(unmanagedStream.PositionPointer, checked((int)unmanagedStream.Length));
                            return global::Meziantou.Framework.Geo.FlatGeobuf.Read(memory.Memory, options);
                        }

                        return global::Meziantou.Framework.Geo.FlatGeobuf.Read(stream, options);
                    }

                    private sealed unsafe class UnmanagedMemoryManager : global::System.Buffers.MemoryManager<byte>
                    {
                        private readonly byte* _pointer;
                        private readonly int _length;

                        public UnmanagedMemoryManager(byte* pointer, int length)
                        {
                            _pointer = pointer;
                            _length = length;
                        }

                        public override global::System.Span<byte> GetSpan() => new(_pointer, _length);

                        public override global::System.Buffers.MemoryHandle Pin(int elementIndex = 0) => new(_pointer + elementIndex);

                        public override void Unpin()
                        {
                        }

                        protected override void Dispose(bool disposing)
                        {
                        }
                    }

                """);
        }
        else
        {
            code.Append("""
                    // GeoJSON has no index: the whole layer is read, and the map keeps the features of the box
                    private static global::Meziantou.Framework.Geo.GeoFeatureCollection Read(string name, global::Meziantou.Framework.Geo.GeoBounds? bounds)
                    {
                        using var stream = typeof(
                """).Append(className).Append("""
                ).Assembly.GetManifestResourceStream(name) ?? throw new global::System.InvalidOperationException("The resource '" + name + "' is missing.");
                        return global::Meziantou.Framework.Geo.GeoJson.Read(stream);
                    }

                """);
        }

        code.Append("}\n");
        return code.ToString();
    }

    // A C# identifier: the characters that are not letters, digits or '_' become '_', and '@' makes a keyword an identifier
    private static string GetIdentifier(string name)
    {
        var builder = new StringBuilder(name.Length + 2);
        builder.Append('@');
        if (name.Length == 0 || char.IsAsciiDigit(name[0]))
        {
            builder.Append('_');
        }

        foreach (var c in name)
        {
            builder.Append(char.IsAsciiLetterOrDigit(c) || c is '_' ? c : '_');
        }

        return builder.ToString();
    }

    private static string Literal(double value) => value.ToString("R", CultureInfo.InvariantCulture) + "d";

    private static string Literal(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (var c in value)
        {
            switch (c)
            {
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\\':
                    builder.Append(@"\\");
                    break;
                case < ' ' or '\u007F' or '\u0085' or '\u2028' or '\u2029':
                    builder.Append(CultureInfo.InvariantCulture, $"\\u{(int)c:X4}");
                    break;
                default:
                    builder.Append(c);
                    break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }

    private static string Escape(string text) => SecurityElement.Escape(text);
}
