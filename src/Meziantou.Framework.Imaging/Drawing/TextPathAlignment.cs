namespace Meziantou.Framework.Imaging.Drawing;

/// <summary>Where a text is placed along the path it follows.</summary>
public enum TextPathAlignment
{
    /// <summary>The text starts at the start of the path.</summary>
    Start = 0,

    /// <summary>The middle of the text is at the middle of the path.</summary>
    Center = 1,

    /// <summary>The text ends at the end of the path.</summary>
    End = 2,
}
