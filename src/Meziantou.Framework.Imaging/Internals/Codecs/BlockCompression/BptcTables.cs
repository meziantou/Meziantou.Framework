    };

    /// <summary>Gets the subset of a texel of a partition.</summary>
    /// <param name="subsets">The number of subsets (1, 2 or 3).</param>
    /// <param name="partition">The partition number.</param>
    /// <param name="texel">The texel, <c>x + 4y</c>.</param>
    public static int GetSubset(int subsets, int partition, int texel) => subsets switch
    {
        1 => 0,
        2 => (int)(TwoSubsetPartitions[partition] >> (2 * texel)) & 3,
        _ => (int)(ThreeSubsetPartitions[partition] >> (2 * texel)) & 3,
    };

    /// <summary>Gets a value indicating whether a texel is the anchor of its subset, whose index has one bit less.</summary>
    public static bool IsAnchor(int subsets, int partition, int texel) => texel == 0 || subsets switch
    {
        1 => false,
        2 => texel == TwoSubsetAnchors[partition],
        _ => texel == ThreeSubsetSecondAnchors[partition] || texel == ThreeSubsetThirdAnchors[partition],
    };

