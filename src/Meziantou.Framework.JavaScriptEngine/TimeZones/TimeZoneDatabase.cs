using System.Runtime.InteropServices;
using System.Diagnostics.CodeAnalysis;
using System.IO.Compression;

namespace Meziantou.Framework.JavaScriptEngine.TimeZones;

/// <summary>An identifier of the time zone database: its spelling in the database, its primary identifier and its zone.</summary>
/// <param name="Identifier">The identifier as cased in the database (a Zone or a Link name).</param>
/// <param name="PrimaryIdentifier">The primary identifier (ECMA-402): the Zone a Link resolves to, and "UTC" for Etc/UTC, Etc/GMT and their links.</param>
/// <param name="Zone">The zone, which gives the offsets.</param>
[StructLayout(LayoutKind.Auto)]
internal readonly record struct TimeZoneIdentifier(string Identifier, string PrimaryIdentifier, NamedTimeZone Zone);

/// <summary>
/// The IANA time zone database embedded in the engine (TimeZones/tzdb.bin, generated by
/// tools/Meziantou.Framework.JavaScriptEngine.Data.Generator). It does not depend on the operating system or on ICU, so
/// the engine computes the same local times everywhere. The data is loaded once per process, on first use, and each zone
/// is decoded on first use; the instances are thread-safe.
/// </summary>
internal sealed partial class TimeZoneDatabase
{
    private const string ResourceName = "Meziantou.Framework.JavaScriptEngine.TimeZones.tzdb.bin";
    private static readonly byte[] Magic = "MFTZ"u8.ToArray();

    private static TimeZoneDatabase? s_default;

    private readonly byte[] _data;
    private readonly string[] _zoneNames;
    private readonly int[] _zoneDataOffsets;
    private readonly NamedTimeZone?[] _zones;
    private readonly string[] _abbreviations;
    private readonly Dictionary<string, (string Identifier, int ZoneIndex)> _identifiers;
    private readonly Dictionary<string, string> _windowsIds;

    private TimeZoneDatabase(byte[] data)
    {
        _data = data;
        var reader = new Reader(data, 0);
        if (!reader.ReadBytes(Magic.Length).SequenceEqual(Magic))
            throw new InvalidDataException("The time zone database is invalid");

        var formatVersion = reader.ReadByte();
        if (formatVersion != 1)
            throw new InvalidDataException("The format of the time zone database is not supported: " + formatVersion);

        Version = reader.ReadString();
        _abbreviations = new string[reader.ReadVarUInt32()];
        for (var i = 0; i < _abbreviations.Length; i++)
        {
            _abbreviations[i] = reader.ReadString();
        }

        var zoneCount = (int)reader.ReadVarUInt32();
        _zoneNames = new string[zoneCount];
        _zoneDataOffsets = new int[zoneCount];
        _zones = new NamedTimeZone?[zoneCount];
        _identifiers = new Dictionary<string, (string, int)>(StringComparer.OrdinalIgnoreCase);
        var identifiers = new List<string>();
        for (var i = 0; i < zoneCount; i++)
        {
            var name = reader.ReadString();
            var length = (int)reader.ReadVarUInt32();
            _zoneNames[i] = name;
            _zoneDataOffsets[i] = reader.Position;
            reader.Skip(length);
            _identifiers.Add(name, (name, i));
            identifiers.Add(name);
        }

        var linkCount = (int)reader.ReadVarUInt32();
        for (var i = 0; i < linkCount; i++)
        {
            var name = reader.ReadString();
            var target = (int)reader.ReadVarUInt32();
            _identifiers.Add(name, (name, target));
            identifiers.Add(name);
        }

        var windowsCount = (int)reader.ReadVarUInt32();
        _windowsIds = new Dictionary<string, string>(windowsCount, StringComparer.OrdinalIgnoreCase);
        for (var i = 0; i < windowsCount; i++)
        {
            var windowsId = reader.ReadString();
            var ianaId = reader.ReadString();
            _windowsIds.Add(windowsId, ianaId);
        }

        identifiers.Sort(StringComparer.Ordinal);
        AvailableIdentifiers = identifiers.AsReadOnly();
    }

    /// <summary>Gets the database embedded in the engine.</summary>
    public static TimeZoneDatabase Default
    {
        get
        {
            var result = Volatile.Read(ref s_default);
            if (result is null)
            {
                result = LoadEmbedded();
                result = Interlocked.CompareExchange(ref s_default, result, comparand: null) ?? result;
            }

            return result;
        }
    }

    /// <summary>Gets the release of the IANA time zone database (e.g. "2026e").</summary>
    public string Version { get; }

    /// <summary>Gets the Zone and Link names, sorted by ordinal (AvailableNamedTimeZoneIdentifiers).</summary>
    public IReadOnlyList<string> AvailableIdentifiers { get; }

    /// <summary>Loads a database from its compressed form (the content of tzdb.bin).</summary>
    internal static TimeZoneDatabase LoadCompressed(Stream stream)
    {
        using var brotli = new BrotliStream(stream, CompressionMode.Decompress, leaveOpen: true);
        using var memory = new MemoryStream();
        brotli.CopyTo(memory);
        return new TimeZoneDatabase(memory.ToArray());
    }

    /// <summary>Loads a database from its uncompressed form.</summary>
    internal static TimeZoneDatabase Load(byte[] data) => new(data);

    private static TimeZoneDatabase LoadEmbedded()
    {
        using var stream = typeof(TimeZoneDatabase).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException("The time zone database is not embedded in the assembly: " + ResourceName);
        return LoadCompressed(stream);
    }

    /// <summary>Finds an identifier, ignoring the ASCII case (GetAvailableNamedTimeZoneIdentifier).</summary>
    public bool TryGetTimeZone(string identifier, out TimeZoneIdentifier result)
    {
        if (!_identifiers.TryGetValue(identifier, out var entry))
        {
            result = default;
            return false;
        }

        var zone = GetZone(entry.ZoneIndex);
        result = new TimeZoneIdentifier(entry.Identifier, GetPrimaryIdentifier(zone.Id), zone);
        return true;
    }

    /// <summary>Gets a zone by identifier (ignoring the case), or null when the identifier is unknown.</summary>
    public NamedTimeZone? GetTimeZone(string identifier) => TryGetTimeZone(identifier, out var result) ? result.Zone : null;

    /// <summary>Gets the IANA identifier of a Windows time zone identifier (CLDR windowsZones.xml, territory 001).</summary>
    public bool TryGetIanaIdFromWindowsId(string windowsId, [NotNullWhen(true)] out string? ianaId) => _windowsIds.TryGetValue(windowsId, out ianaId);

    private static string GetPrimaryIdentifier(string zoneName)
    {
        // ECMA-402: Etc/UTC, Etc/GMT and the links to them are UTC
        return zoneName is "Etc/UTC" or "Etc/GMT" ? "UTC" : zoneName;
    }

    private NamedTimeZone GetZone(int index)
    {
        var zone = Volatile.Read(ref _zones[index]);
        if (zone is null)
        {
            zone = DecodeZone(index);
            zone = Interlocked.CompareExchange(ref _zones[index], zone, comparand: null) ?? zone;
        }

        return zone;
    }

    private NamedTimeZone DecodeZone(int index)
    {
        var reader = new Reader(_data, _zoneDataOffsets[index]);
        var types = new TimeZoneLocalTimeType[reader.ReadVarUInt32()];
        for (var i = 0; i < types.Length; i++)
        {
            var offset = (int)reader.ReadVarInt64();
            var isDst = reader.ReadByte() != 0;
            var abbreviation = _abbreviations[reader.ReadVarUInt32()];
            types[i] = new TimeZoneLocalTimeType(offset, isDst, abbreviation);
        }

        var initialType = (int)reader.ReadVarUInt32();
        var transitionCount = (int)reader.ReadVarUInt32();
        var times = new long[transitionCount];
        var transitionTypes = new byte[transitionCount];
        var previous = 0L;
        for (var i = 0; i < transitionCount; i++)
        {
            previous += reader.ReadVarInt64();
            times[i] = previous;
            transitionTypes[i] = reader.ReadByte();
        }

        TimeZoneRecurringRule? rule = null;
        if (reader.ReadByte() != 0)
        {
            var firstYear = (int)reader.ReadVarInt64();
            var standardOffset = (int)reader.ReadVarInt64();
            var entries = new TimeZoneRuleEntry[reader.ReadVarUInt32()];
            for (var i = 0; i < entries.Length; i++)
            {
                var month = reader.ReadByte();
                var dayKind = (TimeZoneRuleDayKind)reader.ReadByte();
                var day = reader.ReadByte();
                var weekday = reader.ReadByte();
                var at = (int)reader.ReadVarInt64();
                var atKind = (TimeZoneTimeKind)reader.ReadByte();
                var save = (int)reader.ReadVarInt64();
                var typeIndex = (int)reader.ReadVarUInt32();
                entries[i] = new TimeZoneRuleEntry(month, dayKind, day, weekday, at, atKind, save, typeIndex);
            }

            rule = new TimeZoneRecurringRule(firstYear, standardOffset, entries);
        }

        return new NamedTimeZone(_zoneNames[index], types, initialType, times, transitionTypes, rule);
    }

    [StructLayout(LayoutKind.Auto)]
    private struct Reader(byte[] data, int position)
    {
        public int Position { readonly get; private set; } = position;

        public byte ReadByte() => data[Position++];

        public ReadOnlySpan<byte> ReadBytes(int length)
        {
            var result = data.AsSpan(Position, length);
            Position += length;
            return result;
        }

        public void Skip(int length) => Position += length;

        public uint ReadVarUInt32() => (uint)ReadVarUInt64();

        public ulong ReadVarUInt64()
        {
            ulong result = 0;
            var shift = 0;
            while (true)
            {
                var b = data[Position++];
                result |= (ulong)(b & 0x7F) << shift;
                if ((b & 0x80) == 0)
                    return result;

                shift += 7;
            }
        }

        /// <summary>Reads a zigzag-encoded signed integer.</summary>
        public long ReadVarInt64()
        {
            var value = ReadVarUInt64();
            return (long)(value >> 1) ^ -(long)(value & 1);
        }

        public string ReadString()
        {
            var length = (int)ReadVarUInt32();
            return Encoding.ASCII.GetString(ReadBytes(length));
        }
    }
}
