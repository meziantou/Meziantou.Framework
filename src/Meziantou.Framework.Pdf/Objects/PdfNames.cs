    public static bool TryGet(string key, [NotNullWhen(true)] out PdfName? name) => Known.TryGetValue(key, out name);

    public static bool TryGet(ReadOnlySpan<char> key, [NotNullWhen(true)] out PdfName? name) => KnownLookup.TryGetValue(key, out name);

    private static PdfName Add(string value)
    {
        var name = PdfName.CreateWellKnown(value);
        Known.Add(value, name);
        return name;
    }
