using System.Collections.Immutable;

namespace Meziantou.Framework.PublicApiGenerator;

/// <summary>A type or a member that is part of the public API of an assembly.</summary>
/// <remarks>
/// Symbols only contain data decoded from metadata. They remain valid after the assembly file or stream is closed.
/// </remarks>
public abstract class PublicApiSymbol
{
    private protected PublicApiSymbol(string name, PublicApiAccessibility accessibility, ImmutableArray<PublicApiAttribute> attributes, PublicApiMetadataOrigin? origin)
    {
        Name = name;
        Accessibility = accessibility;
        Attributes = attributes;
        Origin = origin;
    }

    public abstract PublicApiSymbolKind Kind { get; }

    /// <summary>
    /// Gets the name of the symbol. Types do not include the generic arity suffix (see <see cref="MetadataName"/>).
    /// Explicit interface implementations use their metadata name (e.g. <c>System.IDisposable.Dispose</c>), constructors are named <c>.ctor</c>.
    /// </summary>
    public string Name { get; }

    /// <summary>Gets the name of the symbol as stored in metadata.</summary>
    public virtual string MetadataName => Name;

    public PublicApiAccessibility Accessibility { get; }

    /// <summary>Gets all the custom attributes applied to the symbol, including the ones that are not displayed by the C# formatter.</summary>
    public ImmutableArray<PublicApiAttribute> Attributes { get; }

    /// <summary>Gets the metadata entity the symbol was read from, or <see langword="null"/> when the symbol is not backed by a single metadata entity.</summary>
    public PublicApiMetadataOrigin? Origin { get; }

    /// <summary>Gets the type that declares the symbol. It is <see langword="null"/> for top-level types.</summary>
    public PublicApiType? DeclaringType { get; internal set; }

    /// <summary>Gets the assembly that declares the symbol.</summary>
    public PublicApiAssembly Assembly { get; internal set; } = null!;

    /// <summary>
    /// Gets the XML documentation ID of the symbol, as generated by the C# compiler (e.g. <c>M:System.String.Join(System.String,System.String[])</c>).
    /// It matches the <c>name</c> attribute of the <c>member</c> elements of the XML documentation file.
    /// </summary>
    /// <remarks>
    /// The documentation ID is not unique across assemblies. Use <see cref="Identity"/> to distinguish symbols of different assemblies.
    /// </remarks>
    public string DocumentationId { get; internal set; } = string.Empty;

    /// <summary>Gets the identity of the symbol, made of the scope of its assembly and its documentation ID.</summary>
    public PublicApiSymbolIdentity Identity => new(Assembly.Scope, DocumentationId);

    /// <summary>Gets a value indicating whether the symbol is marked with <c>System.Runtime.CompilerServices.CompilerGeneratedAttribute</c>.</summary>
    public bool IsCompilerGenerated => HasAttribute(Attributes, "System.Runtime.CompilerServices", "CompilerGeneratedAttribute");

    public override string ToString() => DocumentationId;

    internal static bool HasAttribute(ImmutableArray<PublicApiAttribute> attributes, string attributeNamespace, string attributeName)
    {
        foreach (var attribute in attributes)
        {
            if (attribute.AttributeType.ContainingType is null &&
                string.Equals(attribute.AttributeType.Namespace, attributeNamespace, StringComparison.Ordinal) &&
                string.Equals(attribute.AttributeType.MetadataName, attributeName, StringComparison.Ordinal))
            {
                return true;
            }
        }

        return false;
    }
}
