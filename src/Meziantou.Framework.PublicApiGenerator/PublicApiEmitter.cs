namespace Meziantou.Framework.PublicApiGenerator;

internal static class PublicApiEmitter
{
    public static IReadOnlyList<PublicApiFile> Generate(PublicApiModel model, PublicApiOptions options, IReadOnlyList<string> targetFrameworks, IReadOnlyList<string> assemblyReferences)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(targetFrameworks);
        ArgumentNullException.ThrowIfNull(assemblyReferences);

        // The assembly references are written once per assembly: in the single file, or in AssemblyInfo.g.cs for the other layouts
        var header = BuildHeaderComment(options.IncludeAutoGeneratedComment, targetFrameworks, assemblyReferences: []);
        var assemblyHeader = BuildHeaderComment(options.IncludeAutoGeneratedComment, targetFrameworks, assemblyReferences);
        IReadOnlyList<PublicApiFile> files = options.FileLayout switch
        {
            PublicApiFileLayout.SingleFile => [new PublicApiFile(BuildSingleFileName(model.AssemblyName), BuildSingleFile(model, assemblyHeader))],
            PublicApiFileLayout.OneFilePerNamespace => BuildNamespaceFiles(model, header, assemblyHeader),
            PublicApiFileLayout.OneFilePerType => BuildTypeFiles(model, header, assemblyHeader),
            _ => throw new ArgumentOutOfRangeException(nameof(options)),
        };

        return MakeFileNamesUnique(files);
    }

    /// <summary>
    /// Renames the files whose name is already used, ignoring case, so that the generated file set does not depend on the file system.
    /// The first file keeps its name, and the next ones get a <c>~2</c>, <c>~3</c>... suffix. A C# name cannot contain <c>~</c>,
    /// so the new name cannot be the name of another file.
    /// </summary>
    internal static IReadOnlyList<PublicApiFile> MakeFileNamesUnique(IReadOnlyList<PublicApiFile> files)
    {
        if (files.Count < 2)
            return files;

        var originalRelativePaths = new HashSet<string>(files.Select(file => file.RelativePath), StringComparer.OrdinalIgnoreCase);
        if (originalRelativePaths.Count == files.Count)
            return files;

        var usedRelativePaths = new HashSet<string>(files.Count, StringComparer.OrdinalIgnoreCase);
        var result = new List<PublicApiFile>(files.Count);
        foreach (var file in files)
        {
            if (usedRelativePaths.Add(file.RelativePath))
            {
                result.Add(file);
                continue;
            }

            // Keep the extension as written, so the new name is the original name with the suffix inserted
            var extensionLength = file.RelativePath.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ? ".g.cs".Length : Path.GetExtension(file.RelativePath).Length;
            var baseName = file.RelativePath[..^extensionLength];
            var extension = file.RelativePath[^extensionLength..];
            for (var index = 2; ; index++)
            {
                var relativePath = baseName + "~" + index.ToString(CultureInfo.InvariantCulture) + extension;
                if (!originalRelativePaths.Contains(relativePath) && usedRelativePaths.Add(relativePath))
                {
                    result.Add(file with { RelativePath = relativePath });
                    break;
                }
            }
        }

        return result;
    }

    private static List<PublicApiFile> BuildNamespaceFiles(PublicApiModel model, string header, string assemblyHeader)
    {
        var files = new List<PublicApiFile>();
        AddAssemblyInfoFile(files, model.AssemblyAttributesSource, header, assemblyHeader);
        foreach (var group in model.Types.GroupBy(type => type.Namespace, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var fileName = string.IsNullOrEmpty(group.Key) ? "GlobalNamespace.g.cs" : SanitizeFileName(group.Key) + ".g.cs";
            files.Add(new PublicApiFile(fileName, BuildFileContent(group.Key, group.OrderBy(type => type.QualifiedName, StringComparer.Ordinal), header)));
        }

        return files;
    }

    private static List<PublicApiFile> BuildTypeFiles(PublicApiModel model, string header, string assemblyHeader)
    {
        var files = new List<PublicApiFile>(model.Types.Length + 1);
        AddAssemblyInfoFile(files, model.AssemblyAttributesSource, header, assemblyHeader);
        foreach (var type in model.Types.OrderBy(value => value.QualifiedName, StringComparer.Ordinal))
        {
            var fileName = SanitizeFileName(type.QualifiedName) + ".g.cs";
            files.Add(new PublicApiFile(fileName, BuildFileContent(type.Namespace, [type], header)));
        }

        return files;
    }

    private static string BuildSingleFile(PublicApiModel model, string header)
    {
        var sb = CreateFileHeader(header, model.AssemblyAttributesSource);
        var groupedTypes = model.Types.GroupBy(static type => type.Namespace, StringComparer.Ordinal).OrderBy(static group => group.Key, StringComparer.Ordinal);
        foreach (var group in groupedTypes)
        {
            AppendNamespace(sb, group.Key, group.OrderBy(static type => type.QualifiedName, StringComparer.Ordinal));
        }

        return sb.ToString();
    }

    private static string BuildSingleFileName(string assemblyName)
    {
        var sanitizedAssemblyName = SanitizeFileName(assemblyName);
        if (string.IsNullOrWhiteSpace(sanitizedAssemblyName))
        {
            return "PublicApi.g.cs";
        }

        return sanitizedAssemblyName + ".cs";
    }

    private static string BuildFileContent(string namespaceName, IEnumerable<PublicApiTypeModel> types, string header)
    {
        var sb = CreateFileHeader(header, assemblyAttributesSource: string.Empty);
        AppendNamespace(sb, namespaceName, types);
        return sb.ToString();
    }

    private static void AddAssemblyInfoFile(List<PublicApiFile> files, string assemblyAttributesSource, string header, string assemblyHeader)
    {
        // The file also exists when it only lists the assembly references
        if (!string.IsNullOrEmpty(assemblyAttributesSource) || !string.Equals(header, assemblyHeader, StringComparison.Ordinal))
        {
            files.Add(new PublicApiFile("AssemblyInfo.g.cs", CreateFileHeader(assemblyHeader, assemblyAttributesSource).ToString()));
        }
    }

    private static string BuildHeaderComment(bool includeAutoGeneratedComment, IReadOnlyList<string> targetFrameworks, IReadOnlyList<string> assemblyReferences)
    {
        var sb = new StringBuilder();
        if (includeAutoGeneratedComment)
        {
            sb.AppendLine("// <auto-generated/>");
        }

        if (targetFrameworks.Count > 0)
        {
            sb.Append("// Target Frameworks: ");
            sb.AppendJoin(", ", targetFrameworks).AppendLine();
        }

        if (assemblyReferences.Count > 0)
        {
            sb.AppendLine("// Assembly References:");
            foreach (var assemblyReference in assemblyReferences)
            {
                sb.Append("//   ").AppendLine(assemblyReference);
            }
        }

        return sb.ToString();
    }

    private static StringBuilder CreateFileHeader(string header, string assemblyAttributesSource)
    {
        var sb = new StringBuilder(header);
        sb.Append(assemblyAttributesSource);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        return sb;
    }

    private static void AppendNamespace(StringBuilder sb, string namespaceName, IEnumerable<PublicApiTypeModel> types)
    {
        var orderedTypes = types.OrderBy(type => type.QualifiedName, StringComparer.Ordinal).ToList();
        if (orderedTypes.Count == 0)
            return;

        var conflictingNamespaceIdentifiers = GetConflictingNamespaceIdentifiers(namespaceName);
        if (string.IsNullOrEmpty(namespaceName))
        {
            for (var i = 0; i < orderedTypes.Count; i++)
            {
                if (i > 0)
                {
                    sb.AppendLine();
                }

                var source = conflictingNamespaceIdentifiers.Count > 0 ? QualifyConflictingNamespaceReferences(orderedTypes[i].Source, conflictingNamespaceIdentifiers) : orderedTypes[i].Source;
                sb.AppendLine(source);
            }

            return;
        }

        sb.Append("namespace ");
        sb.AppendLine(namespaceName);
        sb.AppendLine("{");
        for (var i = 0; i < orderedTypes.Count; i++)
        {
            if (i > 0)
            {
                sb.AppendLine();
            }

            var source = conflictingNamespaceIdentifiers.Count > 0 ? QualifyConflictingNamespaceReferences(orderedTypes[i].Source, conflictingNamespaceIdentifiers) : orderedTypes[i].Source;
            AppendIndented(sb, source, 1);
        }

        sb.AppendLine("}");
    }

    private static HashSet<string> GetConflictingNamespaceIdentifiers(string namespaceName)
    {
        if (string.IsNullOrEmpty(namespaceName))
            return [with(StringComparer.Ordinal)];

        var lastSeparatorIndex = namespaceName.LastIndexOf('.', StringComparison.Ordinal);
        var lastSegment = lastSeparatorIndex < 0
            ? namespaceName
            : namespaceName[(lastSeparatorIndex + 1)..];

        if (string.IsNullOrEmpty(lastSegment))
            return [with(StringComparer.Ordinal)];

        return [with(StringComparer.Ordinal), lastSegment];
    }

    private static string QualifyConflictingNamespaceReferences(string source, IReadOnlySet<string> conflictingNamespaceIdentifiers)
    {
        var sb = new StringBuilder(source.Length);
        var inString = false;
        var inChar = false;
        var escapeNext = false;
        for (var i = 0; i < source.Length; i++)
        {
            if (!inString && !inChar && TryGetConflictingIdentifierLength(source, i, conflictingNamespaceIdentifiers, out var identifierLength))
            {
                sb.Append("global::");
                sb.Append(source, i, identifierLength + 1);
                i += identifierLength;
                continue;
            }

            var ch = source[i];
            sb.Append(ch);

            if (inString)
            {
                if (escapeNext)
                {
                    escapeNext = false;
                }
                else if (ch == '\\')
                {
                    escapeNext = true;
                }
                else if (ch == '"')
                {
                    inString = false;
                }

                continue;
            }

            if (inChar)
            {
                if (escapeNext)
                {
                    escapeNext = false;
                }
                else if (ch == '\\')
                {
                    escapeNext = true;
                }
                else if (ch == '\'')
                {
                    inChar = false;
                }

                continue;
            }

            if (ch == '"')
            {
                inString = true;
                continue;
            }

            if (ch == '\'')
            {
                inChar = true;
            }
        }

        return sb.ToString();
    }

    private static bool TryGetConflictingIdentifierLength(string source, int index, IReadOnlySet<string> conflictingNamespaceIdentifiers, out int identifierLength)
    {
        identifierLength = 0;
        if (index >= source.Length || (!char.IsLetter(source[index]) && source[index] != '_'))
            return false;

        var currentIndex = index + 1;
        while (currentIndex < source.Length && (char.IsLetterOrDigit(source[currentIndex]) || source[currentIndex] == '_'))
        {
            currentIndex++;
        }

        if (currentIndex >= source.Length || source[currentIndex] != '.')
            return false;

        var identifier = source[index..currentIndex];
        if (!conflictingNamespaceIdentifiers.Contains(identifier))
            return false;

        if (index >= "global::".Length &&
            source[index - 8] == 'g' &&
            source[index - 7] == 'l' &&
            source[index - 6] == 'o' &&
            source[index - 5] == 'b' &&
            source[index - 4] == 'a' &&
            source[index - 3] == 'l' &&
            source[index - 2] == ':' &&
            source[index - 1] == ':')
        {
            return false;
        }

        if (index == 0)
        {
            identifierLength = identifier.Length;
            return true;
        }

        var previousCharacter = source[index - 1];
        if (char.IsLetterOrDigit(previousCharacter) || previousCharacter is '_' or '.')
            return false;

        identifierLength = identifier.Length;
        return true;
    }

    private static void AppendIndented(StringBuilder sb, string text, int indentationLevel)
    {
        using var reader = new StringReader(text);
        string? line;
        while ((line = reader.ReadLine()) is not null)
        {
            if (line.Length > 0)
            {
                sb.Append(' ', indentationLevel * 4);
            }

            sb.AppendLine(line);
        }
    }

    private static string SanitizeFileName(string value)
    {
        var sanitized = new StringBuilder(value.Length);
        foreach (var character in value)
        {
            sanitized.Append(IsInvalidFileNameCharacter(character) ? '_' : character);
        }

        return sanitized.ToString();
    }

    private static bool IsInvalidFileNameCharacter(char character)
    {
        // A fixed set instead of Path.GetInvalidFileNameChars(), which returns only '/' and '\0' on Unix
        // and would make the same assembly produce different file names depending on the operating system
        return char.IsControl(character) || character is '"' or '<' or '>' or '|' or ':' or '*' or '?' or '\\' or '/';
    }
}
