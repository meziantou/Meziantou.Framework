namespace Meziantou.Framework.PublicApiGenerator;

/// <summary>Options for <see cref="PublicApi.ReadAssembly(string, PublicApiReadOptions?)"/>.</summary>
public sealed class PublicApiReadOptions
{
    /// <summary>
    /// Gets or sets the target framework of the assembly (e.g. <c>net8.0</c> or <c>.NETCoreApp,Version=v8.0</c>). The value is kept as provided.
    /// When it is not set, it is inferred from the <c>TargetFrameworkAttribute</c> of the assembly.
    /// </summary>
    public string? TargetFramework { get; set; }

    /// <summary>
    /// Gets or sets an identity for the input, such as a package identity and the path of the assembly in the package (e.g. <c>MyPackage/1.0.0/lib/net8.0/MyLibrary.dll</c>).
    /// When set, it is used as the scope of the symbol identities (see <see cref="PublicApiAssembly.Scope"/>). Avoid machine-specific values such as absolute file paths.
    /// </summary>
    public string? InputIdentity { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether the <c>internal</c> types and members are part of the model, in addition to the ones that are visible outside the assembly.
    /// Use it for the assemblies whose internal symbols are an API, such as an assembly compiled from the C# files of a source package.
    /// </summary>
    /// <remarks>
    /// <para>
    /// When it is <see langword="true"/>, the model contains the types, members and accessors whose accessibility is <c>internal</c> or <c>protected internal</c>, the types nested in
    /// internal types, the interfaces implemented by a type and the explicit implementations of the members of internal interfaces. <see cref="PublicApiSymbol.Accessibility"/>
    /// reports <see cref="PublicApiAccessibility.Internal"/>, so <see cref="PublicApiFormatter"/> writes <c>internal</c> (e.g. <c>public int Value { get; internal set; }</c>).
    /// A member that hides an internal member inherited from a type of the same assembly is reported as <c>new</c>.
    /// </para>
    /// <para>
    /// <c>private</c> and <c>private protected</c> symbols are never included, nor are the internal types generated by the compiler (e.g. the embedded <c>NullableAttribute</c>,
    /// <c>&lt;PrivateImplementationDetails&gt;</c> or the types declared with the <c>file</c> modifier). The internal members of the types declared in other assemblies are not
    /// considered, even when the assembly is listed in their <c>InternalsVisibleToAttribute</c>.
    /// </para>
    /// <para>The default value is <see langword="false"/>: only the symbols that are visible outside the assembly are read.</para>
    /// </remarks>
    public bool IncludeInternalSymbols { get; set; }
}
