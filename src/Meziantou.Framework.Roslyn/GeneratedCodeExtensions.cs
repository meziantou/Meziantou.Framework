#nullable enable
using System;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Meziantou.Framework.Roslyn;

// https://github.com/dotnet/roslyn/blob/2f1cb17a6c23f1700955937641c39d1785173d71/src/Compilers/Core/Portable/SourceGeneration/GeneratedCodeUtilities.cs
#if !MEZIANTOU_FRAMEWORK_ROSLYN_DISABLE_EMBEDDEDATTRIBUTE
[Microsoft.CodeAnalysis.Embedded]
#endif
internal static partial class GeneratedCodeExtensions
{
    private const string GeneratedCodeOptionName = "generated_code";

    /// <summary>
    /// Indicates whether the syntax tree is considered as generated code, using the same heuristics as the Roslyn analyzer driver:
    /// the file name of <see cref="SyntaxTree.FilePath"/> or an <c>&lt;auto-generated&gt;</c> comment at the beginning of the file.
    /// </summary>
    public static bool IsGeneratedCode(this SyntaxTree syntaxTree, CancellationToken cancellationToken)
    {
        return IsGeneratedCodeFile(syntaxTree.FilePath) || syntaxTree.GetRoot(cancellationToken).HasAutoGeneratedComment();
    }

    /// <summary>
    /// Indicates whether the syntax tree is considered as generated code. The <c>generated_code</c> EditorConfig option takes
    /// precedence over the heuristics used by <see cref="IsGeneratedCode(SyntaxTree, CancellationToken)"/>.
    /// </summary>
    public static bool IsGeneratedCode(this SyntaxTree syntaxTree, AnalyzerOptions analyzerOptions, CancellationToken cancellationToken)
    {
        return syntaxTree.IsGeneratedCode(analyzerOptions.AnalyzerConfigOptionsProvider, cancellationToken);
    }

    /// <summary>
    /// Indicates whether the syntax tree is considered as generated code. The <c>generated_code</c> EditorConfig option takes
    /// precedence over the heuristics used by <see cref="IsGeneratedCode(SyntaxTree, CancellationToken)"/>.
    /// </summary>
    public static bool IsGeneratedCode(this SyntaxTree syntaxTree, AnalyzerConfigOptionsProvider optionsProvider, CancellationToken cancellationToken)
    {
        var options = optionsProvider.GetOptions(syntaxTree);
        if (options.TryGetValue(GeneratedCodeOptionName, out var optionValue) && bool.TryParse(optionValue, out var isGeneratedCode))
            return isGeneratedCode;

        return syntaxTree.IsGeneratedCode(cancellationToken);
    }

    /// <summary>
    /// Indicates whether the file name of the path is one of the well-known generated file names, such as <c>Sample.g.cs</c> or <c>Sample.designer.cs</c>.
    /// </summary>
    public static bool IsGeneratedCodeFile(string? filePath)
    {
        if (filePath is null || filePath.Length is 0)
            return false;

        var fileName = GetFileName(filePath, includeExtension: true);
        if (fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
            return true;

        // Only consider the suffixes when the file has an extension, so "Sample.g" is not considered as generated
        if (IndexOfExtension(fileName) < 0)
            return false;

        var fileNameWithoutExtension = GetFileName(filePath, includeExtension: false);
        return fileNameWithoutExtension.EndsWith(".designer", StringComparison.OrdinalIgnoreCase)
            || fileNameWithoutExtension.EndsWith(".generated", StringComparison.OrdinalIgnoreCase)
            || fileNameWithoutExtension.EndsWith(".g", StringComparison.OrdinalIgnoreCase)
            || fileNameWithoutExtension.EndsWith(".g.i", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// Indicates whether the node starts with a comment containing <c>&lt;auto-generated&gt;</c> or <c>&lt;autogenerated&gt;</c>.
    /// Documentation comments are not considered.
    /// </summary>
    public static bool HasAutoGeneratedComment(this SyntaxNode node)
    {
        if (!node.HasLeadingTrivia)
            return false;

        foreach (var trivia in node.GetLeadingTrivia())
        {
            if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) && !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
                continue;

            // string.Contains(string) is ordinal. The overload taking a StringComparison is not available on netstandard2.0.
#pragma warning disable CA1307 // Specify StringComparison for clarity
#pragma warning disable MA0074 // Avoid implicit culture-sensitive methods
            var text = trivia.ToString();
            if (text.Contains("<auto-generated") || text.Contains("<autogenerated"))
                return true;
#pragma warning restore MA0074
#pragma warning restore CA1307
        }

        return false;
    }

    // Roslyn considers '\', '/' and ':' as separators on every platform, so the result doesn't depend on the current OS
    private static string GetFileName(string path, bool includeExtension)
    {
        var fileNameStart = 0;
        for (var i = path.Length - 1; i >= 0; i--)
        {
            var c = path[i];
            if (c is '\\' or '/' or ':')
            {
                fileNameStart = i + 1;
                break;
            }
        }

        var fileName = fileNameStart is 0 ? path : path.Substring(fileNameStart);
        if (includeExtension)
            return fileName;

        var extensionIndex = IndexOfExtension(fileName);
        return extensionIndex < 0 ? fileName : fileName.Substring(0, extensionIndex);
    }

    /// <summary>
    /// Gets the index of the dot starting the extension of the file name, or <c>-1</c> when there is no extension.
    /// It returns <c>0</c> for ".sample" and <c>-1</c> for "sample.".
    /// </summary>
    private static int IndexOfExtension(string fileName)
    {
        for (var i = fileName.Length - 1; i >= 0; i--)
        {
            var c = fileName[i];
            if (c is '.')
                return i == fileName.Length - 1 ? -1 : i;

            if (c is '\\' or '/' or ':')
                break;
        }

        return -1;
    }
}
