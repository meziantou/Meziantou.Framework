namespace Meziantou.Framework.WebPlatform.Css.Layout;

/// <summary>
/// The state of the layout of a fieldset, stored in <see cref="LayoutBox.LayoutState"/> of its principal box: the placement
/// of its rendered legend, which the painting of its border and of its background depends on (see <see cref="FieldsetFormattingContext"/>).
/// </summary>
internal sealed class FieldsetState
{
    /// <summary>The inline size that the percentages of the paddings of the fieldset resolve against (the one of its containing block): the content box uses it for the paddings it inherits.</summary>
    public double PercentageInlineSize { get; set; }

    /// <summary>Whether the fieldset has a rendered legend.</summary>
    public bool HasLegend { get; set; }

    /// <summary>
    /// The distance from the block-start edge of the border box to the block-start edge of the border as it is painted: the
    /// border is centered on the border box of a legend that is taller than it.
    /// </summary>
    public double BorderOffset { get; set; }

    /// <summary>
    /// The rectangle the border is not painted behind, in the logical coordinates of the border box (in the writing mode of the
    /// fieldset).
    /// </summary>
    public LogicalRect Gap { get; set; }
}

/// <summary>
/// The layout of the principal box of a fieldset (https://html.spec.whatwg.org/multipage/rendering.html#the-fieldset-and-legend-elements):
/// a block container whose children are its rendered legend, if any, and its anonymous fieldset content box (generated by
/// <c>BoxTreeBuilder.WrapFieldsetContents</c>), which holds its other contents.
/// </summary>
/// <remarks>
/// <para>
/// The box is sized as a block container (<see cref="FormattingContext.Layout"/>), with its paddings, which are the ones of the
/// content box: the content box is laid out in the padding box of the fieldset and inherits its paddings (the style of the
/// principal box has no overflow and no columns, see <c>StyleEngine.CreateFieldsetStyles</c>).
/// </para>
/// <para>
/// The rendered legend: "If the computed value of 'inline-size' is 'auto', then the used value is the fit-content inline size"
/// (<see cref="BlockFormattingContext.UsesShrinkToFit"/>); it "is expected to be positioned in the inline direction as is normal
/// for blocks" (its margins and its <c>justify-self</c>, which the <c>align</c> attribute maps to), "constrained in the inline
/// direction by the inline content size of the fieldset as if it had used its computed inline padding", and "positioned in the
/// block-flow direction such that its border box is centered over the border on the block-start side of the fieldset". "The
/// space allocated for the element's border on the block-start side is expected to be the element's
/// 'border-block-start-width' or the rendered legend's margin box size in the fieldset's block-flow direction, whichever is
/// greater": the margin box of a legend that is taller than the border starts at the block-start edge of the border box, and
/// the part of it that spills out past the border takes the start of the content box of the fieldset (it is subtracted from a
/// specified block size); the border, and the background, are then painted lower, centered on the border box of the legend
/// (<see cref="FieldsetState.BorderOffset"/>). The border box of a legend that is smaller than the border is centered in it.
/// </para>
/// <para>
/// The anonymous fieldset content box fills the rest of the content box: its block size is the block size that remains when
/// the one of the fieldset is definite (also its maximum block size, not its minimum one). The baselines of the fieldset are
/// the ones of its content box; its intrinsic inline sizes the greater of the ones of the legend and of the content box.
/// </para>
/// </remarks>
internal sealed class FieldsetFormattingContext : FormattingContext
{
    public static FieldsetFormattingContext Instance { get; } = new();

    private FieldsetFormattingContext()
    {
    }

    public override FormattingContextKind Kind => FormattingContextKind.Block;

    public override BoxFragment Layout(LayoutContext context, ContainerBox box, in ConstraintSpace space)
    {
        // "For the purpose of calculating percentage padding, act as if the padding was calculated for the fieldset element"
        var state = box.LayoutState as FieldsetState ?? new FieldsetState();
        state.PercentageInlineSize = space.PercentageInlineSize;
        box.LayoutState = state;
        return base.Layout(context, box, space);
    }

    protected override ContentLayoutResult LayoutContents(LayoutContext context, ContainerBox box, FragmentBuilder builder, in ContentArea content)
    {
        var writingDirection = content.WritingDirection;
        var legend = BlockFormattingContext.FindRenderedLegend(box);
        var contentBox = BlockFormattingContext.FindFieldsetContent(box);
        var border = writingDirection.ToLogical(box.Style.Layout.Box.BorderWidth);
        var state = box.LayoutState as FieldsetState ?? new FieldsetState { PercentageInlineSize = content.InlineSize };
        box.LayoutState = state;
        state.HasLegend = false;
        state.BorderOffset = 0;

        // The paddings of the fieldset are the ones of its content box, which is laid out in its padding box
        var paddingStart = new LogicalOffset(content.Offset.Inline - border.InlineStart, content.Offset.Block - border.BlockStart);
        var padding = writingDirection.ToLogical(ResolvePadding(box.Style.Layout.Box, state.PercentageInlineSize));
        padding = padding with { InlineStart = paddingStart.Inline, BlockStart = paddingStart.Block };

        // The legend, over the block-start border, between the inline paddings
        var spill = 0d;
        if (legend is not null)
        {
            var fragment = context.LayoutBox(legend, ConstraintSpace.ForContentBox(writingDirection, content.InlineSize, content.PercentageBlockSize) with { AvailableBlockSize = null });
            var margin = writingDirection.ToLogical(fragment.Margin);
            var size = writingDirection.ToLogical(fragment.Size);
            var marginBoxSize = margin.BlockStart + size.Block + margin.BlockEnd;

            // The offset of the border box of the legend from the block-start edge of the border box of the fieldset, as in
            // Blink (WPT legend-block-margins-2.html): a margin box that is taller than the border starts at the block-start
            // edge of the border box; else the border box of a legend that is smaller than the border is centered in it (its
            // margins are ignored), and a taller one (with negative margins) is not moved before the border
            double legendOffset;
            if (marginBoxSize > border.BlockStart)
            {
                legendOffset = margin.BlockStart;
                spill = marginBoxSize - border.BlockStart;
            }
            else
            {
                legendOffset = size.Block < border.BlockStart ? (border.BlockStart - size.Block) / 2 : Math.Max(margin.BlockStart, border.BlockStart - size.Block);
            }

            builder.AddChild(fragment, new LogicalOffset(content.Offset.Inline + margin.InlineStart, legendOffset));

            // The border is painted centered on the border box of the legend, in the space allocated for it. "The border is
            // expected to not be painted behind the rectangle defined as follows": the border box of the legend in the inline
            // axis, its margin box and the border in the block axis
            var borderOffset = Math.Clamp(legendOffset + ((size.Block - border.BlockStart) / 2), 0, spill);
            var gapStart = Math.Min(borderOffset, legendOffset - margin.BlockStart);
            var gapEnd = Math.Max(borderOffset + border.BlockStart, legendOffset + size.Block + margin.BlockEnd);
            state.HasLegend = true;
            state.BorderOffset = borderOffset;
            state.Gap = new LogicalRect(new LogicalOffset(content.Offset.Inline + margin.InlineStart, gapStart), new LogicalSize(size.Inline, gapEnd - gapStart));
        }

        if (contentBox is null)
            return new ContentLayoutResult(spill);

        // The content box, in the block size that remains: the block size of the fieldset when it does not follow its contents
        var inlineSize = padding.InlineStart + content.InlineSize + padding.InlineEnd;
        var blockPadding = padding.BlockStart + padding.BlockEnd;
        var definiteBlockSize = content.BlockSize is { } definite && !content.BlockSizeGrowsToContents ? definite : (double?)null;
        var contentFragment = LayoutContentBox(context, contentBox, writingDirection, inlineSize, state.PercentageInlineSize, definiteBlockSize is { } target ? Math.Max(0, target - spill) + blockPadding : null);
        var blockSize = spill + writingDirection.ToLogical(contentFragment.Size).Block - blockPadding;
        var intrinsicBlockSize = blockSize;
        if (definiteBlockSize is null)
        {
            // The fieldset is as tall as its contents, within its minimum and maximum block sizes. "The 'block-size' property is
            // expected to be set to '100%'" of the content box: the content box is limited by the maximum block size of the fieldset
            // (it scrolls in it), but it does not fill its minimum block size, as in Blink (the percentage of a block size that
            // depends on the contents behaves as auto, WPT css/css-flexbox/fieldset-as-container-justify-center.tentative.html,
            // https://github.com/whatwg/html/issues/9123); the block size given by the aspect ratio, which grows with the contents,
            // is definite: the content box fills it
            var minimum = content.MinBlockSize ?? 0;
            var used = content.BlockSize is { } transferred
                ? Math.Max(Math.Min(Math.Max(blockSize, transferred), content.MaxBlockSize ?? double.PositiveInfinity), minimum)
                : Math.Min(blockSize, Math.Max(content.MaxBlockSize ?? double.PositiveInfinity, minimum));

            if (Math.Abs(used - blockSize) > 0.01)
            {
                contentFragment = LayoutContentBox(context, contentBox, writingDirection, inlineSize, state.PercentageInlineSize, Math.Max(0, used - spill) + blockPadding);
            }
        }
        else if (!double.IsNaN(contentFragment.IntrinsicBlockSize))
        {
            intrinsicBlockSize = spill + contentFragment.IntrinsicBlockSize - blockPadding;
        }

        builder.AddChild(contentFragment, new LogicalOffset(border.InlineStart, border.BlockStart + spill));
        var sameBlockFlow = contentFragment.WritingDirection.BlockStart == writingDirection.BlockStart;
        var baselineOffset = spill - padding.BlockStart;

        // (the baseline of an inline-level flex or grid fieldset is the first baseline of its content box, as for the
        // inline-level flex and grid containers)
        var lastBaseline = content.UsesInlineBlockBaseline && contentBox.EstablishesIndependentChildrenLayout ? contentFragment.FirstBaseline : contentFragment.LastBaseline;
        return new ContentLayoutResult(
            Math.Max(0, intrinsicBlockSize),
            sameBlockFlow ? baselineOffset + contentFragment.FirstBaseline : null,
            sameBlockFlow ? baselineOffset + lastBaseline : null);
    }

    private static BoxFragment LayoutContentBox(LayoutContext context, ContainerBox contentBox, WritingDirection writingDirection, double inlineSize, double percentageInlineSize, double? blockSize)
    {
        var space = ConstraintSpace.ForContentBox(writingDirection, inlineSize, blockSize) with { PercentageInlineSize = percentageInlineSize };
        return context.LayoutBox(contentBox, blockSize is null ? space : space with { FixedBlockSize = blockSize });
    }

    /// <summary>
    /// "For the purpose of calculating the min-content inline size, use the greater of the min-content inline size of the rendered
    /// legend and the min-content inline size of the anonymous fieldset content box", and the same for the max-content inline size.
    /// </summary>
    protected internal override IntrinsicSizes ComputeIntrinsicInlineSizes(LayoutContext context, ContainerBox box, in IntrinsicSizingInput input)
    {
        var writingDirection = WritingDirection.FromStyle(box.Style.Layout);
        var minContent = 0d;
        var maxContent = 0d;
        if (BlockFormattingContext.FindFieldsetContent(box) is { } contentBox)
        {
            // (the paddings of the content box are the ones of the fieldset)
            var padding = writingDirection.ToLogical(ResolvePadding(contentBox.Style.Layout.Box, 0)).InlineSum();
            (minContent, maxContent) = IntrinsicSizing.GetContribution(context, contentBox, writingDirection, input.ContentBlockSize);
            minContent = Math.Max(0, minContent - padding);
            maxContent = Math.Max(0, maxContent - padding);
        }

        if (BlockFormattingContext.FindRenderedLegend(box) is { } legend)
        {
            var (legendMin, legendMax) = IntrinsicSizing.GetContribution(context, legend, writingDirection, null);
            minContent = Math.Max(minContent, legendMin);
            maxContent = Math.Max(maxContent, legendMax);
        }

        return new IntrinsicSizes(minContent, Math.Max(minContent, maxContent));
    }
}
