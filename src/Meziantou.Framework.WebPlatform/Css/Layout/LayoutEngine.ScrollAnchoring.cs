using Meziantou.Framework.WebPlatform.Css.Cascade;
using Meziantou.Framework.WebPlatform.Dom;
using Meziantou.Framework.WebPlatform.Html;

namespace Meziantou.Framework.WebPlatform.Css.Layout;

// Scroll anchoring (https://drafts.csswg.org/css-scroll-anchoring/): before a layout pass, each scrolling box selects an anchor node
// (with the geometry of the previous pass) and saves the position of its block-start edge; after the pass, the scroll position
// is adjusted by the movement of that edge, unless a suppression trigger occurred. The algorithms follow Blink's ScrollAnchor
// (the reference implementation the WPT tests are written against): the anchor is selected in the box tree (the boxes of the
// elements, of the pseudo-elements and of the text nodes, not the non-atomic inline boxes nor the anonymous boxes), with the
// styles computed for the pass (overflow-anchor, position) and the geometry of the previous pass.
internal sealed partial class LayoutEngine
{
    /// <summary>The adjustments smaller than this (in CSS px) are rounding errors: they are not applied.</summary>
    private const double ScrollAnchoringEpsilon = 1.0 / 1024;

    /// <summary>
    /// The properties whose change on the anchor node or on one of its ancestors up to the scroll container suppresses the
    /// adjustment (https://drafts.csswg.org/css-scroll-anchoring/#suppression-triggers).
    /// </summary>
    private static readonly string[] ScrollAnchoringDisablingProperties =
    [
        "top", "right", "bottom", "left",
        "margin-top", "margin-right", "margin-bottom", "margin-left",
        "padding-top", "padding-right", "padding-bottom", "padding-left",
        "width", "height", "min-width", "max-width", "min-height", "max-height",
        "position", "transform",
    ];

    /// <summary>The scrolling boxes whose anchoring adjustment is queued by the layout pass in progress.</summary>
    private List<ScrollState>? _queuedScrollAnchors;

    /// <summary>The box tree discarded by <see cref="SetNeedsLayout"/> (its boxes have the fragments of the last pass), until the next pass.</summary>
    private BoxTree? _discardedBoxTree;

    /// <summary>
    /// Selects the anchor nodes of the scrolling boxes that have none and saves the positions of the anchors, before a layout
    /// pass, with the fragments of the previous pass; queues their adjustments. Returns whether an adjustment is queued.
    /// </summary>
    /// <param name="previousBoxTree">The box tree of the previous pass.</param>
    /// <param name="stylesChanged">Whether the computed styles changed since the previous pass (the box tree is built again).</param>
    private bool QueueScrollAnchoringAdjustments(BoxTree? previousBoxTree, bool stylesChanged)
    {
        _queuedScrollAnchors = null;
        if (_root is null || previousBoxTree is null)
            return false;

        var search = new ScrollAnchorSearch(this, previousBoxTree, stylesChanged ? _document.GetStyleEngine() : null);
        var priorityCandidate = GetPriorityCandidate();
        foreach (var state in EnumerateScrollStates())
        {
            if (state.Fragment is not { } fragment || state.LayoutVersion != _fragmentIndexVersion)
            {
                state.Anchor = null;
                continue;
            }

            // Only the scrolling boxes that can scroll in their block flow direction are anchored (as in Blink). "If S is not scrolled
            // away from the origin of its scrolling area in its block flow direction, then do not select an anchor node for S" (a
            // suppression trigger: "The scroll offset of the scrollable element being zero"), nor when "S is generated by an element
            // whose computed value of the overflow-anchor property is none" (https://drafts.csswg.org/css-scroll-anchoring/#anchoring-algorithm)
            var horizontal = state.WritingDirection.IsHorizontal;
            var canScroll = horizontal ? state.MinOffset.Y != state.MaxOffset.Y : state.MinOffset.X != state.MaxOffset.X;
            if (!canScroll || (horizontal ? state.Offset.Y : state.Offset.X) == 0
                || (!state.IsViewport && (search.GetCurrentStyle(fragment.Box) is not { } style || IsOverflowAnchorNone(style))))
            {
                state.Anchor = null;
                continue;
            }

            // A change of the focused editable element changes the priority candidate: the anchor is selected again
            // A change of overflow-anchor invalidates the anchors of the scrolling boxes that contain the element (as Blink)
            if (state.Anchor is { } previous && (!ReferenceEquals(previous.PriorityCandidate, priorityCandidate) || (stylesChanged && search.IsOverflowAnchorChanged(fragment.Box))))
            {
                state.Anchor = null;
            }

            state.Anchor ??= search.FindAnchor(state, priorityCandidate);
            if (state.Anchor is not { } anchor)
                continue;

            anchor.Suppressed = stylesChanged && search.HasScrollAnchorDisablingStyleChange(state, anchor);
            anchor.Queued = true;
            (_queuedScrollAnchors ??= []).Add(state);
        }

        return _queuedScrollAnchors is not null;
    }

    /// <summary>
    /// Performs the anchoring adjustments queued before the layout pass (https://drafts.csswg.org/css-scroll-anchoring/#scroll-adjustment),
    /// at the end of the pass: the end of the suppression window (https://drafts.csswg.org/css-scroll-anchoring/#suppression-windows)
    /// is the end of the update of the layout, by the rendering steps or by a forced layout (an operation whose result depends
    /// on the scroll position).
    /// </summary>
    private void PerformScrollAnchoringAdjustments()
    {
        if (_queuedScrollAnchors is not { } queued)
            return;

        _queuedScrollAnchors = null;

        // The nested scrolling boxes are adjusted first: the anchor of a scrolling box may be in a nested one
        if (queued.Count > 1)
        {
            queued.Sort(static (a, b) => GetDepth(b.Fragment).CompareTo(GetDepth(a.Fragment)));
        }

        foreach (var state in queued)
        {
            if (state.Anchor is not { Queued: true } anchor)
                continue;

            anchor.Queued = false;
            if (state.Fragment is null || state.LayoutVersion != _fragmentIndexVersion || _boxTree is null
                || !TryGetAnchorBlockStart(_boxTree, state, anchor.Node, anchor.PseudoElement, out var blockStart))
            {
                // The anchor node was removed (or does not generate a box anymore)
                state.Anchor = null;
                continue;
            }

            // An anchor selected while some contents were replaced (removed nodes were skipped, the new ones had no geometry) is
            // selected again by the next pass, with the geometry of the new contents (as Gecko: a deeper anchor may be found)
            if (anchor.ReselectAfterAdjustment)
            {
                state.Anchor = null;
            }

            // The adjustment is the movement of the block-start edge in the block flow direction ("y1 - y0")
            var delta = blockStart - anchor.SavedBlockStart;
            if (Math.Abs(delta) < ScrollAnchoringEpsilon)
                continue;

            if (anchor.Suppressed)
            {
                // A suppressed adjustment invalidates the anchor (only when the adjustment is not zero, as in Blink)
                state.Anchor = null;
                continue;
            }

            var position = state.Clamp(state.WritingDirection.IsHorizontal ? new PhysicalOffset(state.Offset.X, state.Offset.Y + delta) : new PhysicalOffset(state.Offset.X + delta, state.Offset.Y));
            var applied = position - state.Offset;
            if (!ApplyScrollPosition(state, position))
                continue;

            DeferScrollEvent(state);

            // The anchoring adjustment is not an explicit scroll: the anchor stays valid, no scrollend event is fired, and a smooth
            // scroll in progress is moved with the contents
            state.AnchoringAdjustments += applied;
            if (state.SmoothScroll is { } smooth)
            {
                state.SmoothScroll = new SmoothScroll(smooth.Start + applied, state.Clamp(smooth.Target + applied), smooth.StartTimestamp);
            }
        }

        static int GetDepth(Fragment? fragment)
        {
            var depth = 0;
            for (var current = fragment; current is not null; current = current.Parent)
            {
                depth++;
            }

            return depth;
        }
    }

    /// <summary>
    /// Invalidates the anchor node of a scrolling box whose scroll position changes (excluding the adjustments of the scroll
    /// anchoring, https://drafts.csswg.org/css-scroll-anchoring/#anchor-node-invalidation), and the ones of the scrolling boxes that
    /// contain it (the positions of the nodes in the box changed relative to them), as Blink.
    /// </summary>
    private static void InvalidateScrollAnchors(ScrollState state)
    {
        state.Anchor = null;
        for (var fragment = state.Fragment?.Parent; fragment is not null; fragment = fragment.Parent)
        {
            if (fragment is BoxFragment { ScrollState: { } ancestor })
            {
                ancestor.Anchor = null;
            }
        }
    }

    /// <summary>
    /// Returns the priority candidate of the anchor node selection (https://drafts.csswg.org/css-scroll-anchoring/#anchor-priority-candidates):
    /// the focused element when it is text editable (an editing host or editable, a mutable textarea, or a mutable input whose
    /// type allows text entry), or null. The active match of find-in-page does not apply (there is no find-in-page).
    /// </summary>
    private Element? GetPriorityCandidate()
    {
        if (FocusModel.GetFocusedElement(_document) is not { } focused)
            return null;

        var editable = focused switch
        {
            HtmlTextAreaElement textArea => textArea.IsMutable,
            HtmlInputElement input => input.IsMutable && input.AllowsTextEntry,
            _ => Editing.IsEditingHost(focused) || Editing.IsEditable(focused),
        };
        return editable ? focused : null;
    }

    /// <summary>Whether the computed value of overflow-anchor is none (https://drafts.csswg.org/css-scroll-anchoring/#exclusion-api).</summary>
    private static bool IsOverflowAnchorNone(ComputedStyle style) => style.GetComputedValue("overflow-anchor") == "none";

    /// <summary>Returns the box of an anchor node in a box tree: the principal box of an element, the box of a pseudo-element, or the first text run of a text node.</summary>
    private static LayoutBox? GetAnchorBox(BoxTree tree, Node node, string? pseudoElement) => node switch
    {
        Text text => tree.GetFirstTextRun(text),
        Element element => pseudoElement is null ? tree.GetPrincipalBox(element) : tree.GetPseudoElementBox(element, pseudoElement),
        _ => null,
    };

    /// <summary>
    /// Returns the position of the block-start edge of the scroll anchoring bounding rect of an anchor node in the visible
    /// contents of a scrolling box (see <see cref="ScrollAnchor.SavedBlockStart"/>).
    /// </summary>
    private bool TryGetAnchorBlockStart(BoxTree tree, ScrollState state, Node node, string? pseudoElement, out double blockStart)
    {
        blockStart = 0;
        if (GetAnchorBox(tree, node, pseudoElement) is not { } box || !TryGetScrollAnchoringRect(box, state, out var rect))
            return false;

        blockStart = GetBlockStart(state, rect);
        return true;
    }

    /// <summary>
    /// The block-start edge of a rectangle in the block flow direction of a scrolling box (the top, the left or the right edge),
    /// from the block-start edge of its scrollport: a change of the size of the scrollport does not move the contents that are
    /// laid out from its block-start edge (the right edge in <c>vertical-rl</c>).
    /// </summary>
    private static double GetBlockStart(ScrollState state, PhysicalRect rect)
    {
        var writingDirection = state.WritingDirection;
        var scrollport = state.Scrollport;
        if (writingDirection.IsHorizontal)
            return rect.Top - scrollport.Top;

        return writingDirection.IsFlippedBlocks ? rect.Right - scrollport.Right : rect.Left - scrollport.Left;
    }

    /// <summary>
    /// Returns the scroll anchoring bounding rect of a box (https://drafts.csswg.org/css-scroll-anchoring/#scroll-anchoring-bounding-rect)
    /// in the visible contents of a scrolling box (the coordinates of its scroll container minus its scroll position): the union of
    /// its fragments (of the text fragments of all the runs of a text node), each extended to the bottom of its scrollable
    /// overflow unless it clips its overflow (as Blink). Returns false when the box has no fragment in the scroll container.
    /// </summary>
    private bool TryGetScrollAnchoringRect(LayoutBox box, ScrollState state, out PhysicalRect rect)
    {
        rect = default;
        var found = false;
        for (var part = box; part is not null; part = part is TextRun run ? run.NextRunOfNode : null)
        {
            for (var fragment = GetFirstFragment(part); fragment is not null; fragment = fragment.NextFragmentOfBox)
            {
                var local = fragment.LocalRect;
                if (fragment is BoxFragment { ClipsOverflow: false } boxFragment)
                {
                    var bottom = Math.Max(local.Bottom, boxFragment.ScrollableOverflow.Bottom);
                    local = local with { Height = bottom - local.Y };
                }

                if (!TryMapToVisibleContents(fragment, local, state, out var mapped))
                    return false;

                rect = found ? rect.Union(mapped) : mapped;
                found = true;
            }
        }

        return found;
    }

    /// <summary>
    /// Maps a rectangle in the coordinates of a fragment to the visible contents of a scrolling box: the coordinates of its scroll
    /// container, minus its scroll position (applying the transforms and the scroll positions of the fragments between them).
    /// Returns false when the fragment is not in the scroll container.
    /// </summary>
    private static bool TryMapToVisibleContents(Fragment fragment, PhysicalRect rect, ScrollState state, out PhysicalRect result)
    {
        result = default;
        var scroller = state.Fragment;
        var quad = new PhysicalQuad(rect);
        for (var current = fragment; !ReferenceEquals(current, scroller); current = current.Parent)
        {
            if (current is null)
                return false;

            if (GetTransform(current) is { } matrix)
            {
                quad = new PhysicalQuad(Transform(matrix, quad.P1), Transform(matrix, quad.P2), Transform(matrix, quad.P3), Transform(matrix, quad.P4));
            }

            quad = quad.Translate(GetScrolledOffset(current));
        }

        // The scroll position of the children of the viewport is applied by ToViewport, not by GetScrolledOffset
        if (state.IsViewport)
        {
            quad = quad.Translate(-state.Offset);
        }

        result = quad.Bounds;
        return true;

        static PhysicalOffset Transform(double[] matrix, PhysicalOffset point) => LayoutTransforms.TryTransformPoint(matrix, point, out var transformed) ? transformed : point;
    }

    /// <summary>The status of a box examined by the anchor node selection (Blink's WalkStatus).</summary>
    private enum AnchorWalkStatus
    {
        /// <summary>The box and its descendants are not candidates.</summary>
        Skip,

        /// <summary>The box is a partially visible candidate: a better anchor may be among its descendants.</summary>
        Constrain,

        /// <summary>The box is not a candidate, but its descendants may be.</summary>
        Continue,

        /// <summary>The box is a fully visible candidate: it is selected.</summary>
        Return,
    }

    /// <summary>The anchor node selection of the scrolling boxes before a layout pass (https://drafts.csswg.org/css-scroll-anchoring/#anchor-node-selection).</summary>
    private sealed class ScrollAnchorSearch(LayoutEngine engine, BoxTree boxTree, StyleEngine? styleEngine)
    {
        private ScrollState _state = null!;
        private ContainerBox _scrollerBox = null!;
        private PhysicalRect _visibleRect;
        private LayoutBox? _anchor;
        private HashSet<LayoutBox>? _outOfFlowChanges;
        private HashSet<LayoutBox>? _overflowAnchorChanges;
        private bool _styleChangesCollected;
        private bool _sawRemovedNode;

        /// <summary>
        /// Returns the computed style of the element (or pseudo-element) of a box for the layout pass in progress: the styles may
        /// have changed since the box tree of the previous pass was built. Returns null when the element was removed.
        /// </summary>
        public ComputedStyle? GetCurrentStyle(LayoutBox box)
        {
            if (styleEngine is null || box.Element is not { } element || box is ContainerBox { IsAnonymous: true })
                return box.Style;

            return element.IsConnected ? styleEngine.GetStyle(element, box.PseudoElement) : null;
        }

        /// <summary>The anchor node selection algorithm (https://drafts.csswg.org/css-scroll-anchoring/#anchoring-algorithm) for a scrolling box.</summary>
        public ScrollAnchor? FindAnchor(ScrollState state, Element? priorityCandidate)
        {
            _state = state;
            _scrollerBox = state.Fragment!.Box;
            _anchor = null;
            _sawRemovedNode = false;
            _visibleRect = state.ContainerStyle is { } containerStyle ? ScrollIntoView.ApplyScrollPadding(state.Scrollport, containerStyle.Overflow.ScrollPadding) : state.Scrollport;

            // "For each priority candidate PC in order specified, check if PC is a viable candidate in S. If so, perform the candidate
            // examination algorithm for PC in S and terminate."
            var foundPriority = false;
            if (priorityCandidate is not null && GetPriorityCandidateBox(priorityCandidate) is { } candidate && IsViable(ExaminePriorityCandidate(candidate)))
            {
                _anchor = candidate;
                FindAnchorRecursive(candidate);
                foundPriority = true;
            }

            // "Otherwise, for each DOM child N of the element or document associated with S, perform the candidate examination algorithm"
            if (!foundPriority)
            {
                FindAnchorRecursive(_scrollerBox);
            }

            if (_anchor is not { } anchor)
                return null;

            // The anchor is identified by its node (the box of a table is its table wrapper box)
            if (anchor is ContainerBox { Kind: ContainerBoxKind.TableGrid, Parent: { } wrapper })
            {
                anchor = wrapper;
            }

            var (node, pseudoElement) = anchor is TextRun run ? ((Node?)run.Node, (string?)null) : (anchor.Element, anchor.PseudoElement);
            if (node is null || !engine.TryGetAnchorBlockStart(boxTree, state, node, pseudoElement, out var blockStart))
                return null;

            return new ScrollAnchor(node, pseudoElement, priorityCandidate, blockStart) { ReselectAfterAdjustment = _sawRemovedNode };
        }

        private static bool IsViable(AnchorWalkStatus status) => status is AnchorWalkStatus.Constrain or AnchorWalkStatus.Return;

        /// <summary>
        /// The candidate examination algorithm (https://drafts.csswg.org/css-scroll-anchoring/#candidate-examination), as Blink: the
        /// descendants of a partially visible box are examined, then its absolutely positioned descendants whose containing block
        /// it is (their box is not its child); the deepest viable candidate is selected.
        /// </summary>
        private AnchorWalkStatus FindAnchorRecursive(LayoutBox candidate)
        {
            var status = Examine(candidate);
            if (IsViable(status))
            {
                _anchor = candidate;
            }

            if (status is AnchorWalkStatus.Return or AnchorWalkStatus.Skip || candidate is not ContainerBox container)
                return status;

            // In a multi-column container, an absolutely positioned descendant may be a better anchor than a partially visible child
            var isFragmentationRoot = container.Kind != ContainerBoxKind.Viewport && container.Style.Layout.IsMultiColumnContainer;
            for (var child = container.FirstChild; child is not null; child = child.NextSibling)
            {
                var childStatus = FindAnchorRecursive(child);
                if (childStatus == AnchorWalkStatus.Return)
                    return childStatus;

                if (childStatus == AnchorWalkStatus.Constrain)
                {
                    if (!isFragmentationRoot)
                        return childStatus;

                    status = childStatus;
                    break;
                }
            }

            // "For each absolutely-positioned element A whose containing block is N, but whose DOM parent is not N, perform the
            // candidate examination algorithm for A in S"
            var outOfFlowStatus = FindAnchorInOutOfFlowDescendants(container);
            return IsViable(outOfFlowStatus) ? outOfFlowStatus : status;
        }

        private AnchorWalkStatus FindAnchorInOutOfFlowDescendants(ContainerBox candidate)
        {
            for (var fragment = engine.GetFirstFragment(candidate); fragment is not null; fragment = fragment.NextFragmentOfBox)
            {
                foreach (var child in fragment.ChildrenSpan)
                {
                    if (child is BoxFragment { Box: { IsAnonymous: false, Style.Layout.IsAbsolutelyPositioned: true } box } && !ReferenceEquals(box.Parent, candidate) && ReferenceEquals(engine.GetFirstFragment(box), child))
                    {
                        var status = FindAnchorRecursive(box);
                        if (IsViable(status))
                            return status;
                    }
                }
            }

            return AnchorWalkStatus.Skip;
        }

        /// <summary>Examines a candidate box: whether it is a viable candidate (https://drafts.csswg.org/css-scroll-anchoring/#anchor-viable-candidate), fully visible or not.</summary>
        private AnchorWalkStatus Examine(LayoutBox candidate)
        {
            if (ReferenceEquals(candidate, _scrollerBox))
                return AnchorWalkStatus.Continue;

            if (GetCurrentStyle(candidate) is not { } style)
            {
                // A removed node: the contents changed since the previous pass, and the new nodes have no geometry yet
                _sawRemovedNode = true;
                return AnchorWalkStatus.Skip;
            }

            if (IsOverflowAnchorNone(style))
                return AnchorWalkStatus.Skip;

            // "C is an element that is not a non-atomic inline": the descendants of an inline box are candidates. The anonymous
            // boxes are not in the DOM (the anchor would be hard to reason about), and neither are the generated texts
            if (candidate is ContainerBox { IsInlineBox: true } or ContainerBox { IsAnonymous: true } or TextRun { Node: null })
                return AnchorWalkStatus.Continue;

            if (style.Layout.Display.IsNone || !CandidateMayMoveWithScroller(candidate, style))
                return AnchorWalkStatus.Skip;

            if (!engine.TryGetScrollAnchoringRect(candidate, _state, out var rect))
                return AnchorWalkStatus.Skip;

            // Fully visible, partially visible or fully clipped (https://drafts.csswg.org/css-scroll-anchoring/#fully-visible): a box
            // that occupies no space is not a candidate (as in Blink)
            var visible = _visibleRect;
            var occupiesSpace = rect.Width > 0 && rect.Height > 0;
            if (!occupiesSpace || visible.IsEmpty || rect.Left >= visible.Right || visible.Left >= rect.Right || rect.Top >= visible.Bottom || visible.Top >= rect.Bottom)
                return AnchorWalkStatus.Skip;

            var contained = visible.Left <= rect.Left && rect.Right <= visible.Right && visible.Top <= rect.Top && rect.Bottom <= visible.Bottom;
            return contained ? AnchorWalkStatus.Return : AnchorWalkStatus.Constrain;
        }

        /// <summary>
        /// Whether a candidate moves with the scrolling contents (https://drafts.csswg.org/css-scroll-anchoring/#excluded-subtree):
        /// not a fixed or sticky positioned box, nor an absolutely positioned box whose containing block is outside the scroll
        /// container (its fragment is not in the one of the scroll container).
        /// </summary>
        private bool CandidateMayMoveWithScroller(LayoutBox candidate, ComputedStyle style)
        {
            // The geometry of the previous pass is used with the current styles: a box that was or becomes fixed or sticky positioned
            // is excluded (its previous position may be relative to the viewport)
            if (candidate is ContainerBox && (style.Layout.Position is PositionKind.Fixed or PositionKind.Sticky || candidate.Style.Layout.Position is PositionKind.Fixed or PositionKind.Sticky))
                return false;

            // A box without fragment (e.g. an empty inline box) has no rect: it is not selected
            if (engine.GetFirstFragment(candidate) is not { } first)
                return true;

            var scroller = _state.Fragment;
            for (Fragment? fragment = first; fragment is not null; fragment = fragment.Parent)
            {
                if (ReferenceEquals(fragment, scroller))
                    return true;
            }

            return false;
        }

        /// <summary>
        /// Returns the box of a priority candidate: "if the priority candidate is a non-atomic inline element, then instead consider
        /// its nearest ancestor element that is not a non-atomic inline element".
        /// </summary>
        private ContainerBox? GetPriorityCandidateBox(Element element)
        {
            for (Node? node = element; node is not null; node = HtmlElement.GetFlatTreeParent(node))
            {
                if (node is Element ancestor && boxTree.GetPrincipalBox(ancestor) is { IsAnonymous: false, IsInlineBox: false } box && engine.GetFirstFragment(box) is not null)
                    return box;
            }

            return null;
        }

        /// <summary>Examines a priority candidate: it must be in the scroll container, outside of the excluded subtrees (https://drafts.csswg.org/css-scroll-anchoring/#anchor-viable-candidate).</summary>
        private AnchorWalkStatus ExaminePriorityCandidate(LayoutBox candidate)
        {
            for (LayoutBox? ancestor = candidate; ancestor is not null; ancestor = ancestor.Parent)
            {
                if (ReferenceEquals(ancestor, _scrollerBox))
                    return Examine(candidate);

                if (GetCurrentStyle(ancestor) is not { } style || IsOverflowAnchorNone(style) || !CandidateMayMoveWithScroller(ancestor, style))
                    return AnchorWalkStatus.Skip;
            }

            return AnchorWalkStatus.Skip;
        }

        /// <summary>
        /// Whether a suppression trigger occurred since the previous layout pass (https://drafts.csswg.org/css-scroll-anchoring/#suppression-triggers):
        /// a change of the computed value of a property that affects the position on the anchor node or on an ancestor up to the
        /// scroll container, or an element of the scroll container that became or stopped being absolutely positioned (as in
        /// Blink, the nearest scroll container of the element, or the root element, is marked, and the adjustment is suppressed
        /// when it is on the path from the anchor node to the scroll container).
        /// </summary>
        public bool HasScrollAnchorDisablingStyleChange(ScrollState state, ScrollAnchor anchor)
        {
            if (GetAnchorBox(boxTree, anchor.Node, anchor.PseudoElement) is not { } box)
                return false;

            EnsureStyleChangesCollected();
            var scrollerBox = state.Fragment!.Box;
            for (LayoutBox? current = box; current is not null; current = current.Parent)
            {
                if (_outOfFlowChanges is not null && _outOfFlowChanges.Contains(current))
                    return true;

                if (current is ContainerBox { IsAnonymous: false, Kind: not ContainerBoxKind.Viewport } && HasDisablingPropertyChange(current))
                    return true;

                if (ReferenceEquals(current, scrollerBox))
                    break;
            }

            return false;
        }

        private bool HasDisablingPropertyChange(LayoutBox box)
        {
            var previous = box.Style;
            if (GetCurrentStyle(box) is not { } current || ReferenceEquals(previous, current))
                return false;

            foreach (var property in ScrollAnchoringDisablingProperties)
            {
                if (!string.Equals(previous.GetComputedValue(property), current.GetComputedValue(property), StringComparison.Ordinal))
                    return true;
            }

            return false;
        }

        /// <summary>Whether the overflow-anchor of an element contained by a scroll container (or by the viewport) changed since the previous layout pass.</summary>
        public bool IsOverflowAnchorChanged(ContainerBox scrollerBox)
        {
            EnsureStyleChangesCollected();
            return _overflowAnchorChanges is not null && _overflowAnchorChanges.Contains(scrollerBox);
        }

        /// <summary>
        /// Compares the styles of the boxes of the previous pass with the current ones: marks the nearest scroll container (or the
        /// root element) of the elements that became or stopped being absolutely positioned, and the scroll containers (and the
        /// viewport) that contain an element whose overflow-anchor changed. The elements whose display became none are skipped
        /// with their descendants (their boxes are removed).
        /// </summary>
        private void EnsureStyleChangesCollected()
        {
            if (_styleChangesCollected)
                return;

            _styleChangesCollected = true;
            if (boxTree.Viewport is not { } viewport)
                return;

            var stack = new Stack<ContainerBox>();
            stack.Push(viewport);
            while (stack.TryPop(out var container))
            {
                for (var child = container.FirstChild; child is not null; child = child.NextSibling)
                {
                    if (child is not ContainerBox box)
                        continue;

                    var style = box.IsAnonymous || box.Kind == ContainerBoxKind.TableGrid ? null : GetCurrentStyle(box);

                    // An element that stops generating boxes (display: none) is not a change of its position or of the position of
                    // its descendants: its box is removed (as Blink, which destroys its layout object without a style change)
                    if (style is not null && style.Layout.Display.IsNone)
                        continue;

                    stack.Push(box);
                    if (style is null || ReferenceEquals(style, box.Style))
                        continue;

                    if (style.Layout.IsAbsolutelyPositioned != box.Style.Layout.IsAbsolutelyPositioned)
                    {
                        for (var ancestor = box.Parent; ancestor is not null; ancestor = ancestor.Parent)
                        {
                            if (ancestor.Parent is { Kind: ContainerBoxKind.Viewport } || engine.GetFirstFragment(ancestor) is BoxFragment { IsScrollContainer: true })
                            {
                                (_outOfFlowChanges ??= new(ReferenceEqualityComparer.Instance)).Add(ancestor);
                                break;
                            }
                        }
                    }

                    if (IsOverflowAnchorNone(style) != IsOverflowAnchorNone(box.Style))
                    {
                        for (var ancestor = box.Parent; ancestor is not null; ancestor = ancestor.Parent)
                        {
                            if (ancestor.Kind == ContainerBoxKind.Viewport || engine.GetFirstFragment(ancestor) is BoxFragment { IsScrollContainer: true })
                            {
                                (_overflowAnchorChanges ??= new(ReferenceEqualityComparer.Instance)).Add(ancestor);
                            }
                        }
                    }
                }
            }
        }
    }
