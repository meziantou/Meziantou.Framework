using Meziantou.Framework.WebPlatform.Css.Cascade;
using Meziantou.Framework.WebPlatform.Dom;

namespace Meziantou.Framework.WebPlatform.Css.Layout;

/// <summary>
/// The contents of the form controls that are replaced boxes (their natural sizes are the ones of <see cref="FormControlSizing"/>)
/// and whose parts are boxes, as the inner editor of the text controls (see <see cref="TextControlLayout"/>): the child of the
/// replaced box of the control is an anonymous block container (<see cref="ContainerBox.IsFormControlContents"/>) laid out in
/// its content box by <see cref="ReplacedFormattingContext"/>. The specification describes these parts as the user agent
/// sees fit (the browsers use shadow trees of the user agent); the library has none: the boxes are generated by
/// <see cref="BoxTreeBuilder"/>.
/// </summary>
/// <remarks>
/// <para>
/// A list box with native appearance (https://html.spec.whatwg.org/multipage/rendering.html#the-select-element-2: a select
/// element with a <c>multiple</c> attribute or a display size greater than 1): its contents box holds the boxes of its
/// children in the flat tree, the options being its rows. The list box is the scroll container of its rows, as a
/// <c>textarea</c> is the one of its inner editor (see <see cref="ScrollContainers.GetUsedOverflow"/>): it scrolls in its
/// block axis.
/// </para>
/// <para>
/// A slider-like control (https://drafts.csswg.org/css-forms-1/#slider-pseudos: an <c>input</c> element of type range, a
/// <c>meter</c> or a <c>progress</c> element) with primitive appearance (<c>appearance: none</c>): its contents box, which
/// has the size of its content box, holds the boxes of its <c>::slider-track</c> pseudo-element, which holds the box of its
/// <c>::slider-fill</c>, and of its <c>::slider-thumb</c>. With native appearance, the control is painted as a widget.
/// </para>
/// </remarks>
internal static class FormControlContents
{
    /// <summary>The names of the tree-abiding pseudo-elements of the slider-like controls (https://drafts.csswg.org/css-forms-1/#slider-pseudos).</summary>
    public const string SliderTrack = "slider-track";
    public const string SliderFill = "slider-fill";
    public const string SliderThumb = "slider-thumb";

    /// <summary>The name of the pseudo-element of the button of a file upload control (https://drafts.csswg.org/css-forms-1/#file-selector-button-pseudo).</summary>
    public const string FileSelectorButton = "file-selector-button";

    /// <summary>
    /// Whether the element is a file upload control (https://html.spec.whatwg.org/multipage/rendering.html#the-input-element-as-a-file-upload-control):
    /// it is not a replaced box, but an inline-block box that holds the box of its button and its text.
    /// </summary>
    public static bool IsFileUploadControl(Element? element) => element is HtmlInputElement { InputType: InputType.File };

    /// <summary>The label of the button of a file upload control.</summary>
    public static string GetFileSelectorButtonLabel(HtmlInputElement input) => input.HasAttributeWithLocalName("multiple") ? "Choose Files" : "Choose File";

    /// <summary>The text of a file upload control: the name of the selected file, or the number of selected files.</summary>
    public static string GetFileUploadText(HtmlInputElement input) => input.Files switch
    {
        null or { Length: 0 } => "No file chosen",
        { Length: 1 } files => files[0]?.Name ?? "",
        var files => files.Length.ToString(System.Globalization.CultureInfo.InvariantCulture) + " files",
    };

    /// <summary>
    /// Whether the element is a switch control: a checkbox with a <c>switch</c> attribute (https://github.com/whatwg/html/pull/9546,
    /// tentative, implemented by Safari). Its native appearance is a track with a thumb at its inline-start side, or at its inline-end
    /// side when it is checked (it ignores <c>indeterminate</c>); with <c>appearance: none</c> it is a checkbox without appearance.
    /// </summary>
    public static bool IsSwitch(Element? element) => element is HtmlInputElement { InputType: InputType.Checkbox } input && input.HasAttribute("switch");

    /// <summary>Whether the element is a slider-like control (https://drafts.csswg.org/css-forms-1/#slider-pseudos); the switches are not supported.</summary>
    public static bool IsSliderLikeControl(Element? element) => element is HtmlMeterElement or HtmlProgressElement or HtmlInputElement { InputType: InputType.Range };

    /// <summary>
    /// Whether the parts of a slider-like control are boxes: the control has primitive appearance (<c>appearance: none</c>, or a
    /// devolved widget); with native appearance the widget is painted.
    /// </summary>
    public static bool HasSliderParts(Element? element, ComputedStyle style) => IsSliderLikeControl(element) && !HasNativeAppearance(element!, style);

    /// <summary>
    /// Whether a form control is painted with its native appearance (https://drafts.csswg.org/css-ui-4/#appearance-switching):
    /// its <c>appearance</c> is not <c>none</c>, it does not have base appearance (<c>base</c>, or <c>base-select</c> for a
    /// <c>select</c> element) and it is not a devolved widget.
    /// </summary>
    public static bool HasNativeAppearance(Element element, ComputedStyle style)
        => style.GetComputedValue("appearance") is not ("none" or "") && !StyleEngine.HasControlBaseAppearance(style)
            && !(element is HtmlSelectElement && StyleEngine.HasBaseAppearance(style)) && !IsDevolvedWidget(element, style);

    /// <summary>
    /// Whether the element is a form control with base appearance (https://drafts.csswg.org/css-forms-1/#appearance) that is
    /// not a replaced box, but a box that holds the boxes of its parts: a checkbox or a radio button (its <c>::checkmark</c>,
    /// between its <c>::before</c> and <c>::after</c>), a button (its label), a color well (its <c>::color-swatch</c>), a
    /// slider, a meter or a progress bar (its <c>::slider-track</c>, <c>::slider-fill</c> and <c>::slider-thumb</c>). The
    /// text controls and the date and time fields with base appearance stay replaced boxes.
    /// </summary>
    public static bool HasBaseAppearanceBoxes(Element element, ComputedStyle style)
    {
        if (!StyleEngine.HasControlBaseAppearance(style))
            return false;

        return element is HtmlMeterElement or HtmlProgressElement
            or HtmlInputElement { InputType: InputType.Checkbox or InputType.Radio or InputType.Button or InputType.Submit or InputType.Reset or InputType.Color or InputType.Range };
    }

    /// <summary>
    /// Whether the contents of the box of the element are generated by the box tree builder instead of its children and its
    /// <c>::before</c> and <c>::after</c> pseudo-elements: a file upload control, and the controls with base appearance
    /// that are not replaced boxes, but the checkboxes and the radio buttons.
    /// </summary>
    public static bool HasGeneratedContents(Element element, ComputedStyle style)
        => IsFileUploadControl(element) || (element is not HtmlInputElement { InputType: InputType.Checkbox or InputType.Radio } && HasBaseAppearanceBoxes(element, style));

    /// <summary>The label of a button with base appearance (https://html.spec.whatwg.org/multipage/rendering.html#the-input-element-as-a-button).</summary>
    public static string GetButtonLabel(HtmlInputElement input)
    {
        var label = FormControlSizing.GetButtonLabel(input);
        return label.Contains('\r', StringComparison.Ordinal) ? label.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n') : label;
    }

    /// <summary>
    /// Whether the box of a part of a form control (a pseudo-element) is painted with its native appearance: its
    /// <c>appearance</c> is not <c>none</c>, and the author specifies none of the properties that disable the native appearance.
    /// </summary>
    public static bool HasNativePartAppearance(ComputedStyle style)
    {
        if (style.GetComputedValue("appearance") is "none" or "")
            return false;

        if (style.MayHaveCascadedValueStartingWith("background", "border"))
        {
            foreach (var property in AppearanceDisablingProperties)
            {
                if (style.HasAuthorCascadedValue(property))
                    return false;
            }
        }

        return true;
    }

    /// <summary>
    /// Whether a widget falls back to its primitive appearance (https://drafts.csswg.org/css-ui-4/#appearance-disabling-properties):
    /// as in the browsers, when the author gives one of its backgrounds or borders a value other than the one of the user agent
    /// style sheet (which only sets the background color: Field for the text controls, transparent for the other ones).
    /// </summary>
    public static bool IsDevolvedWidget(Element element, ComputedStyle style)
    {
        // A progress bar, a meter, a text control and a select element fall back as soon as the author specifies one of the
        // properties (as in the browsers, whatever its value: WPT css/css-ui/compute-kind-widget-generated): "in an author-level
        // rule", so that a declaration that reverts the property to the user agent origin does not count, nor an animation or a
        // transition: their computed values are not compared (WPT html/rendering/widgets/appearance/appearance-animation-002)
        if (element is HtmlProgressElement or HtmlMeterElement || HasNativeFrame(element))
        {
            if (!style.MayHaveCascadedValueStartingWith("background", "border"))
                return false;

            foreach (var property in AppearanceDisablingProperties)
            {
                if (style.HasAuthorCascadedValue(property))
                    return true;
            }

            return style.HasAuthorCascadedValue("all");
        }

        if (style.GetComputedValue("background-image") is not ("none" or "") || style.GetComputedValue("border-image-source") is not ("none" or ""))
            return true;

        var layout = style.Layout.Box;
        var widths = layout.BorderWidth;
        if (widths.Top > 0 || widths.Right > 0 || widths.Bottom > 0 || widths.Left > 0)
            return true;

        foreach (var property in RadiusProperties)
        {
            if (style.GetComputedValue(property) is not ("0px" or "0" or ""))
                return true;
        }

        var background = Rendering.DisplayColor.Parse(style.GetUsedValue("background-color")) ?? Rendering.DisplayColor.Transparent;
        return background != GetNativeBackgroundColor(element, style);
    }

    /// <summary>
    /// The background color of the native appearance of a widget, the one of the user agent style sheet: <c>Field</c> for the
    /// text controls, transparent for the other ones.
    /// </summary>
    public static Rendering.DisplayColor GetNativeBackgroundColor(Element element, ComputedStyle style)
    {
        var textControl = element is HtmlTextAreaElement or HtmlSelectElement or HtmlInputElement { InputType: not (InputType.Checkbox or InputType.Radio or InputType.Range or InputType.File or InputType.Image or InputType.Color) };
        return textControl ? Rendering.DisplayColor.Parse(CssValueComputer.GetSystemColor(style, "field")) ?? Rendering.DisplayColor.White : Rendering.DisplayColor.Transparent;
    }

    /// <summary>
    /// Whether the native appearance of a form control has a frame along the edges of its border box (see <c>Painter.PaintNativeFrame</c>):
    /// a text field (also a date and time field), a <c>textarea</c> and a <c>select</c> element rendered as a drop-down box.
    /// </summary>
    public static bool HasNativeFrame(Element element) => element switch
    {
        HtmlTextAreaElement => true,
        HtmlInputElement input => FormControlSizing.IsTextField(input),
        HtmlSelectElement select => StyleEngine.IsDropDownBox(select),
        _ => false,
    };

    /// <summary>The longhands of https://drafts.csswg.org/css-ui-4/#appearance-disabling-properties.</summary>
    private static readonly string[] AppearanceDisablingProperties =
    [
        "background-color", "background-attachment", "background-clip", "background-image", "background-origin", "background-position-x", "background-position-y", "background-size",
        "border-top-color", "border-right-color", "border-bottom-color", "border-left-color",
        "border-top-style", "border-right-style", "border-bottom-style", "border-left-style",
        "border-top-width", "border-right-width", "border-bottom-width", "border-left-width",
        "border-top-left-radius", "border-top-right-radius", "border-bottom-right-radius", "border-bottom-left-radius",
        "border-image-source", "border-image-slice", "border-image-width", "border-image-outset", "border-image-repeat",
        "border-block-start-color", "border-block-end-color", "border-inline-start-color", "border-inline-end-color",
        "border-block-start-style", "border-block-end-style", "border-inline-start-style", "border-inline-end-style",
        "border-block-start-width", "border-block-end-width", "border-inline-start-width", "border-inline-end-width",
        "border-start-start-radius", "border-start-end-radius", "border-end-start-radius", "border-end-end-radius",
    ];

    private static readonly string[] RadiusProperties = ["border-top-left-radius", "border-top-right-radius", "border-bottom-right-radius", "border-bottom-left-radius"];

    /// <summary>
    /// Returns the progress of a slider-like control, from 0 to 1: the position of the value of a slider in its range, the
    /// position of a progress bar (0 when it is indeterminate: "the user agent must give this portion an inline-size of
    /// zero"), the value of a meter in its range.
    /// </summary>
    public static double GetSliderProgress(Element element)
    {
        switch (element)
        {
            case HtmlInputElement input:
            {
                var min = ParseNumber(input.GetAttributeValue("min"), 0);
                var max = ParseNumber(input.GetAttributeValue("max"), 100);
                var value = double.IsNaN(input.ValueAsNumber) ? (min + max) / 2 : input.ValueAsNumber;
                return max > min ? Math.Clamp((value - min) / (max - min), 0, 1) : 0;
            }

            case HtmlProgressElement progress:
                return Math.Clamp(progress.Position, 0, 1);

            case HtmlMeterElement meter:
            {
                var range = meter.Max - meter.Min;
                return range > 0 ? Math.Clamp((meter.Value - meter.Min) / range, 0, 1) : 0;
            }

            default:
                return 0;
        }
    }

    private static double ParseNumber(string? value, double defaultValue)
        => value is not null && double.TryParse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var number) && double.IsFinite(number) ? number : defaultValue;

    /// <summary>
    /// Whether the element is a select element rendered as a list box with native appearance or primitive appearance: a
    /// replaced box whose rows are the boxes of its options (a list box with base appearance is not a replaced box).
    /// </summary>
    public static bool IsNativeListBox(Element? element, ComputedStyle style)
        => element is HtmlSelectElement select && !StyleEngine.IsDropDownBox(select) && !StyleEngine.HasBaseAppearance(style);

    /// <summary>Whether a box is the replaced box of a list box with native appearance: the scroll container of its rows.</summary>
    public static bool IsNativeListBox(ContainerBox box)
        => box.Kind == ContainerBoxKind.Replaced && box.PseudoElement is null && box.Element is HtmlSelectElement && IsNativeListBox(box.Element, box.Style);

    /// <summary>
    /// Whether a replaced box is the scroll container of its contents: a <c>textarea</c> (its inner editor) or a list box with
    /// native appearance (its rows). The other replaced boxes clip their contents.
    /// </summary>
    public static bool IsScrollContainer(ContainerBox box) => TextControlLayout.IsMultiline(box) || IsNativeListBox(box);

    /// <summary>
    /// Returns the first of the boxes of the contents of the replaced box of a form control that are laid out in its content
    /// box (the inner editor of a text control, which its placeholder follows, or the contents box of another control), or null.
    /// </summary>
    public static ContainerBox? GetContents(ContainerBox control)
        => control.FirstChild is ContainerBox { IsTextControlInnerEditor: true } or ContainerBox { IsFormControlContents: true } ? (ContainerBox)control.FirstChild : null;

    /// <summary>Returns the contents box of the replaced box of a form control (not the inner editor of a text control), or null.</summary>
    public static ContainerBox? GetContentsBox(ContainerBox control)
        => control.Kind == ContainerBoxKind.Replaced && control.FirstChild is ContainerBox { IsFormControlContents: true } contents ? contents : null;

    /// <summary>
    /// Returns the max-content inline size of the rows of a list box with native appearance, zoomed ("the width of the select's
    /// labels", https://html.spec.whatwg.org/multipage/rendering.html#the-select-element-2), or null when the box has no rows.
    /// </summary>
    public static double? GetListBoxLabelsInlineSize(LayoutContext context, ContainerBox control)
        => IsNativeListBox(control) && GetContentsBox(control) is { } contents ? IntrinsicSizing.GetIntrinsicInlineSizes(context, contents, contentBlockSize: null).MaxContent : null;

    /// <summary>
    /// Lays out the contents box of a form control at the start of its content box. Its block size does not change the size of
    /// the control: the one of a list box is a part of its scrollable overflow. The rows of a list box are as wide as the widest of them, at
    /// least as wide as the content box: they do not wrap (as in the browsers), and the highlight of a selected row spans the
    /// scrollable overflow of the inline axis.
    /// </summary>
    public static ContentLayoutResult LayoutContents(LayoutContext context, ContainerBox control, ContainerBox contents, FragmentBuilder builder, in ContentArea content)
    {
        if (!IsNativeListBox(control))
        {
            // The contents box of a slider-like control has the size of its content box (the percentages of its parts resolve)
            var fixedSpace = ConstraintSpace.ForContentBox(content.WritingDirection, content.InlineSize, content.BlockSize) with { FixedInlineSize = content.InlineSize, FixedBlockSize = content.BlockSize };
            builder.AddChild(context.LayoutBox(contents, fixedSpace), content.Offset);
            return new ContentLayoutResult(0) { InFlowBlockSize = content.BlockSize ?? 0 };
        }

        var inlineSize = Math.Max(content.InlineSize, IntrinsicSizing.GetIntrinsicInlineSizes(context, contents, contentBlockSize: null).MaxContent);
        var space = ConstraintSpace.ForContentBox(content.WritingDirection, inlineSize, blockSize: null) with { FixedInlineSize = inlineSize };
        var fragment = context.LayoutBox(contents, space);
        builder.AddChild(fragment, content.Offset);
        return new ContentLayoutResult(0) { InFlowBlockSize = content.WritingDirection.ToLogical(fragment.Size).Block };
    }

    /// <summary>Whether the fragment of a form control has the fragment of a contents box: its contents are not painted by the painter of the form controls.</summary>
    public static bool HasContentsFragment(BoxFragment control)
        => control.Box.Kind == ContainerBoxKind.Replaced && control.ChildrenSpan is [BoxFragment { Box.IsFormControlContents: true }, ..];
}
