using Meziantou.Framework.WebPlatform.Css.Layout;

namespace Meziantou.Framework.WebPlatform.Dom;

public partial class Document
{
    private LayoutEngine? _layoutEngine;

    /// <summary>Returns the layout of the document (it is created on first use; creating it does not lay out the document).</summary>
    internal LayoutEngine GetLayoutEngine() => _layoutEngine ??= new LayoutEngine(this);

    /// <summary>The natural sizes of the images fetched for the computed values (see <c>CssImageFetching</c>) by URL, null for a response that is not an image.</summary>
    internal Dictionary<string, ImageNaturalSize?>? CssImageNaturalSizes { get; set; }

    /// <summary>
    /// The images fetched for the computed values (see <c>CssImageFetching</c>) by URL, for the painting (the background images,
    /// the border images, the generated content and the list markers): only when the document has a rendering backend, which
    /// decodes them (without a backend, nothing is painted and the encoded bytes are not kept).
    /// </summary>
    internal Dictionary<string, Rendering.PaintImage>? CssPaintImages { get; set; }

    /// <summary>The layout of the document when something used it, else null.</summary>
    internal LayoutEngine? LayoutEngineOrNull => _layoutEngine;

    /// <summary>Marks the layout of the document as out of date after a change that does not change the computed styles (e.g. the natural size of an image).</summary>
    /// <param name="rebuildBoxTree">Whether the boxes generated by the elements changed (e.g. an image is rendered as its alternative text): the box tree is built again.</param>
    internal void InvalidateLayout(bool rebuildBoxTree = false) => _layoutEngine?.SetNeedsLayout(rebuildBoxTree);

    /// <summary>The document is painted again without a new layout (e.g. the frame of a video changed).</summary>
    internal void InvalidatePaint() => _layoutEngine?.InvalidatePaint();

    /// <summary>The caret of the document may have changed (see <see cref="LayoutEngine.OnCaretChanged"/>).</summary>
    internal void OnCaretChanged() => _layoutEngine?.OnCaretChanged();
}
