namespace Meziantou.Framework.WebPlatform.Dom;

/// <summary>
/// The data of the <c>secure-payment-confirmation</c> payment method (https://w3c.github.io/secure-payment-confirmation/#sctn-securepaymentconfirmationrequest-dictionary):
/// the credentials of the relying party that can authenticate the payment, and what the transaction dialog shows. It is the
/// <see cref="PaymentMethodData.Data"/> of a <see cref="PaymentRequest"/>.
/// </summary>
/// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dictdef-securepaymentconfirmationrequest"/>
[IdlInterface("SecurePaymentConfirmationRequest", "https://w3c.github.io/secure-payment-confirmation/#dictdef-securepaymentconfirmationrequest")]
public sealed class SecurePaymentConfirmationRequest
{
    /// <summary>Gets the random challenge generated by the relying party, signed by the authenticator.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-challenge"/>
    [IdlMember("challenge", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-challenge")]
    public required ReadOnlyMemory<byte> Challenge { get; init; }

    /// <summary>Gets the relying party identifier of the credentials (a valid domain).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-rpid"/>
    [IdlMember("rpId", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-rpid")]
    public required string RpId { get; init; }

    /// <summary>Gets the identifiers of the credentials that can authenticate the payment.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-credentialids"/>
    [IdlMember("credentialIds", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-credentialids")]
    public required IReadOnlyList<ReadOnlyMemory<byte>> CredentialIds { get; init; }

    /// <summary>Gets the payment instrument shown to the user and signed with the transaction.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-instrument"/>
    [IdlMember("instrument", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-instrument")]
    public required PaymentCredentialInstrument Instrument { get; init; }

    /// <summary>Gets the number of milliseconds before the authentication times out, or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-timeout"/>
    [IdlMember("timeout", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-timeout")]
    public uint? Timeout { get; init; }

    /// <summary>Gets the display name of the payee (e.g. the merchant), or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-payeename"/>
    [IdlMember("payeeName", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-payeename")]
    public string? PayeeName { get; init; }

    /// <summary>Gets the origin of the payee (an <c>https:</c> URL), or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-payeeorigin"/>
    [IdlMember("payeeOrigin", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-payeeorigin")]
    public string? PayeeOrigin { get; init; }

    /// <summary>Gets the logos of the entities that facilitate the payment, in descending order of display priority, or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-paymententitieslogos"/>
    [IdlMember("paymentEntitiesLogos", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-paymententitieslogos")]
    public IReadOnlyList<PaymentEntityLogo>? PaymentEntitiesLogos { get; init; }

    /// <summary>Gets the Web Authentication extensions of the authentication (the <c>payment</c> extension is added by the user agent), or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-extensions"/>
    [IdlMember("extensions", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-extensions")]
    public AuthenticationExtensionsClientInputs? Extensions { get; init; }

    /// <summary>Gets the algorithms allowed for the browser bound key, when one is created, or null (ES256, then RS256).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-browserboundpubkeycredparams"/>
    [IdlMember("browserBoundPubKeyCredParams", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-browserboundpubkeycredparams")]
    public IReadOnlyList<PublicKeyCredentialParameters>? BrowserBoundPubKeyCredParams { get; init; }

    /// <summary>Gets the language tags of the locales that the caller accepts for the transaction dialog, or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-locale"/>
    [IdlMember("locale", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-locale")]
    public IReadOnlyList<string>? Locale { get; init; }

    /// <summary>Gets whether the transaction dialog lets the user opt out of the process for the relying party, or null (false).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-showoptout"/>
    [IdlMember("showOptOut", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationrequest-showoptout")]
    public bool? ShowOptOut { get; init; }
}

/// <summary>A payment instrument shown by the transaction dialog of Secure Payment Confirmation (https://w3c.github.io/secure-payment-confirmation/#sctn-paymentcredentialinstrument-dictionary).</summary>
/// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dictdef-paymentcredentialinstrument"/>
[IdlInterface("PaymentCredentialInstrument", "https://w3c.github.io/secure-payment-confirmation/#dictdef-paymentcredentialinstrument")]
public sealed class PaymentCredentialInstrument
{
    /// <summary>Gets the name of the instrument.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-displayname"/>
    [IdlMember("displayName", "https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-displayname")]
    public required string DisplayName { get; init; }

    /// <summary>Gets the URL of the icon of the instrument (an <c>https:</c> or a <c>data:</c> URL).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-icon"/>
    [IdlMember("icon", "https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-icon")]
    public required string Icon { get; init; }

    /// <summary>Gets whether the icon must be fetched and shown for the payment to be possible (the default); otherwise an icon that cannot be fetched is replaced by an empty string.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-iconmustbeshown"/>
    [IdlMember("iconMustBeShown", "https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-iconmustbeshown")]
    public bool IconMustBeShown { get; init; } = true;

    /// <summary>Gets additional details of the instrument (e.g. the last digits of a card), or null.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-details"/>
    [IdlMember("details", "https://w3c.github.io/secure-payment-confirmation/#dom-paymentcredentialinstrument-details")]
    public string? Details { get; init; }
}

/// <summary>The logo of an entity that facilitates a payment (https://w3c.github.io/secure-payment-confirmation/#sctn-paymententitylogo-dictionary).</summary>
/// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dictdef-paymententitylogo"/>
[IdlInterface("PaymentEntityLogo", "https://w3c.github.io/secure-payment-confirmation/#dictdef-paymententitylogo")]
public sealed class PaymentEntityLogo
{
    /// <summary>Gets the URL of the logo (an empty string when the logo cannot be fetched).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-paymententitylogo-url"/>
    [IdlMember("url", "https://w3c.github.io/secure-payment-confirmation/#dom-paymententitylogo-url")]
    public required string Url { get; init; }

    /// <summary>Gets the description of the logo (for the accessibility of the dialog).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-paymententitylogo-label"/>
    [IdlMember("label", "https://w3c.github.io/secure-payment-confirmation/#dom-paymententitylogo-label")]
    public required string Label { get; init; }
}

/// <summary>Whether Secure Payment Confirmation is available (https://w3c.github.io/secure-payment-confirmation/#enumdef-securepaymentconfirmationavailability).</summary>
/// <seealso href="https://w3c.github.io/secure-payment-confirmation/#enumdef-securepaymentconfirmationavailability"/>
[IdlInterface("SecurePaymentConfirmationAvailability", "https://w3c.github.io/secure-payment-confirmation/#enumdef-securepaymentconfirmationavailability")]
public enum SecurePaymentConfirmationAvailability
{
    /// <summary>Secure Payment Confirmation is available.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-available"/>
    [IdlMember("available", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-available")]
    Available,

    /// <summary>Secure Payment Confirmation is not available, for an unknown reason.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-unknown-reason"/>
    [IdlMember("unavailable-unknown-reason", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-unknown-reason")]
    UnavailableUnknownReason,

    /// <summary>The user agent does not support Secure Payment Confirmation (<see cref="UserAgentUIBackend.HasPaymentHandlerAsync"/> does not support the payment method).</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-feature-not-enabled"/>
    [IdlMember("unavailable-feature-not-enabled", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-feature-not-enabled")]
    UnavailableFeatureNotEnabled,

    /// <summary>The document is not allowed to use the <c>payment</c> feature.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-no-permission-policy"/>
    [IdlMember("unavailable-no-permission-policy", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-no-permission-policy")]
    UnavailableNoPermissionPolicy,

    /// <summary>There is no user-verifying platform authenticator.</summary>
    /// <seealso href="https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-no-user-verifying-platform-authenticator"/>
    [IdlMember("unavailable-no-user-verifying-platform-authenticator", "https://w3c.github.io/secure-payment-confirmation/#dom-securepaymentconfirmationavailability-unavailable-no-user-verifying-platform-authenticator")]
    UnavailableNoUserVerifyingPlatformAuthenticator,
}
