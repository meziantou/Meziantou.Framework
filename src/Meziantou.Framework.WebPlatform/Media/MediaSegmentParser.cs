namespace Meziantou.Framework.WebPlatform.Media;

/// <summary>
/// The byte stream parser of a <c>SourceBuffer</c> of the Media Source Extensions (https://w3c.github.io/media-source/#byte-stream-formats),
/// created by <see cref="MediaBackend.CreateSegmentParser"/> for the MIME type of <c>addSourceBuffer()</c> or
/// <c>changeType()</c>: it splits the bytes appended by <c>appendBuffer()</c> into initialization segments (the tracks) and
/// media segments (the coded frames: their timestamps, their durations and whether they are random access points). The
/// library implements the rest of the specification on top of it: the segment parser loop, the coded frame processing
/// algorithm (<c>timestampOffset</c>, <c>mode</c>, the append window), the track buffers and their buffered ranges, the
/// removals, the duration, the ready states of the media element...
/// </summary>
/// <remarks>The members are called on the thread of the event loop of the global object (a window or a dedicated worker) that created the <c>MediaSource</c>.</remarks>
public abstract class MediaSegmentParser : IDisposable
{
    /// <summary>
    /// Gets a value indicating whether the timestamps of the coded frames are generated by the <c>SourceBuffer</c>
    /// (the "Generate Timestamps Flag" of the byte stream format registry, https://www.w3.org/TR/mse-byte-stream-format-registry/):
    /// true for the formats whose frames have no timestamp (<c>audio/mpeg</c>, <c>audio/aac</c>). The mode of the
    /// <c>SourceBuffer</c> is then <c>sequence</c>. The default is false.
    /// </summary>
    public virtual bool GeneratesTimestamps => false;

    /// <summary>
    /// Gets the size in bytes of the media segments the <c>SourceBuffer</c> keeps before it is full, or null for the default
    /// (150 MB with a video track, 12 MB for audio, as in Chromium). When the buffer is full, the frames that were played are
    /// evicted, and <c>appendBuffer()</c> throws a <c>QuotaExceededError</c> when it is still full
    /// (https://w3c.github.io/media-source/#sourcebuffer-coded-frame-eviction).
    /// </summary>
    public virtual long? BufferCapacity => null;

    /// <summary>
    /// Parses the start of the input buffer of the <c>SourceBuffer</c> (the segment parser loop,
    /// https://w3c.github.io/media-source/#sourcebuffer-segment-parser-loop). The method is called again with the rest of the
    /// buffer until it returns <see cref="MediaSegmentParseResult.NeedMoreData"/> or an error, and again when more bytes are
    /// appended.
    /// </summary>
    /// <param name="input">The bytes that were appended and not consumed yet. The buffer is not empty.</param>
    /// <returns>What the start of the buffer contains, and the number of bytes to remove from the buffer.</returns>
    public abstract MediaSegmentParseResult Parse(ReadOnlyMemory<byte> input);

    /// <summary>
    /// Resets the parser (https://w3c.github.io/media-source/#sourcebuffer-reset-parser-state): the bytes that were not
    /// consumed are dropped (<c>abort()</c>, <c>changeType()</c>, an append error), and the next bytes are the start of a
    /// segment. The default implementation does nothing.
    /// </summary>
    public virtual void Reset()
    {
    }

    /// <summary>Releases the resources of the parser: its <c>SourceBuffer</c> is removed, or its type changed.</summary>
    public void Dispose()
    {
        Dispose(disposing: true);
        GC.SuppressFinalize(this);
    }

    /// <summary>Releases the resources of the parser.</summary>
    /// <param name="disposing">Whether the method is called by <see cref="Dispose()"/>.</param>
    protected virtual void Dispose(bool disposing)
    {
    }
}

/// <summary>What <see cref="MediaSegmentParser.Parse"/> found at the start of the input buffer of a <c>SourceBuffer</c>.</summary>
public enum MediaSegmentParseStatus
{
    /// <summary>The buffer does not contain a complete segment (or a complete coded frame of a media segment) yet.</summary>
    NeedMoreData,

    /// <summary>The buffer starts with bytes that the byte stream format ignores.</summary>
    Ignored,

    /// <summary>The buffer starts with a complete initialization segment.</summary>
    InitializationSegment,

    /// <summary>The buffer starts with coded frames of a media segment.</summary>
    MediaSegment,

    /// <summary>The bytes violate the byte stream format, or cannot be decoded: the append fails with a decode error.</summary>
    Error,
}

/// <summary>The result of <see cref="MediaSegmentParser.Parse"/>.</summary>
public sealed class MediaSegmentParseResult
{
    private static readonly MediaSegmentParseResult NeedMoreDataResult = new(MediaSegmentParseStatus.NeedMoreData, 0);
    private static readonly MediaSegmentParseResult NeedMoreMediaDataResult = new(MediaSegmentParseStatus.NeedMoreData, 0) { IsParsingMediaSegment = true };

    private MediaSegmentParseResult(MediaSegmentParseStatus status, int byteCount)
    {
        Status = status;
        ByteCount = byteCount;
    }

    /// <summary>Gets what the start of the buffer contains.</summary>
    public MediaSegmentParseStatus Status { get; }

    /// <summary>Gets the number of bytes to remove from the start of the buffer.</summary>
    public int ByteCount { get; }

    /// <summary>Gets the initialization segment (<see cref="MediaSegmentParseStatus.InitializationSegment"/>), or null.</summary>
    public MediaInitializationSegment? InitializationSegment { get; private init; }

    /// <summary>Gets the complete coded frames of the media segment (<see cref="MediaSegmentParseStatus.MediaSegment"/>), in decode order.</summary>
    public IReadOnlyList<MediaCodedFrame> Frames { get; private init; } = [];

    /// <summary>
    /// Gets a value indicating whether the parser is in the middle of a media segment: the rest of the segment is not
    /// received yet (the append state of the <c>SourceBuffer</c> is then <c>PARSING_MEDIA_SEGMENT</c>: <c>mode</c> and
    /// <c>timestampOffset</c> cannot be set until the segment is complete or <c>abort()</c> is called).
    /// </summary>
    public bool IsParsingMediaSegment { get; private init; }

    /// <summary>Gets the diagnostic message of an error, or an empty string.</summary>
    public string ErrorMessage { get; private init; } = "";

    /// <summary>The buffer does not contain a complete segment yet.</summary>
    /// <param name="isParsingMediaSegment">Whether the buffer starts with (or continues) a media segment that is not complete.</param>
    public static MediaSegmentParseResult NeedMoreData(bool isParsingMediaSegment = false) => isParsingMediaSegment ? NeedMoreMediaDataResult : NeedMoreDataResult;

    /// <summary>The buffer starts with bytes that the byte stream format ignores (e.g. an unknown box).</summary>
    /// <param name="byteCount">The number of bytes to ignore.</param>
    public static MediaSegmentParseResult Ignore(int byteCount)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(byteCount, 1);
        return new(MediaSegmentParseStatus.Ignored, byteCount);
    }

    /// <summary>The buffer starts with a complete initialization segment.</summary>
    /// <param name="byteCount">The size of the segment in bytes (0 when the segment has no byte of its own: e.g. the header of the first frame of an MPEG audio stream, which is then parsed as a media segment).</param>
    /// <param name="segment">The tracks and the duration of the segment.</param>
    public static MediaSegmentParseResult Initialization(int byteCount, MediaInitializationSegment segment)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(byteCount);
        ArgumentNullException.ThrowIfNull(segment);
        return new(MediaSegmentParseStatus.InitializationSegment, byteCount) { InitializationSegment = segment };
    }

    /// <summary>The buffer starts with complete coded frames of a media segment.</summary>
    /// <param name="byteCount">The number of bytes of the buffer that were parsed (0 or more when the segment is not complete).</param>
    /// <param name="frames">The coded frames, in decode order.</param>
    /// <param name="isComplete">Whether the media segment is complete: otherwise the next bytes are the rest of the segment.</param>
    public static MediaSegmentParseResult Media(int byteCount, IReadOnlyList<MediaCodedFrame> frames, bool isComplete = true)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(byteCount);
        ArgumentNullException.ThrowIfNull(frames);
        if (byteCount == 0 && (isComplete || frames.Count == 0))
            throw new ArgumentException("A media segment consumes bytes of the buffer", nameof(byteCount));

        return new(MediaSegmentParseStatus.MediaSegment, byteCount) { Frames = frames, IsParsingMediaSegment = !isComplete };
    }

    /// <summary>The bytes violate the byte stream format, use a codec that is not supported, or cannot be decoded.</summary>
    /// <param name="message">A diagnostic message.</param>
    public static MediaSegmentParseResult Error(string message = "") => new(MediaSegmentParseStatus.Error, 0) { ErrorMessage = message ?? "" };
}

/// <summary>An initialization segment of a <c>SourceBuffer</c> (https://w3c.github.io/media-source/#init-segment): the tracks of the next media segments.</summary>
public sealed class MediaInitializationSegment
{
    /// <summary>Creates an initialization segment.</summary>
    /// <param name="tracks">The audio and video tracks of the segment.</param>
    /// <param name="duration">The duration of the presentation in seconds, or NaN when the segment has none (the duration of the <c>MediaSource</c> is then infinite).</param>
    public MediaInitializationSegment(IReadOnlyList<MediaSegmentTrack> tracks, double duration = double.NaN)
    {
        ArgumentNullException.ThrowIfNull(tracks);
        Tracks = tracks;
        Duration = duration;
    }

    /// <summary>Gets the audio and video tracks of the segment.</summary>
    public IReadOnlyList<MediaSegmentTrack> Tracks { get; }

    /// <summary>Gets the duration of the presentation in seconds, or NaN.</summary>
    public double Duration { get; }
}

/// <summary>A track of an initialization segment (<see cref="MediaInitializationSegment"/>).</summary>
/// <param name="Id">The identifier of the track in the byte stream (the track ID of the coded frames, see <see cref="MediaCodedFrame.TrackId"/>).</param>
/// <param name="IsVideo">Whether the track is a video track (else an audio track).</param>
/// <param name="Kind">The category of the track (<c>main</c>, <c>alternative</c>...), or an empty string.</param>
/// <param name="Label">The label of the track, or an empty string.</param>
/// <param name="Language">The BCP 47 language tag of the track, or an empty string.</param>
/// <param name="VideoWidth">The natural width of the frames of a video track, in CSS pixels.</param>
/// <param name="VideoHeight">The natural height of the frames of a video track, in CSS pixels.</param>
public sealed record MediaSegmentTrack(long Id, bool IsVideo, string Kind = "", string Label = "", string Language = "", int VideoWidth = 0, int VideoHeight = 0);

/// <summary>A coded frame of a media segment (https://w3c.github.io/media-source/#coded-frame): the library stores its position on the media timeline, not its data.</summary>
/// <param name="TrackId">The identifier of the track of the frame (<see cref="MediaSegmentTrack.Id"/>).</param>
/// <param name="PresentationTimestamp">The presentation timestamp of the frame, in seconds.</param>
/// <param name="DecodeTimestamp">The decode timestamp of the frame, in seconds.</param>
/// <param name="Duration">The duration of the frame, in seconds.</param>
/// <param name="IsRandomAccessPoint">Whether the frame can be decoded without the previous frames (a key frame; every audio frame of most codecs).</param>
[System.Runtime.InteropServices.StructLayout(System.Runtime.InteropServices.LayoutKind.Auto)]
public readonly record struct MediaCodedFrame(long TrackId, double PresentationTimestamp, double DecodeTimestamp, double Duration, bool IsRandomAccessPoint);
