namespace Meziantou.Framework.WebPlatform.Scripting;

/// <summary>The flags of an interface of the bindings.</summary>
[Flags]
internal enum InterfaceBindingFlags
{
    None = 0,

    /// <summary>A namespace (https://webidl.spec.whatwg.org/#idl-namespaces): an ordinary object.</summary>
    Namespace = 1,

    /// <summary>The constructor is an HTML element constructor (https://html.spec.whatwg.org/multipage/dom.html#htmlconstructor).</summary>
    HtmlConstructor = 2,

    /// <summary>[Global]: the regular attributes and operations are properties of the global object.</summary>
    Global = 4,

    /// <summary>[LegacyOverrideBuiltIns]</summary>
    LegacyOverrideBuiltIns = 8,

    /// <summary>[LegacyUnenumerableNamedProperties]</summary>
    LegacyUnenumerableNamedProperties = 16,

    /// <summary>The indexed and named setters and deleters are decorated with [CEReactions].</summary>
    SpecialOperationsHaveCEReactions = 32,

    /// <summary>[SecureContext]: the interface is only exposed in a secure context.</summary>
    SecureContext = 64,
}

/// <summary>
/// The global objects in which an interface or a member is exposed (https://webidl.spec.whatwg.org/#dfn-exposure-set): the
/// global names of the [Exposed] extended attribute (https://webidl.spec.whatwg.org/#Exposed).
/// </summary>
[Flags]
internal enum ExposureSet
{
    None = 0,

    /// <summary>The windows (<c>Window</c>).</summary>
    Window = 1,

    /// <summary>The dedicated workers (<c>DedicatedWorkerGlobalScope</c>).</summary>
    DedicatedWorker = 2,

    /// <summary>The shared workers (<c>SharedWorkerGlobalScope</c>).</summary>
    SharedWorker = 4,

    /// <summary>The service workers (<c>ServiceWorkerGlobalScope</c>).</summary>
    ServiceWorker = 8,

    /// <summary>The paint worklets (<c>PaintWorkletGlobalScope</c>).</summary>
    PaintWorklet = 16,

    /// <summary>The other global objects (e.g. <c>ShadowRealmGlobalScope</c>).</summary>
    Other = 32,

    /// <summary>The layout worklets (<c>LayoutWorkletGlobalScope</c>).</summary>
    LayoutWorklet = 64,

    /// <summary>The animation worklets (<c>AnimationWorkletGlobalScope</c>).</summary>
    AnimationWorklet = 128,

    /// <summary>The audio worklets (<c>AudioWorkletGlobalScope</c>).</summary>
    AudioWorklet = 256,

    /// <summary>The worklets (the <c>Worklet</c> global name of the worklet global scopes).</summary>
    Worklet = PaintWorklet | LayoutWorklet | AnimationWorklet | AudioWorklet,

    /// <summary>All the global objects (<c>[Exposed=*]</c>).</summary>
    All = Window | DedicatedWorker | SharedWorker | ServiceWorker | Worklet | Other,
}

/// <summary>
/// An interface of the bindings (https://webidl.spec.whatwg.org/#es-interfaces): its interface object, its prototype
/// and its members, generated by tools/Meziantou.Framework.WebPlatform.SpecGen.
/// </summary>
internal sealed class InterfaceBinding<TAdapter, TValue>
    where TAdapter : struct, IJsAdapter<TValue>
    where TValue : class
{
    public required string Name { get; init; }

    /// <summary>
    /// The class string of the interface (https://webidl.spec.whatwg.org/#dfn-class-string), when it is not its name: the
    /// qualified name of an interface with [LegacyNamespace] (e.g. <c>WebAssembly.Module</c>).
    /// </summary>
    public string? ClassString { get; init; }

    public string? ParentName { get; init; }

    public InterfaceBinding<TAdapter, TValue>? Parent { get; set; }

    /// <summary>The .NET type that implements the interface.</summary>
    public required Type ClrType { get; init; }

    public InterfaceBindingFlags Flags { get; init; }

    /// <summary>The global objects in which the interface is exposed (https://webidl.spec.whatwg.org/#dfn-exposed).</summary>
    public ExposureSet Exposure { get; init; } = ExposureSet.Window;

    /// <summary>The value of the <c>length</c> property of the interface object.</summary>
    public int ConstructorLength { get; init; }

    /// <summary>The constructor steps (null when the interface has no constructor): returns the new .NET object.</summary>
    public WebIdlRealm<TAdapter, TValue>.ConstructorSteps? Constructor { get; init; }

    /// <summary>Defines the constants, attributes and operations on the interface object, the prototype and the instance target (the global object for [Global]).</summary>
    public required Action<WebIdlRealm<TAdapter, TValue>, TValue, TValue, TValue> DefineMembers { get; init; }

    /// <summary>
    /// Gets or sets the number of properties of the interface object once its members are defined (learned by the first realm
    /// of the process: the next ones allocate the storage of the properties once). The realms of several threads can set it.
    /// </summary>
    public int InterfaceObjectPropertyCount { get; set; }

    /// <summary>Gets or sets the number of properties of the interface prototype object once its members are defined (see <see cref="InterfaceObjectPropertyCount"/>).</summary>
    public int PrototypePropertyCount { get; set; }

    /// <summary>Defines the [LegacyUnforgeable] members on a new instance (https://webidl.spec.whatwg.org/#LegacyUnforgeable), or null.</summary>
    public Action<WebIdlRealm<TAdapter, TValue>, TValue>? DefineUnforgeableMembers { get; init; }

    /// <summary>The indexed and named properties (https://webidl.spec.whatwg.org/#es-legacy-platform-objects), or null.</summary>
    public LegacyPlatformObjectBinding<TAdapter, TValue>? LegacyPlatformObject { get; init; }

    /// <summary>Whether the object is an instance of the interface (the .NET type or a derived type).</summary>
    public bool IsInstance(object target) => ClrType.IsInstanceOfType(target);

    public bool IsA(string name)
    {
        for (var binding = this; binding is not null; binding = binding.Parent)
        {
            if (binding.Name == name)
                return true;
        }

        return false;
    }

    public override string ToString() => Name;
}

/// <summary>The indexed and named properties of a legacy platform object (https://webidl.spec.whatwg.org/#es-legacy-platform-objects).</summary>
internal sealed class LegacyPlatformObjectBinding<TAdapter, TValue>
    where TAdapter : struct, IJsAdapter<TValue>
    where TValue : class
{
    /// <summary>Returns the number of indexed properties (the <c>length</c> attribute), or null when there are no indexed properties.</summary>
    public Func<object, uint>? Length { get; init; }

    /// <summary>The indexed property getter.</summary>
    public Func<WebIdlRealm<TAdapter, TValue>, object, uint, TValue>? IndexedGetter { get; init; }

    /// <summary>The indexed property setter.</summary>
    public Action<WebIdlRealm<TAdapter, TValue>, object, uint, TValue>? IndexedSetter { get; init; }

    /// <summary>The named property getter.</summary>
    public Func<WebIdlRealm<TAdapter, TValue>, object, string, TValue>? NamedGetter { get; init; }

    /// <summary>The supported property names.</summary>
    public Func<object, IReadOnlyList<string>>? SupportedPropertyNames { get; init; }

    /// <summary>The named property setter.</summary>
    public Action<WebIdlRealm<TAdapter, TValue>, object, string, TValue>? NamedSetter { get; init; }

    /// <summary>The named property deleter.</summary>
    public Action<WebIdlRealm<TAdapter, TValue>, object, string>? NamedDeleter { get; init; }

    public bool SupportsIndexedProperties => IndexedGetter is not null && Length is not null;

    public bool SupportsNamedProperties => NamedGetter is not null && SupportedPropertyNames is not null;
}
