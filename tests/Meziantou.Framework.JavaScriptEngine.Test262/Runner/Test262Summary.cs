using System.Globalization;
using System.Text;

namespace Meziantou.Framework.JavaScriptEngine.Test262.Runner;

/// <summary>
/// The pass rate of test262 per area (docs/JavaScriptEngine/10-Conformance.md), computed from the discovered tests, the skip list, the excluded
/// features and the expectations. It is rewritten at the end of a run that updates the expectations.
/// </summary>
internal static class Test262Summary
{
    private static readonly string[] TopLevelDirectories = ["annexB", "built-ins", "intl402", "language", "staging"];

    public static string Generate()
    {
        var rows = new List<Row>();
        foreach (var topLevel in TopLevelDirectories)
        {
            var directory = Path.Combine(Test262Paths.Tests, topLevel);
            if (!Directory.Exists(directory))
                continue;

            var tests = Test262Discovery.Discover(topLevel).All;
            foreach (var group in tests.GroupBy(test => GetAreaName(test.Id)).OrderBy(group => group.Key, StringComparer.Ordinal))
            {
                var row = new Row(group.Key);
                foreach (var test in group)
                {
                    row.Files++;
                    if (Test262Discovery.IsExcludedByFeature(test))
                    {
                        row.Excluded++;
                        continue;
                    }

                    var modes = test.Modes.Count;
                    row.Runs += modes;
                    if (Test262Discovery.Skipped.IsSkipped(test.Id))
                    {
                        row.Skipped += modes;
                    }
                    else
                    {
                        foreach (var mode in test.Modes)
                        {
                            if (Test262Expectations.IsExpectedToFail(test.Id, mode))
                            {
                                row.Failing++;
                            }
                        }
                    }
                }

                rows.Add(row);
            }
        }

        var total = new Row("**Total**");
        foreach (var row in rows)
        {
            total.Files += row.Files;
            total.Excluded += row.Excluded;
            total.Runs += row.Runs;
            total.Skipped += row.Skipped;
            total.Failing += row.Failing;
        }

        var builder = new StringBuilder();
        builder.Append("---\n");
        builder.Append("title: Conformance\n");
        builder.Append("description: The test262 pass rate of the engine, per area of the specification.\n");
        builder.Append("---\n\n");
        builder.Append("<!-- Generated by tests/Meziantou.Framework.JavaScriptEngine.Test262 when the expectations are updated (TEST262_UPDATE_EXPECTATIONS=1). Do not edit. -->\n\n");
        builder.Append("The engine is tested against [test262](https://github.com/tc39/test262), the conformance suite of ECMAScript. A run is a test in one mode (sloppy, strict or module). The excluded tests use features that the engine does not implement on purpose, and are not run. The pass rate is computed over the runs of the other tests: the skipped runs and the known failures do not pass.\n\n");
        builder.Append(CultureInfo.InvariantCulture, $"Overall: **{FormatRate(total)}** ({total.Passing:N0} / {total.Runs:N0} runs)\n\n");
        builder.Append("| Area | Files | Excluded | Runs | Skipped | Failing | Passing | Pass rate |\n");
        builder.Append("|---|---:|---:|---:|---:|---:|---:|---:|\n");
        foreach (var row in rows.Append(total))
        {
            builder.Append(CultureInfo.InvariantCulture, $"| {row.Name} | {row.Files} | {row.Excluded} | {row.Runs} | {row.Skipped} | {row.Failing} | {row.Passing} | {FormatRate(row)} |\n");
        }

        return builder.ToString();
    }

    private static string GetAreaName(string id)
    {
        var segments = id.Split('/');
        return segments.Length > 2 ? segments[0] + "/" + segments[1] : segments[0];
    }

    private static string FormatRate(Row row) => row.Runs == 0 ? "-" : (row.Passing * 100.0 / row.Runs).ToString("0.0", CultureInfo.InvariantCulture) + "%";

    public static void Write()
    {
        Test262Expectations.Reset();
        File.WriteAllText(Test262Paths.SummaryFile, Generate());
    }

    private sealed class Row(string name)
    {
        public string Name { get; } = name;

        public int Files { get; set; }

        public int Excluded { get; set; }

        public int Runs { get; set; }

        public int Skipped { get; set; }

        public int Failing { get; set; }

        public int Passing => Runs - Skipped - Failing;
    }
}
