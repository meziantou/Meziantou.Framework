using System.Collections.Generic;
using System.Text.Json;
using System.Text.RegularExpressions;
using Meziantou.Framework.Markdown.Extensions.Tables;

namespace Meziantou.Framework.Markdown.Tests;

public class TestGfmPipeTableDifferential
{
    private static readonly MarkdownPipeline Strict = new MarkdownPipelineBuilder()
        .UsePipeTables(new PipeTableOptions { UseGfmRules = true }).Build();
    private static readonly MarkdownPipeline Tracked = new MarkdownPipelineBuilder()
        .UsePipeTables(new PipeTableOptions { UseGfmRules = true }).EnableTrackTrivia().Build();

    // Native cmark-gfm output, not output generated by this library. See the tool's
    // README for provenance, regeneration and the limits of subtree comparisons.
    public static TheoryData<string, string, string, bool> NativeCases()
    {
        var result = new TheoryData<string, string, string, bool>();
        foreach (var (name, markdown, expected, tableOnly) in EnumerateNativeCases())
        {
            result.Add(name, markdown, expected, tableOnly);
        }

        return result;
    }

    private static IEnumerable<(string Name, string Markdown, string Expected, bool TableOnly)> EnumerateNativeCases()
    {
        using var stream = typeof(TestGfmPipeTableDifferential).Assembly.GetManifestResourceStream(
            "Meziantou.Framework.Markdown.Tests.Specs.GfmPipeTableDifferential.json")!;
        using var document = JsonDocument.Parse(stream);
        var index = 0;
        foreach (var item in document.RootElement.EnumerateArray())
        {
            yield return ($"NativeGfm_{item.GetProperty("group").GetString()}_{++index:D4}",
                item.GetProperty("input").GetString()!,
                item.GetProperty("expected").GetString()!,
                item.GetProperty("tableOnly").GetBoolean());
        }
    }

    [Theory]
    [MemberData(nameof(NativeCases))]
    public void MatchesNativeOutput(string name, string markdown, string expected, bool tableOnly)
    {
        var message = name + "\n" + markdown;
        var actual = Normalize(MarkdownConverter.ToHtml(markdown, Strict));
        Assert.Equal(tableOnly ? Tables(expected) : expected, tableOnly ? Tables(actual) : actual, message: message);
        // Trivia mode deliberately preserves whitespace outside tables, unlike
        // cmark-gfm. Table presence, cell text, alignment and row shape must agree.
        Assert.Equal(Tables(expected), Tables(Normalize(MarkdownConverter.ToHtml(markdown, Tracked))), message: message);
    }

    private static string Normalize(string html) => Regex.Replace(html.Replace("\r\n", "\n", StringComparison.Ordinal),
        @"<li>\n?(?=<(?:h[1-6]|table|blockquote|pre|ul|ol|hr|p)[ >])", "<li>\n").Trim();

    private static string Tables(string html) => string.Join("\n",
        Regex.Matches(html, @"(?s)<table>.*?</table>").Select(match => match.Value));

    public static TheoryData<string, string> NormalizationCases()
    {
        var result = new TheoryData<string, string>();
        foreach (var (name, markdown, _, _) in EnumerateNativeCases())
        {
            if (name.StartsWith("NativeGfm_backslash_", StringComparison.Ordinal)
                || name.StartsWith("NativeGfm_inline-focused_", StringComparison.Ordinal))
            {
                result.Add(name.Replace("NativeGfm_", "NormalizeGfm_", StringComparison.Ordinal), markdown);
            }
        }

        return result;
    }

    [Theory]
    [MemberData(nameof(NormalizationCases))]
    public void NormalizationPreservesNativeInlineSemantics(string name, string markdown)
    {
        var normalized = MarkdownConverter.Normalize(markdown, pipeline: Strict);
        Assert.Equal(MarkdownConverter.ToHtml(markdown, Strict), MarkdownConverter.ToHtml(normalized, Strict), message: name);
        Assert.Equal(normalized, MarkdownConverter.Normalize(normalized, pipeline: Strict), message: name);
    }
}
