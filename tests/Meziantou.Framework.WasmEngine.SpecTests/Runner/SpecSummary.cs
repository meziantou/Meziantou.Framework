using System.Globalization;
using System.Text;
using Meziantou.Framework.WasmEngine.Text;

namespace Meziantou.Framework.WasmEngine.SpecTests.Runner;

/// <summary>
/// The pass rate of the test suite (docs/WasmEngine/09-Conformance.md), computed from the commands of the scripts and the
/// expectations.
/// </summary>
internal static class SpecSummary
{
    public static string Generate() => Generate(SpecTestPaths.GetScripts(), SpecTestPaths.TestSuite, SpecExpectations.Core, """
            ---
            title: Conformance
            description: The pass rate of the official WebAssembly test suite.
            ---

            The engine runs the scripts of the official test suite ([WebAssembly/testsuite](https://github.com/WebAssembly/testsuite)):
            the modules, the invocations and the assertions (the results, the traps, the stack exhaustion, the invalid,
            malformed and unlinkable modules, the exceptions). A command passes when its assertion holds. Each script runs
            three times, with the same results: with the interpreter, with the functions compiled to .NET code on their
            first call, and with the interpreter continuing the calls in .NET code from the first iteration of their loops.

            This page is generated by the tests of `tests/Meziantou.Framework.WasmEngine.SpecTests`, from the known failures
            listed in `expectations.txt`.

            """);

    /// <summary>The pass rate of the tests of the component model (docs/WasmEngine/13-Components/05-Conformance.md).</summary>
    public static string GenerateComponents() => Generate(SpecTestPaths.GetComponentScripts(), SpecTestPaths.ComponentModelTests, SpecExpectations.Components, """
            ---
            title: Conformance
            description: The pass rate of the tests of the component model.
            ---

            The engine runs the scripts of the tests of the component model
            ([WebAssembly/component-model](https://github.com/WebAssembly/component-model/tree/main/test)): the components,
            the invocations and the assertions (the results, the traps, the invalid and malformed components). A command
            passes when its assertion holds. Each script runs twice, with the same results: with the interpreter, and with the
            functions compiled to .NET code on their first call.

            The known failures are the scripts of `nyi.txt` of the tests: the reference engines do not implement them
            either.

            This page is generated by the tests of `tests/Meziantou.Framework.WasmEngine.SpecTests`, from the known failures
            listed in `component-expectations.txt`.

            """);

    private static string Generate(IReadOnlyList<string> scripts, FullPath root, SpecExpectations expectations, string header)
    {
        var rows = new List<(string Name, int Scripts, int Commands, int Failing)>();
        var failingScripts = new List<(string Script, int Commands, int Failing)>();
        foreach (var group in scripts.GroupBy(GetDirectory).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var commands = 0;
            var failing = 0;
            foreach (var script in group)
            {
                var count = CountCommands(root / script);
                var failures = expectations.CountFailures(script);
                commands += count;
                failing += failures;
                if (failures > 0)
                {
                    failingScripts.Add((script, count, failures));
                }
            }

            rows.Add((group.Key, group.Count(), commands, failing));
        }

        var sb = new StringBuilder();
        sb.Append(header).Append('\n');
        sb.Append("""
            | Directory | Scripts | Commands | Passing | Pass rate |
            | --- | ---: | ---: | ---: | ---: |

            """);
        var totalScripts = 0;
        var totalCommands = 0;
        var totalFailing = 0;
        foreach (var (name, scriptCount, commands, failing) in rows)
        {
            AppendRow(sb, name, scriptCount, commands, failing);
            totalScripts += scriptCount;
            totalCommands += commands;
            totalFailing += failing;
        }

        AppendRow(sb, "**Total**", totalScripts, totalCommands, totalFailing);
        if (failingScripts.Count > 0)
        {
            sb.Append("""

                The scripts with known failures:

                | Script | Commands | Failing |
                | --- | ---: | ---: |

                """);
            foreach (var (script, commands, failing) in failingScripts)
            {
                sb.Append(CultureInfo.InvariantCulture, $"| `{script}` | {commands} | {failing} |\n");
            }
        }

        return sb.ToString().ReplaceLineEndings("\n");
    }

    private static void AppendRow(StringBuilder sb, string name, int scripts, int commands, int failing)
    {
        var passing = commands - failing;
        var rate = commands == 0 ? 100.0 : passing * 100.0 / commands;
        sb.Append(CultureInfo.InvariantCulture, $"| {name} | {scripts} | {commands} | {passing} | {rate:0.00}% |\n");
    }

    private static string GetDirectory(string script)
    {
        var index = script.LastIndexOf("/", StringComparison.Ordinal);
        return index < 0 ? "(root)" : "`" + script[..index] + "`";
    }

    private static int CountCommands(FullPath script)
    {
        try
        {
            var commands = SExpressionReader.Parse(File.ReadAllText(script));
            return WastRunner.IsInlineModule(commands) ? 1 : commands.Count;
        }
        catch (FormatException)
        {
            return 1;
        }
    }

    public static void Write() => File.WriteAllText(SpecTestPaths.SummaryFile, Generate());

    public static void WriteComponents() => File.WriteAllText(SpecTestPaths.ComponentSummaryFile, GenerateComponents());
}
