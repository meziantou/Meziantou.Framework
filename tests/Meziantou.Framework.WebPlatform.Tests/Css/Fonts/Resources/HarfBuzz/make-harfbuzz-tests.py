#!/usr/bin/env python3
"""Extracts a subset of the shaping tests of HarfBuzz (test/shape/data/in-house, MIT license) for ComplexShapingTests.

usage: make-harfbuzz-tests.py <harfbuzz checkout>

The tests of the complex-script shapers whose fonts are under the SIL Open Font License (Noto, Lohit) or the Apache License
(Droid) and smaller than 32 KB are copied to harfbuzz.tests with their expected glyph names replaced by glyph ids (with
fontTools), and their fonts are copied to fonts/ (with their licenses, fonts/OFL.txt and fonts/LICENSE-Apache-2.0.txt). The format of a line is "<test file>;<font>;<options>;<unicodes>;<expected glyphs>", as the .tests
files of HarfBuzz.
"""

import os
import re
import shutil
import sys

from fontTools.ttLib import TTFont

TESTS = [
    'indic-consonant-with-stacker.tests',
    'indic-joiner-candrabindu.tests',
    'indic-joiners.tests',
    'indic-malayalam-dot-reph.tests',
    'indic-old-spec.tests',
    'indic-pref-blocking.tests',
    'indic-special-cases.tests',
    'indic-syllable.tests',
    'indic-vowel-letter-spoofing.tests',
    'ligature-id.tests',
    'context-matching.tests',
    'cluster.tests',
    'khmer-mark-order.tests',
    'khmer-misc.tests',
    'myanmar-misc.tests',
    'myanmar-syllable.tests',
    'use.tests',
    'use-indic3.tests',
    'use-syllable.tests',
    'arabic-phags-pa.tests',
    'arabic-like-joining.tests',
    'arabic-fallback-shaping.tests',
    'hangul-jamo.tests',
    'zero-width-marks.tests',
]

# The fonts of the families under the OFL or the Apache License
FAMILIES = re.compile(r'^(Noto Sans|Noto Serif|Lohit|Droid)')
EXCLUDED_FAMILIES = {'Noto Sans Tamil MN'}
MAX_FONT_SIZE = 32 * 1024
SUPPORTED_OPTIONS = re.compile(r'^(--no-glyph-names|--no-positions|--no-clusters|--font-funcs=ot|--features=\S+|--script=\S+|--direction=\S+|--language=\S+)$')

def glyph_id(font, name):
    # HarfBuzz names the glyphs without a name gidN
    if name not in font.getReverseGlyphMap() and re.match(r'^gid\d+$', name):
        return int(name[3:])

    return font.getGlyphID(name)


root = sys.argv[1]
base = os.path.join(root, 'test', 'shape', 'data', 'in-house')
here = os.path.dirname(os.path.abspath(__file__))
fonts_dir = os.path.join(here, 'fonts')
os.makedirs(fonts_dir, exist_ok=True)
for name in os.listdir(fonts_dir):
    if name.endswith('.ttf'):
        os.remove(os.path.join(fonts_dir, name))

output = []
families = {}
for test in TESTS:
    for number, line in enumerate(open(os.path.join(base, 'tests', test), encoding='utf-8'), start=1):
        line = line.rstrip('\n')
        if not line or line.startswith('#') or line.startswith('@'):
            continue

        font_path, options, unicodes, expected = line.split(';')
        path = os.path.normpath(os.path.join(base, 'tests', font_path))
        if not os.path.exists(path) or os.path.getsize(path) > MAX_FONT_SIZE:
            continue

        font = TTFont(path)
        family = font['name'].getDebugName(1) or ''
        if not FAMILIES.match(family) or family in EXCLUDED_FAMILIES:
            continue

        options = options.split()
        if not all(SUPPORTED_OPTIONS.match(option) for option in options):
            print('skipped (options): %s:%d' % (test, number))
            continue

        # The glyph names to glyph ids
        if '--no-glyph-names' not in options and expected != '[]':
            glyphs = []
            for glyph in expected[1:-1].split('|'):
                match = re.match(r'^([^=@+]+)(.*)$', glyph)
                glyphs.append('%d%s' % (glyph_id(font, match.group(1)), match.group(2)))

            expected = '[' + '|'.join(glyphs) + ']'
            options = options + ['--no-glyph-names']

        name = os.path.basename(path)
        shutil.copyfile(path, os.path.join(fonts_dir, name))
        families[name] = family
        output.append(';'.join(['%s:%d' % (test, number), name, ' '.join(options), unicodes, expected]))

with open(os.path.join(here, 'harfbuzz.tests'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Generated by make-harfbuzz-tests.py from the shaping tests of HarfBuzz (test/shape/data/in-house, MIT license)\n')
    for line in output:
        f.write(line + '\n')

with open(os.path.join(fonts_dir, 'FONTS.txt'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('The fonts of the shaping tests of HarfBuzz (test/shape/data/in-house/fonts, subsets of the fonts below).\n')
    f.write('The Noto and Lohit fonts are licensed under the SIL Open Font License 1.1 (OFL.txt), the Droid fonts under\n')
    f.write('the Apache License 2.0 (LICENSE-Apache-2.0.txt).\n\n')
    for name, family in sorted(families.items()):
        f.write('%s: %s\n' % (name, family))

print('%d tests, %d fonts' % (len(output), len(families)))
