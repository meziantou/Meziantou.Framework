using System.IO.Compression;
using System.Security;
using System.Security.Cryptography;
using System.Text;
using Meziantou.Framework.Geo.Maps.GeoPackage;

namespace Meziantou.Framework.Geo.Maps.Tool;

/// <summary>
/// Writes the NuGet package of a bundle, without the SDK: the map in data/ (the folder data/&lt;Region&gt;/, or the file
/// data/&lt;Region&gt;.gpkg), and buildTransitive targets that copy it to the maps folder next to the application, where
/// <see cref="MapCatalog.Default"/> reads it. The entries have a fixed date, so that the same bundle gives the same package.
/// </summary>
internal static class NuGetPackageWriter
{
    private static readonly DateTimeOffset EntryDate = new(2000, 1, 1, 0, 0, 0, TimeSpan.Zero);

    public static FullPath Write(Region region, MapFormat format, string mapPath, IEnumerable<MapLayer> layers, PackageOptions options)
    {
        var id = options.IdPrefix + "." + region.Key;
        var version = options.Version;
        var files = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
        if (Directory.Exists(mapPath))
        {
            foreach (var file in Directory.EnumerateFiles(mapPath))
            {
                files[$"data/{region.Key}/{Path.GetFileName(file)}"] = File.ReadAllBytes(file);
            }
        }
        else
        {
            files[$"data/{Path.GetFileName(mapPath)}"] = File.ReadAllBytes(mapPath);
        }

        // A GeoPackage map needs the format of its package to be read
        var dependency = format is GeoPackageMapFormat ? typeof(GeoPackageMapFormat).Assembly : typeof(Map).Assembly;
        var dependencyId = dependency.GetName().Name!;
        var dependencyVersion = dependency.GetName().Version!.ToString(3);

        files[$"buildTransitive/{id}.targets"] = Encoding.UTF8.GetBytes(
            """
            <Project>
              <ItemGroup>
                <None Include="$(MSBuildThisFileDirectory)../data/**/*" Link="maps/%(RecursiveDir)%(Filename)%(Extension)" CopyToOutputDirectory="PreserveNewest" CopyToPublishDirectory="PreserveNewest" Visible="false" />
              </ItemGroup>
            </Project>
            """);

        var description = $"The map of {region.Name}: {GetLayerList(layers)}, as {format.Name}, for {dependencyId}, generated by Meziantou.Framework.Geo.Maps.Tool. {RegionBuilder.Attribution}";
        var psmdcp = $"package/services/metadata/core-properties/{Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(id + version)))[..32]}.psmdcp";

        Directory.CreateDirectory(options.OutputDirectory);
        var path = options.OutputDirectory / $"{id}.{version}.nupkg";
        using var stream = File.Create(path);
        using var zip = new ZipArchive(stream, ZipArchiveMode.Create);
        Add(zip, "[Content_Types].xml", """
            <?xml version="1.0" encoding="utf-8"?>
            <Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
              <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml" />
              <Default Extension="psmdcp" ContentType="application/vnd.openxmlformats-package.core-properties+xml" />
              <Default Extension="nuspec" ContentType="application/octet" />
              <Default Extension="fgb" ContentType="application/octet" />
              <Default Extension="geojson" ContentType="application/octet" />
              <Default Extension="gpkg" ContentType="application/octet" />
              <Default Extension="json" ContentType="application/octet" />
              <Default Extension="targets" ContentType="application/octet" />
            </Types>
            """);
        Add(zip, "_rels/.rels", $"""
            <?xml version="1.0" encoding="utf-8"?>
            <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
              <Relationship Type="http://schemas.microsoft.com/packaging/2010/07/manifest" Target="/{id}.nuspec" Id="R1" />
              <Relationship Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="/{psmdcp}" Id="R2" />
            </Relationships>
            """);
        Add(zip, $"{id}.nuspec", $"""
            <?xml version="1.0" encoding="utf-8"?>
            <package xmlns="http://schemas.microsoft.com/packaging/2013/05/nuspec.xsd">
              <metadata>
                <id>{id}</id>
                <version>{version}</version>
                <authors>{Escape(options.Authors)}</authors>
                <description>{Escape(description)}</description>
                <license type="expression">ODbL-1.0</license>
                <licenseUrl>https://licenses.nuget.org/ODbL-1.0</licenseUrl>
                <projectUrl>https://github.com/meziantou/Meziantou.Framework</projectUrl>
                <tags>map maps geo gis offline borders cities {format.Name.ToLowerInvariant()} openstreetmap natural-earth</tags>
                <dependencies>
                  <group>
                    <dependency id="{dependencyId}" version="{dependencyVersion}" />
                  </group>
                </dependencies>
              </metadata>
            </package>
            """);
        Add(zip, psmdcp, $"""
            <?xml version="1.0" encoding="utf-8"?>
            <coreProperties xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns="http://schemas.openxmlformats.org/package/2006/metadata/core-properties">
              <dc:creator>{Escape(options.Authors)}</dc:creator>
              <dc:description>{Escape(description)}</dc:description>
              <dc:identifier>{id}</dc:identifier>
              <version>{version}</version>
              <lastModifiedBy>Meziantou.Framework.Geo.Maps.Tool</lastModifiedBy>
            </coreProperties>
            """);
        foreach (var (name, content) in files)
        {
            Add(zip, name, content);
        }

        return path;
    }

    /// <summary>Gets the layers of a bundle as a list in English, such as <c>borders, cities and lakes</c>.</summary>
    public static string GetLayerList(IEnumerable<MapLayer> layers)
    {
        var layerNames = layers.Order().Select(layer => layer switch
        {
            MapLayer.StatesProvinces => "states and provinces",
            MapLayer.MarineAreas => "seas and gulfs",
            MapLayer.PhysicalRegions => "physical regions",
            _ => layer.ToString().ToLowerInvariant(),
        }).ToList();
        return layerNames.Count > 1 ? string.Join(", ", layerNames[..^1]) + " and " + layerNames[^1] : string.Join("", layerNames);
    }

    private static void Add(ZipArchive zip, string name, string text) => Add(zip, name, Encoding.UTF8.GetBytes(text));

    private static void Add(ZipArchive zip, string name, byte[] content)
    {
        var entry = zip.CreateEntry(name, CompressionLevel.Optimal);
        entry.LastWriteTime = EntryDate;
        using var stream = entry.Open();
        stream.Write(content);
    }

    private static string Escape(string text) => SecurityElement.Escape(text);
}
