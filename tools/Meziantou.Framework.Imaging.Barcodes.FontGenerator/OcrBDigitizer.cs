using System.Globalization;
using System.Text;
using Meziantou.Framework.Imaging;

namespace Meziantou.Framework.Imaging.Barcodes.FontGenerator;

/// <summary>
/// Extracts the centerlines of the OCR-B characters from the 4:1 illustrations of ANSI X3.49-1975 (Fig. 141 and 142),
/// rendered at 600 dpi: each character is thinned to its skeleton, which is traced into polylines between its ends and
/// its junctions. The result is the source of <c>OcrB.Centerlines.cs</c>; the illustrations are not committed.
/// </summary>
internal static class OcrBDigitizer
{
    // 4:1 illustrations rendered at 600 dpi: one millimeter of the character is 4 mm of the illustration
    private const double PixelsPerMillimeter = 600 / 25.4 * 4;
    private const double PixelsPerUnit = PixelsPerMillimeter / OcrFont.UnitsPerMillimeter;
    private const double PitchPixels = 2.54 * PixelsPerMillimeter;

    /// <summary>A page: the rows of the 4:1 block, top to bottom, with a space for an empty cell, and the area of the block.</summary>
    public sealed record Page(string Path, int Top, int Bottom, int Left, int Right, string[] Rows, int?[]? Baselines = null);

    public static string Digitize(IReadOnlyList<Page> pages)
    {
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated/>");
        output.AppendLine("// Centerlines of the OCR-B characters, traced from the 4:1 illustrations of ANSI X3.49-1975 (Fig. 141 and 142) by");
        output.AppendLine("// OcrBDigitizer, in font units (baseline at y = 0, the middle of the advance at x = 300). See readme.md.");
        output.AppendLine("namespace Meziantou.Framework.Imaging.Barcodes.FontGenerator;");
        output.AppendLine();
        output.AppendLine("internal static partial class OcrB");
        output.AppendLine("{");
        output.AppendLine("    private static readonly TracedGlyph[] TracedGlyphs =");
        output.AppendLine("    [");
        foreach (var page in pages)
        {
            foreach (var glyph in DigitizePage(page))
            {
                output.Append("        new(").Append(Quote(glyph.Character)).Append(", ");
                output.Append(glyph.StrokeWidth.ToString("F1", CultureInfo.InvariantCulture)).Append(", [");
                output.Append(string.Join(", ", glyph.Strokes.Select(stroke => "[" + string.Join(", ", stroke.Select(point => $"{point.X}, {point.Y}")) + "]")));
                output.Append("], [");
                output.Append(string.Join(", ", glyph.Outlines.Select(outline => "[" + string.Join(", ", outline.Select(point => $"{point.X}, {point.Y}")) + "]")));
                output.AppendLine("]),");
            }
        }

        output.AppendLine("    ];");
        output.AppendLine("}");
        return output.ToString();
    }

    private static string Quote(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c is '"' or '\\' ? "\\" + c : c < 0x20 || c > 0x7E ? $"\\u{(int)c:X4}" : c.ToString());
        }

        return builder.Append('"').ToString();
    }

    private static List<DigitizedGlyph> DigitizePage(Page page)
    {
        using var image = Image.Load<Rgba32>(page.Path);
        var width = image.Width;
        var pixels = new Rgba32[image.Width * image.Height];
        image.Frames[0].CopyPixelDataTo(pixels);
        bool IsInk(int x, int y) => x >= page.Left && x < page.Right && y >= page.Top && y < page.Bottom && ((pixels[(y * width) + x].R + pixels[(y * width) + x].G + pixels[(y * width) + x].B) / 3) < 150;

        // The rows are the bands of the block that hold ink, separated by blank lines
        var bands = new List<(int Top, int Bottom)>();
        int? start = null;
        for (var y = page.Top; y <= page.Bottom; y++)
        {
            var hasInk = false;
            for (var x = page.Left; x < page.Right && !hasInk && y < page.Bottom; x++)
            {
                hasInk = IsInk(x, y);
            }

            if (hasInk && start is null)
            {
                start = y;
            }
            else if (!hasInk && start is not null)
            {
                if (y - start.Value > 20)
                {
                    bands.Add((start.Value, y));
                }

                start = null;
            }
        }

        if (bands.Count != page.Rows.Length)
            throw new InvalidOperationException($"{page.Path}: {bands.Count} rows of ink, {page.Rows.Length} expected: {string.Join(", ", bands)}");

        var glyphs = new List<DigitizedGlyph>();
        for (var row = 0; row < bands.Count; row++)
        {
            var (top, bottom) = bands[row];
            var components = FindComponents(IsInk, page.Left, page.Right, top, bottom);
            var text = page.Rows[row];

            // The cells are on the pitch: their phase is the circular mean of the centers of the components
            double sin = 0, cos = 0;
            foreach (var component in components)
            {
                var angle = 2 * Math.PI * ((component.Left + component.Right) / 2.0) / PitchPixels;
                sin += Math.Sin(angle) * component.Pixels.Count;
                cos += Math.Cos(angle) * component.Pixels.Count;
            }

            var phase = Math.Atan2(sin, cos) / (2 * Math.PI) * PitchPixels;
            int CellOf(Component component) => (int)Math.Round((((component.Left + component.Right) / 2.0) - phase) / PitchPixels, MidpointRounding.AwayFromZero);
            var firstCell = components.Min(CellOf);
            var cells = new Dictionary<int, List<Component>>();
            foreach (var component in components)
            {
                var cell = CellOf(component) - firstCell;
                if (!cells.TryGetValue(cell, out var list))
                {
                    cells[cell] = list = [];
                }

                list.Add(component);
            }

            // The baseline of the row: the most common bottom of the characters, less half a stroke
            var bottoms = cells.Values.Select(list => list.Max(component => component.Bottom)).Order().ToArray();
            var baselineInk = page.Baselines is not null && page.Baselines[row] is { } fixedBaseline ? fixedBaseline : bottoms[bottoms.Length / 2];
            Console.Error.WriteLine($"{Path.GetFileName(page.Path)} row {row}: band {top}-{bottom}, ink baseline {baselineInk}, {cells.Count} cells");
            foreach (var (cell, list) in cells.OrderBy(pair => pair.Key))
            {
                if (cell < 0 || cell >= text.Length || text[cell] == ' ')
                    continue;

                var character = text[cell].ToString();
                var cellCenter = phase + ((cell + firstCell) * PitchPixels);
                var digitized = DigitizeGlyph(character, list, cellCenter, baselineInk);
                glyphs.Add(digitized with { CellCenter = cellCenter, Baseline = baselineInk - (digitized.StrokeWidth / 2 * PixelsPerUnit) });
            }
        }

        return glyphs;
    }

    // The characters that are not strokes of a constant width: their outline is traced instead of their centerline
    private const string OutlinedCharacters = ",;'_";

    private static DigitizedGlyph DigitizeGlyph(string character, List<Component> components, double cellCenter, int baselineInk)
    {
        var isSmall = character.Length == 1 && char.IsLower(character[0]);
        var nominalWidth = (isSmall ? 0.31 : 0.35) * OcrFont.UnitsPerMillimeter;

        // The ink of the characters is a stroke of the nominal width: its centerline is half a stroke above the bottom
        // of the ink on the baseline
        var baseline = baselineInk - (nominalWidth / 2 * PixelsPerUnit);
        (int X, int Y) ToUnits(double x, double y) => ((int)Math.Round(((x - cellCenter) / PixelsPerUnit) + (OcrFont.Advance / 2.0), MidpointRounding.AwayFromZero), (int)Math.Round((baseline - y) / PixelsPerUnit, MidpointRounding.AwayFromZero));

        var strokes = new List<List<(int X, int Y)>>();
        var outlines = new List<List<(int X, int Y)>>();
        foreach (var component in components)
        {
            List<(int X, int Y)> TraceOutline() => Simplify([.. Smooth([.. Skeleton.Outline(component), Skeleton.Outline(component)[0]], window: 2).Select(point => ToUnits(point.X, point.Y))], tolerance: 1.5);

            if (OutlinedCharacters.Contains(character, StringComparison.Ordinal))
            {
                outlines.Add(TraceOutline());
                continue;
            }

            var chains = Skeleton.Trace(component, spurLength: nominalWidth * 0.75 * PixelsPerUnit, maxHoleArea: (int)Math.Pow(nominalWidth * 0.5 * PixelsPerUnit, 2));

            // A dot: its skeleton is shorter than a stroke is wide; its outline is traced
            var skeletonLength = chains.Sum(chain => chain.Points.Zip(chain.Points.Skip(1), (a, b) => Math.Sqrt(Math.Pow(b.X - a.X, 2) + Math.Pow(b.Y - a.Y, 2))).Sum());
            if (chains.Count == 0 || skeletonLength < nominalWidth * 1.2 * PixelsPerUnit)
            {
                outlines.Add(TraceOutline());
                continue;
            }

            foreach (var chain in chains)
            {
                var smoothed = Smooth(chain.Points, window: 4);
                var straightening = nominalWidth * 0.5 * PixelsPerUnit;
                if (chain.StartIsEnd)
                {
                    smoothed = StraightenStart(smoothed, straightening);
                }

                if (chain.EndIsEnd)
                {
                    smoothed.Reverse();
                    smoothed = StraightenStart(smoothed, straightening);
                    smoothed.Reverse();
                }

                var points = smoothed.Select(point => ToUnits(point.X, point.Y)).ToList();
                strokes.Add(Simplify(points, tolerance: 2.5));
            }
        }

        return new DigitizedGlyph(character, Math.Round(nominalWidth, 1, MidpointRounding.AwayFromZero), strokes, outlines);
    }

    // The skeleton bends near a free end, where the outline of the end is cut at an angle: the last points are replaced by
    // the extension of the direction of the chain before them, as far as the end reached
    private static List<(double X, double Y)> StraightenStart(List<(double X, double Y)> points, double length)
    {
        static double Distance((double X, double Y) a, (double X, double Y) b) => Math.Sqrt(Math.Pow(b.X - a.X, 2) + Math.Pow(b.Y - a.Y, 2));

        var cut = 1;
        var walked = 0.0;
        while (cut < points.Count - 1 && walked + Distance(points[cut - 1], points[cut]) < length)
        {
            walked += Distance(points[cut - 1], points[cut]);
            cut++;
        }

        var inner = cut;
        var innerWalked = 0.0;
        while (inner < points.Count - 1 && innerWalked < length)
        {
            innerWalked += Distance(points[inner], points[inner + 1]);
            inner++;
        }

        if (inner == cut)
            return points;

        var (dx, dy) = (points[cut].X - points[inner].X, points[cut].Y - points[inner].Y);
        var norm = Math.Sqrt((dx * dx) + (dy * dy));
        var reach = Distance(points[0], points[cut]);
        var end = (points[cut].X + (dx / norm * reach), points[cut].Y + (dy / norm * reach));
        return [end, .. points.Skip(cut)];
    }

    private static List<(double X, double Y)> Smooth(List<(double X, double Y)> points, int window)
    {
        var closed = points.Count > 2 && points[0] == points[^1];
        var result = new List<(double X, double Y)>(points.Count);
        for (var i = 0; i < points.Count; i++)
        {
            if (!closed && (i == 0 || i == points.Count - 1))
            {
                result.Add(points[i]);
                continue;
            }

            double sx = 0, sy = 0;
            var count = 0;
            for (var k = -window; k <= window; k++)
            {
                var j = i + k;
                if (closed)
                {
                    j = ((j % (points.Count - 1)) + points.Count - 1) % (points.Count - 1);
                }
                else if (j < 0 || j >= points.Count)
                {
                    continue;
                }

                sx += points[j].X;
                sy += points[j].Y;
                count++;
            }

            result.Add((sx / count, sy / count));
        }

        if (closed)
        {
            result[^1] = result[0];
        }

        return result;
    }

    // Douglas-Peucker
    private static List<(int X, int Y)> Simplify(List<(int X, int Y)> points, double tolerance)
    {
        if (points.Count <= 2)
            return points;

        var keep = new bool[points.Count];
        keep[0] = keep[^1] = true;
        var stack = new Stack<(int First, int Last)>();
        stack.Push((0, points.Count - 1));
        while (stack.Count > 0)
        {
            var (first, last) = stack.Pop();
            var (ax, ay) = points[first];
            var (bx, by) = points[last];
            var length = Math.Sqrt(((bx - ax) * (bx - ax)) + ((by - ay) * (by - ay)));
            var maxDistance = 0.0;
            var index = -1;
            for (var i = first + 1; i < last; i++)
            {
                var (px, py) = points[i];
                var distance = length == 0 ? Math.Sqrt(((px - ax) * (px - ax)) + ((py - ay) * (py - ay))) : Math.Abs(((bx - ax) * (ay - py)) - ((ax - px) * (by - ay))) / length;
                if (distance > maxDistance)
                {
                    maxDistance = distance;
                    index = i;
                }
            }

            if (maxDistance > tolerance)
            {
                keep[index] = true;
                stack.Push((first, index));
                stack.Push((index, last));
            }
        }

        return [.. points.Where((_, i) => keep[i])];
    }

    private static List<Component> FindComponents(Func<int, int, bool> isInk, int left, int right, int top, int bottom)
    {
        var seen = new HashSet<(int, int)>();
        var components = new List<Component>();
        for (var y = top; y < bottom; y++)
        {
            for (var x = left; x < right; x++)
            {
                if (!isInk(x, y) || !seen.Add((x, y)))
                    continue;

                var pixels = new List<(int X, int Y)>();
                var queue = new Queue<(int X, int Y)>();
                queue.Enqueue((x, y));
                while (queue.Count > 0)
                {
                    var (px, py) = queue.Dequeue();
                    pixels.Add((px, py));
                    for (var dy = -1; dy <= 1; dy++)
                    {
                        for (var dx = -1; dx <= 1; dx++)
                        {
                            var (nx, ny) = (px + dx, py + dy);
                            if (ny >= top && ny < bottom && isInk(nx, ny) && seen.Add((nx, ny)))
                            {
                                queue.Enqueue((nx, ny));
                            }
                        }
                    }
                }

                // Specks of the scan
                if (pixels.Count >= 60)
                {
                    components.Add(new Component(pixels));
                }
            }
        }

        return components;
    }

    private sealed record DigitizedGlyph(string Character, double StrokeWidth, List<List<(int X, int Y)>> Strokes, List<List<(int X, int Y)>> Outlines)
    {
        public double CellCenter { get; init; }

        public double Baseline { get; init; }
    }

    /// <summary>Writes, for each character of a page, the illustration and the outline of the glyph of the font drawn over it in red.</summary>
    public static void WriteReview(Page page, OcrFont font, string outputPath)
    {
        var glyphs = DigitizePage(page);
        using var scan = Image.Load<Rgba32>(page.Path);
        const int Columns = 6;
        const int RowsPerSheet = 3;
        var cellWidth = (int)PitchPixels;
        var cellHeight = (int)(4.6 * PixelsPerMillimeter);
        var designs = font.Glyphs.ToDictionary(design => design.CodePoints[0]);
        for (var sheetIndex = 0; sheetIndex * Columns * RowsPerSheet < glyphs.Count; sheetIndex++)
        {
            var sheetGlyphs = glyphs.Skip(sheetIndex * Columns * RowsPerSheet).Take(Columns * RowsPerSheet).ToList();
            using var sheet = new Image<Rgba32>(cellWidth * Columns, cellHeight * ((sheetGlyphs.Count + Columns - 1) / Columns), Colors.White);
            sheet.Draw(canvas =>
            {
                for (var i = 0; i < sheetGlyphs.Count; i++)
                {
                    var glyph = sheetGlyphs[i];
                    var originX = (i % Columns) * cellWidth;
                    var originY = (i / Columns) * cellHeight;

                    // The baseline is 3.3 mm below the top of the cell
                    var source = new Rectangle((int)(glyph.CellCenter - (cellWidth / 2.0)), (int)(glyph.Baseline - (3.3 * PixelsPerMillimeter)), cellWidth, cellHeight);
                    canvas.DrawImage(scan.Frames[0], source, new RectangleD(originX, originY, cellWidth, cellHeight));
                    if (!designs.TryGetValue(char.ConvertToUtf32(glyph.Character, 0), out var design))
                        continue;

                    var pen = new Imaging.Drawing.Pen(new Imaging.Drawing.SolidBrush(Colors.Red), 2);
                    foreach (var contour in OutlineBuilder.Build(design))
                    {
                        var points = contour.Select(p => new PointD(originX + (cellWidth / 2.0) + ((p.X - (OcrFont.Advance / 2.0)) * PixelsPerUnit), originY + (3.3 * PixelsPerMillimeter) - (p.Y * PixelsPerUnit))).ToArray();
                        canvas.StrokePolygon(pen, points);
                    }
                }
            });
            sheet.Save(outputPath.Replace(".png", $"-{sheetIndex}.png", StringComparison.Ordinal), new Imaging.Formats.PngEncoder());
        }
    }
}

/// <summary>The pixels of a connected area of ink.</summary>
internal sealed class Component
{
    public Component(List<(int X, int Y)> pixels)
    {
        Pixels = pixels;
        Left = pixels.Min(p => p.X);
        Right = pixels.Max(p => p.X) + 1;
        Top = pixels.Min(p => p.Y);
        Bottom = pixels.Max(p => p.Y) + 1;
    }

    public List<(int X, int Y)> Pixels { get; }

    public int Left { get; }

    public int Right { get; }

    public int Top { get; }

    public int Bottom { get; }
}
