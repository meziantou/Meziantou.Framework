using Meziantou.Framework.Imaging.CorpusGenerator.Common;

namespace Meziantou.Framework.Imaging.Barcodes.FontGenerator;

/// <summary>A monospaced OCR font: its names, its glyph designs and the TrueType file built from them.</summary>
internal sealed class OcrFont
{
    /// <summary>The units per em of the fonts.</summary>
    public const int UnitsPerEm = 1000;

    /// <summary>The advance of every glyph: the 0.1 inch (2.54 mm) character pitch of the standards, 0.6 em.</summary>
    public const int Advance = 600;

    /// <summary>The number of font units per millimeter: the 2.54 mm pitch is the advance.</summary>
    public const double UnitsPerMillimeter = Advance / 2.54;

    public required string FileName { get; init; }

    public required string FamilyName { get; init; }

    public required string PostScriptName { get; init; }

    public required string Standard { get; init; }

    public required IReadOnlyList<GlyphDesign> Glyphs { get; init; }

    /// <summary>Builds the TrueType file.</summary>
    public byte[] Build()
    {
        var builder = new FontBuilder
        {
            UnitsPerEm = UnitsPerEm,
            FamilyName = FamilyName,
            SubfamilyName = "Regular",
            PostScriptName = PostScriptName,
            IsMonospaced = true,
            CmapFormats = FontCmapFormats.Format4,
        };

        builder.ExtraNames[0] = $"Generated by Meziantou.Framework from the character shapes of {Standard}.";
        builder.ExtraNames[3] = $"Meziantou.Framework: {PostScriptName}";
        builder.ExtraNames[5] = "Version 1.000";
        builder.ExtraNames[13] = "Licensed under the MIT License.";
        builder.ExtraNames[14] = "https://github.com/meziantou/Meziantou.Framework/blob/main/LICENSE.txt";

        // .notdef: an empty box, then the space
        var notdef = new FontGlyph { AdvanceWidth = Advance };
        notdef.Contours.Add([new(100, 0), new(100, 700), new(500, 700), new(500, 0)]);
        notdef.Contours.Add([new(150, 50), new(450, 50), new(450, 650), new(150, 650)]);
        builder.Glyphs.Add(notdef);
        builder.Glyphs.Add(FontGlyph.Empty(Advance));
        builder.CharacterMap[' '] = 1;
        builder.CharacterMap[0xA0] = 1;

        var yMin = 0;
        var yMax = 0;
        foreach (var design in Glyphs)
        {
            var glyph = new FontGlyph { AdvanceWidth = Advance };
            var glyphTop = int.MinValue;
            foreach (var contour in OutlineBuilder.Build(design))
            {
                glyph.Contours.Add([.. contour.Select(point => new FontPoint(point.X, point.Y))]);
                yMin = Math.Min(yMin, contour.Min(point => point.Y));
                yMax = Math.Max(yMax, contour.Max(point => point.Y));
                glyphTop = Math.Max(glyphTop, contour.Max(point => point.Y));
            }

            // The OS/2 heights are the tops of the ink of "H" and "x"
            if (design.CodePoints.Contains('H'))
            {
                builder.CapHeight = glyphTop;
            }
            else if (design.CodePoints.Contains('x'))
            {
                builder.XHeight = glyphTop;
            }

            var glyphIndex = builder.Glyphs.Count;
            builder.Glyphs.Add(glyph);
            foreach (var codePoint in design.CodePoints)
            {
                if (!builder.CharacterMap.TryAdd(codePoint, glyphIndex))
                    throw new InvalidOperationException($"U+{codePoint:X4} is mapped twice ({design.Name}).");
            }
        }

        // The line spans every glyph, so that nothing is clipped
        builder.Ascender = yMax;
        builder.Descender = yMin;
        builder.TypoAscender = yMax;
        builder.TypoDescender = yMin;
        builder.WinAscent = yMax;
        builder.WinDescent = -yMin;
        builder.LineGap = 0;
        builder.UnderlinePosition = -100;
        builder.UnderlineThickness = 80;
        return builder.Build();
    }
}
