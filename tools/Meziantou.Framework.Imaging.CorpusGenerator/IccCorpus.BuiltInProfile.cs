using System.Globalization;
using System.Text;
using Meziantou.Framework.Imaging.CorpusGenerator.Infrastructure;

namespace Meziantou.Framework.Imaging.CorpusGenerator;

/// <summary>
/// Transcribes the CMYK profile that the library provides (<c>IccProfile.Cgats001CompatibleCmyk</c>) from the committed
/// corpus into the source of the library: the profile is third-party data (CC0-1.0), so its bytes are never typed by
/// hand and always come from the file pinned by its SHA-256.
/// </summary>
internal static partial class IccCorpus
{
    private const string BuiltInProfileId = "icc/cgats001-compat-v2-micro";
    private const string BuiltInProfileSource = "src/Meziantou.Framework.Imaging/Internals/Color/BuiltInCmykProfile.g.cs";

    public static int RunBuiltInProfile(GeneratorOptions options)
    {
        var profile = Profiles.Single(profile => profile.Id == BuiltInProfileId);
        var data = File.ReadAllBytes(CorpusDriver.CorpusDir / "icc" / "profiles" / profile.FileName);
        var hash = Bytes.Sha256Hex(data);
        if (hash != profile.Sha256)
            throw new FatalException($"{profile.FileName} has sha256 {hash} but {profile.Sha256} is pinned (commit {ProfilesCommit} of {ProfilesRepository}).");

        var source = RenderBuiltInProfile(profile.FileName, data, hash);
        var target = CorpusDriver.RepoRoot / BuiltInProfileSource;
        if (File.Exists(target) && string.Equals(File.ReadAllText(target, Encoding.UTF8), source, StringComparison.Ordinal))
        {
            Console.WriteLine($"{BuiltInProfileSource} is reproducible ({data.Length} bytes).");
            return 0;
        }

        if (!options.Write)
        {
            Console.WriteLine($"{BuiltInProfileSource} differs from the generator output. Review, then rerun with --write.");
            return 1;
        }

        File.WriteAllText(target, source, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Console.WriteLine($"{BuiltInProfileSource} written ({data.Length} bytes). Review the diff before committing.");
        return 0;
    }

    private static string RenderBuiltInProfile(string fileName, byte[] data, string hash)
    {
        var builder = new StringBuilder();
        builder.Append("// <auto-generated>\n");
        builder.Append(CultureInfo.InvariantCulture, $"// Transcribed by tools/Meziantou.Framework.Imaging.CorpusGenerator (icc-builtin) from {fileName} of\n");
        builder.Append(CultureInfo.InvariantCulture, $"// {ProfilesRepository} (commit {ProfilesCommit}), by Clinton Ingram,\n");
        builder.Append(CultureInfo.InvariantCulture, $"// released to the public domain (CC0-1.0). SHA-256 {hash}\n");
        builder.Append("// Do not edit this file: run the generator again.\n");
        builder.Append("// </auto-generated>\n\n");
        builder.Append("namespace Meziantou.Framework.Imaging.Internals;\n\n");
        builder.Append("/// <summary>The bytes of the CMYK profile provided by the library (<see cref=\"BuiltInIccProfiles.Cgats001CompatibleCmyk\"/>).</summary>\n");
        builder.Append("internal static class BuiltInCmykProfile\n{\n");
        builder.Append(CultureInfo.InvariantCulture, $"    /// <summary>Gets the {data.Length} bytes of <c>{fileName}</c>.</summary>\n");
        builder.Append("    public static ReadOnlySpan<byte> Data =>\n    [\n");
        for (var i = 0; i < data.Length; i += 16)
        {
            builder.Append("        ");
            var end = Math.Min(data.Length, i + 16);
            for (var j = i; j < end; j++)
            {
                builder.Append(CultureInfo.InvariantCulture, $"0x{data[j]:X2},");
                if (j + 1 < end)
                {
                    builder.Append(' ');
                }
            }

            builder.Append('\n');
        }

        builder.Append("    ];\n}\n");
        return builder.ToString();
    }
}
