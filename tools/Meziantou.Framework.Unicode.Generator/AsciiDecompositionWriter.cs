using System.Text;
using Meziantou.Framework;

/// <summary>Writes the table that Meziantou.Framework.Markdown uses to make the ASCII identifiers of the headings.</summary>
/// <remarks>
/// A character maps to the ASCII characters of its compatibility decomposition (NFKD), such as <c>é</c> to <c>e</c>,
/// <c>½</c> to <c>12</c> or <c>ǆ</c> to <c>dz</c>, as Markdig does. The characters below U+00A0, and the ones whose
/// decomposition has no ASCII character other than whitespace, are not in the table.
/// </remarks>
internal static class AsciiDecompositionWriter
{
    private const int FirstCodePoint = 0xA0;
    private const int CodeUnitCount = 0x10000;

    public static async Task<bool> WriteAsync(FullPath outputFilePath)
    {
        Console.WriteLine("Loading the ASCII decompositions...");
        var combiningClass = await PropertyTablesWriter.LoadCombiningClassAsync();
        var (canonical, compatibility) = await NormalizationWriter.LoadDecompositionMappingsAsync();

        var entries = new SortedDictionary<int, string>();
        foreach (var codePoint in canonical.Keys.Concat(compatibility.Keys).Distinct())
        {
            if (codePoint is < FirstCodePoint or >= CodeUnitCount || NormalizationWriter.IsHangulSyllable(codePoint))
                continue;

            var ascii = new StringBuilder();
            foreach (var value in NormalizationWriter.Decompose(codePoint, canonical, compatibility, combiningClass))
            {
                if (value < 0x80)
                {
                    ascii.Append((char)value);
                }
            }

            if (ascii.ToString().Trim().Length > 0)
            {
                entries.Add(codePoint, ascii.ToString());
            }
        }

        var lines = new StringBuilder();
        foreach (var (codePoint, ascii) in entries)
        {
            lines.Append(CultureInfo.InvariantCulture, $"        ['\\u{codePoint:X4}'] = \"{Escape(ascii)}\",\n");
        }

        var content = string.Create(CultureInfo.InvariantCulture, $$"""
            // <auto-generated />
            // Generated from the Unicode Character Database {{Ucd.Version}}
            // Data sources: {{Ucd.GetUrl("ucd/UnicodeData.txt")}}
            //               {{Ucd.GetUrl("ucd/extracted/DerivedCombiningClass.txt")}}
            // Entries: {{entries.Count:N0}}
            // DO NOT MODIFY THIS FILE MANUALLY - regenerate using the Unicode generator tool

            #nullable enable

            using System.Collections.Frozen;

            namespace Meziantou.Framework.Markdown.Parsing;

            static partial class CharNormalizer
            {
                // The ASCII characters of the compatibility decomposition (NFKD) of the characters from U+00A0, when they are
                // not only whitespace
                private static readonly FrozenDictionary<char, string> CodeToAscii = new Dictionary<char, string>({{entries.Count}})
                {
            {{lines}}    }.ToFrozenDictionary();
            }

            """).ReplaceLineEndings("\n");

        Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"  ASCII decompositions: {entries.Count:N0}"));
        return await GeneratorFiles.WriteTextIfChanged(outputFilePath, content);
    }

    private static string Escape(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            if (c is '"' or '\\')
            {
                builder.Append('\\');
            }

            builder.Append(c);
        }

        return builder.ToString();
    }
}
