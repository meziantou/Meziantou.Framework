using System.Text;
using Meziantou.Framework;

/// <summary>Writes the table that Meziantou.Framework.Markdown uses to match the labels of the links.</summary>
/// <remarks>
/// CommonMark matches the labels with the Unicode case folding: the table is the full case folding of CaseFolding.txt
/// (statuses C and F, without the Turkic mappings of status T), as the reference implementation (cmark) does. For instance,
/// <c>ẞ</c> folds to <c>ss</c> and <c>ﬀ</c> to <c>ff</c>.
/// </remarks>
internal static class CaseFoldingWriter
{
    public static async Task<bool> WriteAsync(FullPath outputFilePath)
    {
        Console.WriteLine("Loading the full case folding...");
        var entries = new SortedDictionary<int, string>();
        foreach (var line in Ucd.ParseLines(await Ucd.DownloadAsync("ucd/CaseFolding.txt")))
        {
            // code; status; mapping;
            if (line.IsMissing || line.Start != line.End || line.Fields.Length < 2 || line.Fields[0] is not ("C" or "F"))
                continue;

            var folded = new StringBuilder();
            foreach (var value in line.Fields[1].Split(' ', StringSplitOptions.RemoveEmptyEntries))
            {
                folded.Append(char.ConvertFromUtf32(int.Parse(value, NumberStyles.HexNumber, CultureInfo.InvariantCulture)));
            }

            entries.Add(line.Start, folded.ToString());
        }

        if (entries.Count == 0)
            throw new InvalidOperationException("No full case folding in CaseFolding.txt");

        var lines = new StringBuilder();
        foreach (var (codePoint, folded) in entries)
        {
            lines.Append(CultureInfo.InvariantCulture, $"        [0x{codePoint:X4}] = \"{Escape(folded)}\",\n");
        }

        var content = string.Create(CultureInfo.InvariantCulture, $$"""
            // <auto-generated />
            // Generated from the Unicode Character Database {{Ucd.Version}}
            // Data sources: {{Ucd.GetUrl("ucd/CaseFolding.txt")}}
            // Entries: {{entries.Count:N0}}
            // DO NOT MODIFY THIS FILE MANUALLY - regenerate using the Unicode generator tool

            #nullable enable

            using System.Collections.Frozen;

            namespace Meziantou.Framework.Markdown.Parsing;

            static partial class CaseFolding
            {
                // The full case folding of the code points (statuses C and F of CaseFolding.txt, without the Turkic mappings)
                private static readonly FrozenDictionary<int, string> CodePointToFolded = new Dictionary<int, string>({{entries.Count}})
                {
            {{lines}}    }.ToFrozenDictionary();
            }

            """).ReplaceLineEndings("\n");

        Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"  Full case foldings: {entries.Count:N0}"));
        return await GeneratorFiles.WriteTextIfChanged(outputFilePath, content);
    }

    private static string Escape(string value)
    {
        var builder = new StringBuilder(value.Length * 6);
        for (var i = 0; i < value.Length; i++)
        {
            var codePoint = char.ConvertToUtf32(value, i);
            if (codePoint > 0xFFFF)
            {
                builder.Append(CultureInfo.InvariantCulture, $"\\U{codePoint:X8}");
                i++;
            }
            else if (codePoint is >= 0x20 and < 0x7F and not '"' and not '\\')
            {
                builder.Append((char)codePoint);
            }
            else
            {
                builder.Append(CultureInfo.InvariantCulture, $"\\u{codePoint:X4}");
            }
        }

        return builder.ToString();
    }
}
