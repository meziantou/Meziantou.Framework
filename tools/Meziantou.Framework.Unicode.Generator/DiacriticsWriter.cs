using Meziantou.Framework;

/// <summary>Writes the table <c>StringExtensions.RemoveDiacritics</c> uses when the runtime cannot normalize strings.</summary>
/// <remarks>
/// <c>RemoveDiacritics</c> decomposes a string (NFD), removes the nonspacing marks, and composes the result (NFC). In
/// the invariant globalization mode, the runtime does not normalize strings, so the table maps each UTF-16 code unit
/// to the code unit these three steps give for it alone, when they give a single one.
/// </remarks>
internal static class DiacriticsWriter
{
    private const int CodeUnitCount = 0x10000;

    public static async Task<bool> WriteAsync(FullPath outputFilePath)
    {
        Console.WriteLine("Loading the diacritic replacements...");
        var generalCategory = await PropertyTablesWriter.LoadGeneralCategoryAsync();
        var combiningClass = await PropertyTablesWriter.LoadCombiningClassAsync();
        var (canonical, _) = await NormalizationWriter.LoadDecompositionMappingsAsync();

        var exclusions = new HashSet<int>();
        foreach (var line in Ucd.ParseLines(await Ucd.DownloadAsync("ucd/DerivedNormalizationProps.txt")))
        {
            if (!line.IsMissing && line.Fields[0] == "Full_Composition_Exclusion")
            {
                for (var codePoint = line.Start; codePoint <= line.End; codePoint++)
                {
                    exclusions.Add(codePoint);
                }
            }
        }

        var compositions = new Dictionary<(int First, int Second), int>();
        foreach (var (codePoint, values) in canonical)
        {
            if (values.Length == 2 && !exclusions.Contains(codePoint))
            {
                compositions.Add((values[0], values[1]), codePoint);
            }
        }

        // The Hangul syllables are left out: their decomposition holds no nonspacing mark, so they compose back to themselves.
        var replacements = new SortedDictionary<int, int>();
        foreach (var codePoint in canonical.Keys)
        {
            if (codePoint >= CodeUnitCount || NormalizationWriter.IsHangulSyllable(codePoint))
                continue;

            var remaining = NormalizationWriter.Decompose(codePoint, canonical, compatibility: null, combiningClass)
                .Where(value => generalCategory[value] != (byte)UnicodeCategory.NonSpacingMark)
                .ToList();
            if (remaining.Count == 0)
                continue;

            var composed = Compose(remaining, compositions, combiningClass);
            if (composed.Count == 1 && composed[0] != codePoint && composed[0] < CodeUnitCount)
            {
                replacements.Add(codePoint, composed[0]);
            }
        }

        // The table is applied once, so a replacement must not have a replacement of its own.
        foreach (var (codePoint, replacement) in replacements)
        {
            if (replacements.ContainsKey(replacement))
                throw new InvalidOperationException($"The replacement of U+{codePoint:X4} (U+{replacement:X4}) has a replacement");
        }

        // A two-stage table of the difference between the replacement and the code unit, modulo 2^16: a code unit
        // without a replacement has 0, so the blocks of code units without replacements are shared.
        var deltas = new ushort[CodeUnitCount];
        foreach (var (codePoint, replacement) in replacements)
        {
            deltas[codePoint] = (ushort)(replacement - codePoint);
        }

        (int Shift, byte[] Stage1, byte[] Stage2)? best = null;
        for (var shift = 3; shift <= 8; shift++)
        {
            var candidate = BuildTable(deltas, shift);
            if (candidate is not null && (best is null || candidate.Value.Stage1.Length + candidate.Value.Stage2.Length < best.Value.Stage1.Length + best.Value.Stage2.Length))
            {
                best = candidate;
            }
        }

        if (best is not { } table)
            throw new InvalidOperationException("No block size fits the diacritic table");

        var blockSize = 1 << table.Shift;
        for (var codeUnit = 0; codeUnit < CodeUnitCount; codeUnit++)
        {
            var offset = ((table.Stage1[codeUnit >> table.Shift] << table.Shift) | (codeUnit & (blockSize - 1))) * 2;
            if ((table.Stage2[offset] | (table.Stage2[offset + 1] << 8)) != deltas[codeUnit])
                throw new InvalidOperationException($"The diacritic table disagrees with its source at U+{codeUnit:X4}");
        }

        var byteCount = table.Stage1.Length + table.Stage2.Length;
        var content = string.Create(CultureInfo.InvariantCulture, $$"""
            // <auto-generated />
            // Generated from the Unicode Character Database {{Ucd.Version}}
            // Data sources: {{Ucd.GetUrl("ucd/UnicodeData.txt")}}
            //               {{Ucd.GetUrl("ucd/extracted/DerivedGeneralCategory.txt")}}
            //               {{Ucd.GetUrl("ucd/extracted/DerivedCombiningClass.txt")}}
            //               {{Ucd.GetUrl("ucd/DerivedNormalizationProps.txt")}}
            // Replacements: {{replacements.Count:N0}} ({{byteCount:N0}} bytes)
            // DO NOT MODIFY THIS FILE MANUALLY - regenerate using the Unicode generator tool

            #nullable enable

            using System.Runtime.CompilerServices;

            namespace Meziantou.Framework;

            static partial class StringExtensions
            {
                /// <summary>
                /// Gets the character that remains of <paramref name="c"/> once it is decomposed (NFD), its nonspacing marks
                /// are removed, and the result is composed (NFC), or <paramref name="c"/> when these steps do not give a single
                /// other character.
                /// </summary>
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                internal static char RemoveDiacritic(char c)
                {
                    var offset = ((DiacriticBlocks[c >> {{table.Shift}}] << {{table.Shift}}) | (c & {{blockSize - 1}})) * 2;
                    return (char)(c + (DiacriticDeltas[offset] | (DiacriticDeltas[offset + 1] << 8)));
                }

                // For each group of {{blockSize}} code units, the index of a block of DiacriticDeltas.
                private static ReadOnlySpan<byte> DiacriticBlocks =>
                [{{TrieBuilder.FormatElements<byte>(table.Stage1, "        ")}}
                ];

                // Blocks of {{blockSize}} differences between the replacement and the code unit, modulo 2^16, in little-endian order.
                private static ReadOnlySpan<byte> DiacriticDeltas =>
                [{{TrieBuilder.FormatElements<byte>(table.Stage2, "        ")}}
                ];
            }

            """).ReplaceLineEndings("\n");

        Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"  Diacritic replacements: {replacements.Count:N0} ({byteCount:N0} bytes)"));
        return await GeneratorFiles.WriteTextIfChanged(outputFilePath, content);
    }

    /// <summary>Applies the canonical composition algorithm to a sequence in canonical order (Unicode Standard Annex #15).</summary>
    private static List<int> Compose(List<int> values, Dictionary<(int First, int Second), int> compositions, byte[] combiningClass)
    {
        var result = new List<int>(values.Count) { values[0] };
        var starterIndex = combiningClass[values[0]] == 0 ? 0 : -1;
        var lastClass = combiningClass[values[0]] == 0 ? 0 : 256;
        foreach (var value in values.Skip(1))
        {
            var valueClass = combiningClass[value];
            if (starterIndex >= 0 && (lastClass < valueClass || lastClass == 0) && compositions.TryGetValue((result[starterIndex], value), out var composite))
            {
                result[starterIndex] = composite;
                continue;
            }

            if (valueClass == 0)
            {
                starterIndex = result.Count;
            }

            lastClass = valueClass;
            result.Add(value);
        }

        return result;
    }

    private static (int Shift, byte[] Stage1, byte[] Stage2)? BuildTable(ushort[] deltas, int shift)
    {
        var blockSize = 1 << shift;
        var stage1 = new byte[deltas.Length >> shift];
        var stage2 = new List<byte>();
        var blocks = new Dictionary<string, int>(StringComparer.Ordinal);
        for (var i = 0; i < stage1.Length; i++)
        {
            var block = deltas.AsSpan(i << shift, blockSize);
            var key = string.Join(',', block.ToArray());
            if (!blocks.TryGetValue(key, out var index))
            {
                index = blocks.Count;
                if (index > byte.MaxValue)
                    return null;

                blocks.Add(key, index);
                foreach (var delta in block)
                {
                    stage2.Add((byte)delta);
                    stage2.Add((byte)(delta >> 8));
                }
            }

            stage1[i] = (byte)index;
        }

        return (shift, stage1, [.. stage2]);
    }
}
