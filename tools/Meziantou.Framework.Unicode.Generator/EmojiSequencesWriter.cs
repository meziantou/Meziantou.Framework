using Meziantou.Framework;

/// <summary>Writes the emoji properties of strings of UTS #51 (emoji-sequences.txt and emoji-zwj-sequences.txt).</summary>
internal static class EmojiSequencesWriter
{
    // The properties, in the order of UnicodeEmojiSequenceProperty, with the name of the generated table.
    private static readonly (string Name, string Table)[] Properties =
    [
        ("Basic_Emoji", "BasicEmoji"),
        ("Emoji_Keycap_Sequence", "EmojiKeycapSequence"),
        ("RGI_Emoji_Flag_Sequence", "RgiEmojiFlagSequence"),
        ("RGI_Emoji_Modifier_Sequence", "RgiEmojiModifierSequence"),
        ("RGI_Emoji_Tag_Sequence", "RgiEmojiTagSequence"),
        ("RGI_Emoji_ZWJ_Sequence", "RgiEmojiZwjSequence"),
    ];

    public static async Task<bool> WriteAsync(FullPath outputPath)
    {
        Console.WriteLine("Loading the emoji sequences...");
        var sequences = Properties.ToDictionary(property => property.Name, _ => new List<int[]>(), StringComparer.Ordinal);
        foreach (var file in (string[])["emoji/emoji-sequences.txt", "emoji/emoji-zwj-sequences.txt"])
        {
            var content = await Ucd.DownloadAsync(file);
            foreach (var rawLine in content.Split('\n'))
            {
                var line = rawLine;
                var commentIndex = line.IndexOf('#', StringComparison.Ordinal);
                if (commentIndex >= 0)
                {
                    line = line[..commentIndex];
                }

                line = line.Trim();
                if (line.Length == 0)
                    continue;

                var fields = line.Split(';', StringSplitOptions.TrimEntries);
                if (fields.Length < 2)
                    throw new InvalidOperationException($"Invalid line in {file}: {rawLine}");

                if (!sequences.TryGetValue(fields[1], out var list))
                    throw new InvalidOperationException($"Unknown property '{fields[1]}' in {file}: decide how to expose it");

                var codePoints = fields[0];
                var rangeSeparator = codePoints.IndexOf("..", StringComparison.Ordinal);
                if (rangeSeparator >= 0)
                {
                    // A range of single code points (Basic_Emoji)
                    var start = int.Parse(codePoints[..rangeSeparator], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
                    var end = int.Parse(codePoints[(rangeSeparator + 2)..], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
                    for (var codePoint = start; codePoint <= end; codePoint++)
                    {
                        list.Add([codePoint]);
                    }
                }
                else
                {
                    list.Add([.. codePoints.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(item => int.Parse(item, NumberStyles.HexNumber, CultureInfo.InvariantCulture))]);
                }
            }
        }

        var tables = new StringBuilder();
        var sizes = new List<(string Name, int Bytes)>();
        var arms = new StringBuilder();
        var statistics = new StringBuilder();
        for (var i = 0; i < Properties.Length; i++)
        {
            var (name, table) = Properties[i];
            var list = sequences[name];
            if (list.Count == 0)
                throw new InvalidOperationException($"No sequence of '{name}'");

            var bytes = new List<byte>();
            foreach (var sequence in list)
            {
                if (sequence.Length is 0 or > byte.MaxValue)
                    throw new InvalidOperationException($"Invalid length of a sequence of '{name}'");

                bytes.Add((byte)sequence.Length);
                bytes.AddRange(PropertyTablesWriter.EncodeUInt24(sequence));
            }

            PropertyTablesWriter.AppendBytes(tables, sizes, table, [.. bytes], $"{name}: for each sequence, the number of code points (1 byte) then the code points (3 bytes each, little-endian).");
            arms.Append(CultureInfo.InvariantCulture, $"            {i} => {table},\n");
            statistics.Append(CultureInfo.InvariantCulture, $"//   - {name}: {list.Count} sequences\n");
        }

        var content2 = string.Create(CultureInfo.InvariantCulture, $$"""
            // <auto-generated />
            // Generated from the emoji data of Unicode {{Ucd.Version}}
            // Data source: {{Ucd.GetUrl("emoji/emoji-sequences.txt")}}, {{Ucd.GetUrl("emoji/emoji-zwj-sequences.txt")}}
            // Statistics:
            {{statistics.ToString().TrimEnd()}}
            //   - Encoded size: {{sizes.Sum(size => size.Bytes):N0}} bytes
            //
            // Specification: https://www.unicode.org/reports/tr51/
            // DO NOT MODIFY THIS FILE MANUALLY - regenerate using the Unicode generator tool

            #nullable enable

            namespace Meziantou.Framework;

            /// <summary>The sequences of the emoji properties of strings.</summary>
            internal static class UnicodeEmojiSequenceTables
            {
                /// <summary>Gets the encoded sequences of a property, by the numeric value of a UnicodeEmojiSequenceProperty.</summary>
                internal static ReadOnlySpan<byte> GetSequences(int property)
                {
                    return property switch
                    {
            {{arms.ToString().TrimEnd()}}
                        _ => default,
                    };
                }
            {{tables.ToString().TrimEnd()}}
            }

            """).ReplaceLineEndings("\n");

        Console.WriteLine($"  Emoji sequences: {sequences.Values.Sum(list => list.Count)} sequences");
        return await GeneratorFiles.WriteTextIfChanged(outputPath / "UnicodeEmojiSequences.g.cs", content2);
    }
}
