using System.Numerics;
using System.Text.RegularExpressions;
using Meziantou.Framework;
using static Meziantou.Framework.UnicodeDataFormat;

/// <summary>Writes the tables of <c>UnicodeCharacterInfos.g.cs</c> and reads them back, so that a refresh can be diffed.</summary>
/// <remarks>See <see cref="UnicodeDataFormat"/> for the layout of the tables.</remarks>
internal static partial class UnicodeCharacterInfosWriter
{
    private static readonly string[] TableNames =
    [
        "PropertyIndexStage1", "PropertyIndexStage2", "PropertyIndexStage3", "Properties", "RangeNames", "NameBuckets", "NameEntries", "NameText",
        "Decompositions", "DecompositionMappings", "NumericValues", "Unicode1Names", "IsoComments", "StringOffsets", "Strings",
    ];

    /// <summary>Generates the content of <c>UnicodeCharacterInfos.g.cs</c>.</summary>
    /// <param name="entries">The characters, in any order.</param>
    /// <param name="dataSource">The URL of <c>UnicodeData.txt</c>, for the header.</param>
    public static string Generate(IReadOnlyList<UnicodeDataEntry> entries, string dataSource)
    {
        var ordered = entries.OrderBy(entry => entry.Rune.Value).ToList();
        var tables = new Dictionary<string, byte[]>(StringComparer.Ordinal);
        var strings = new StringPool();

        // The tags come first so that their string index fits in the byte of a decomposition mapping.
        var parsedDecompositions = ordered
            .Where(entry => entry.DecompositionMapping is not null)
            .Select(entry => (entry.Rune.Value, Mapping: ParseDecompositionMapping(entry.DecompositionMapping!)))
            .ToList();
        foreach (var tag in parsedDecompositions.Select(item => item.Mapping.Tag).OfType<string>().Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
        {
            if (strings.Add(tag) >= byte.MaxValue)
                throw new InvalidOperationException("Too many decomposition tags");
        }

        var trie = WriteProperties(tables, ordered);
        WriteNames(tables, ordered, strings);
        WriteDecompositions(tables, parsedDecompositions, strings);
        WriteStringValues(tables, "NumericValues", ordered, entry => entry.NumericValue, strings);
        WriteStringValues(tables, "Unicode1Names", ordered, entry => entry.Unicode1Name, strings);
        WriteStringValues(tables, "IsoComments", ordered, entry => entry.IsoComment, strings);
        strings.Write(tables);

        // Names are decoded through a single stack buffer, and the front-coding lengths are UTF-8 byte counts.
        var maxNameLength = ordered.Max(entry => Encoding.UTF8.GetByteCount(entry.Name));
        var maxNameLengthPowerOfTwo = (int)BitOperations.RoundUpToPowerOf2((uint)maxNameLength);
        if (maxNameLengthPowerOfTwo > 256)
            throw new InvalidOperationException("Max name length exceeds 256: " + maxNameLengthPowerOfTwo);

        // Enumerating the characters skips these blocks rather than looking up every code point they cover.
        var block3Size = 1 << trie.Shift2;
        var block2Size = 1 << (trie.Shift1 - trie.Shift2);
        var emptyBlock3 = Enumerable.Range(0, trie.Stage3.Length / block3Size)
            .FirstOrDefault(block => trie.Stage3.AsSpan(block * block3Size, block3Size).IndexOfAnyExcept((ushort)0) < 0, -1);
        var emptyBlock2 = emptyBlock3 < 0 ? -1 : Enumerable.Range(0, trie.Stage2.Length / block2Size)
            .FirstOrDefault(block => trie.Stage2.AsSpan(block * block2Size, block2Size).IndexOfAnyExcept((ushort)emptyBlock3) < 0, -1);

        var namedCount = ordered.Count(entry => !IsSharedName(entry.Name));
        var emojiCount = ordered.Count(entry => entry.EmojiProperties != EmojiProperties.None);
        var totalSize = tables.Values.Sum(table => table.Length);

        var sb = new StringBuilder();
        sb.Append(string.Create(CultureInfo.InvariantCulture, $$"""
            // <auto-generated />
            // Generated from Unicode Character Database
            // Data source: {{dataSource}}
            // Statistics:
            //   - Total characters: {{ordered.Count}}
            //   - Emoji characters: {{emojiCount}}
            //   - Table size: {{totalSize:N0}} bytes ({{(double)totalSize / ordered.Count:F2}} bytes per character)

            """));
        foreach (var name in TableNames)
        {
            sb.Append(CultureInfo.InvariantCulture, $"//     - {name}: {tables[name].Length:N0} bytes\n");
        }

        sb.Append(string.Create(CultureInfo.InvariantCulture, $$"""
            //   - Max name length: {{maxNameLength}} bytes
            //
            // Specification: https://www.unicode.org/reports/tr44/
            // DO NOT MODIFY THIS FILE MANUALLY - regenerate using the Unicode generator tool

            #nullable enable

            namespace Meziantou.Framework;

            // See UnicodeDataFormat for the layout of the tables.
            internal static partial class UnicodeCharacterInfos
            {
                private const int MaxSerializedStringLength = {{maxNameLengthPowerOfTwo}};

                /// <summary>Number of characters written to the tables, as counted by the generator.</summary>
                internal const int GeneratedCharacterCount = {{ordered.Count}};

                private const int NamedCharacterCount = {{namedCount}};

                private const int PropertyIndexShift1 = {{trie.Shift1}};

                private const int PropertyIndexShift2 = {{trie.Shift2}};

                // The blocks of the second and third stages that only lead to code points that are not characters, or -1.
                private const int PropertyIndexEmptyBlock2 = {{emptyBlock2}};

                private const int PropertyIndexEmptyBlock3 = {{emptyBlock3}};

            """));

        foreach (var name in TableNames)
        {
            sb.Append(CultureInfo.InvariantCulture, $"\n    private static ReadOnlySpan<byte> {name} =>");
            if (name is "NameText" or "Strings")
            {
                AppendUtf8Literal(sb, tables[name], name is "Strings" ? strings.Lengths : null);
            }
            else
            {
                sb.Append("\n    [").Append(TrieBuilder.FormatElements<byte>(tables[name], "        ")).Append("\n    ];\n");
            }
        }

        sb.Append("}\n");
        Console.WriteLine($"  {ordered.Count} characters in {totalSize} bytes of tables");
        return sb.ToString();
    }

    private static WideTrie WriteProperties(Dictionary<string, byte[]> tables, List<UnicodeDataEntry> entries)
    {
        // Record 0 stays all zeros: it is what a code point that is not a character, and a default
        // UnicodeCharacterInfo, read.
        var indexes = new Dictionary<UnicodeCharacterProperties, int>();
        var properties = new List<UnicodeCharacterProperties> { default };
        var values = new ushort[Trie.CodePointCount];
        foreach (var entry in entries)
        {
            var value = CreateProperties(entry);
            if (!indexes.TryGetValue(value, out var index))
            {
                index = properties.Count;
                if (index > ushort.MaxValue)
                    throw new InvalidOperationException("Too many distinct property tuples");

                indexes.Add(value, index);
                properties.Add(value);
            }

            values[entry.Rune.Value] = (ushort)index;
        }

        var bytes = new List<byte>(properties.Count * PropertyRecordSize);
        foreach (var value in properties)
        {
            bytes.Add((byte)value.Category);
            bytes.Add((byte)value.BidiCategory);
            bytes.Add(value.CanonicalCombiningClass);
            bytes.Add(unchecked((byte)value.DecimalDigitValue));
            bytes.Add(unchecked((byte)value.DigitValue));
            bytes.Add(value.EmojiProperties);
            bytes.Add(value.Flags);
            WriteInt24(bytes, value.SimpleUppercaseDelta);
            WriteInt24(bytes, value.SimpleLowercaseDelta);
            WriteInt24(bytes, value.SimpleTitlecaseDelta);
        }

        var trie = TrieBuilder.BuildWide(values);
        tables["PropertyIndexStage1"] = Encode(trie.Stage1);
        tables["PropertyIndexStage2"] = Encode(trie.Stage2);
        tables["PropertyIndexStage3"] = Encode(trie.Stage3);
        tables["Properties"] = [.. bytes];
        Console.WriteLine($"  {properties.Count - 1} distinct property tuples, {trie.ByteCount} bytes of three-stage table");
        return trie;

        static byte[] Encode(ushort[] values) => Trie.Encode(values, width: 2);
    }

    private static UnicodeCharacterProperties CreateProperties(UnicodeDataEntry entry)
    {
        var codePoint = entry.Rune.Value;
        byte flags = 0;
        if (entry.Mirrored)
        {
            flags |= MirroredFlag;
        }

        if (entry.SimpleUppercaseMapping >= 0)
        {
            flags |= HasUppercaseFlag;
        }

        if (entry.SimpleLowercaseMapping >= 0)
        {
            flags |= HasLowercaseFlag;
        }

        if (entry.SimpleTitlecaseMapping >= 0)
        {
            flags |= HasTitlecaseFlag;
        }

        return new UnicodeCharacterProperties(
            entry.Category,
            entry.BidiCategory,
            entry.CanonicalCombiningClass,
            entry.DecimalDigitValue,
            entry.DigitValue,
            (byte)entry.EmojiProperties,
            flags,
            entry.SimpleUppercaseMapping >= 0 ? entry.SimpleUppercaseMapping - codePoint : 0,
            entry.SimpleLowercaseMapping >= 0 ? entry.SimpleLowercaseMapping - codePoint : 0,
            entry.SimpleTitlecaseMapping >= 0 ? entry.SimpleTitlecaseMapping - codePoint : 0);
    }

    // Writes the names, splitting the ones a whole range shares from the ones that are unique.
    private static void WriteNames(Dictionary<string, byte[]> tables, List<UnicodeDataEntry> entries, StringPool strings)
    {
        var ranges = new List<(int Start, int End, string Name)>();
        foreach (var entry in entries.Where(entry => IsSharedName(entry.Name)))
        {
            var codePoint = entry.Rune.Value;
            if (ranges.Count > 0 && ranges[^1].End + 1 == codePoint && string.Equals(ranges[^1].Name, entry.Name, StringComparison.Ordinal))
            {
                ranges[^1] = (ranges[^1].Start, codePoint, entry.Name);
                continue;
            }

            ranges.Add((codePoint, codePoint, entry.Name));
        }

        var rangeBytes = new List<byte>();
        foreach (var (start, end, name) in ranges)
        {
            WriteUInt24(rangeBytes, start);
            WriteUInt24(rangeBytes, end);
            WriteUInt16(rangeBytes, strings.Add(name));
        }

        // Front-coding restarts at every bucket so a name can be decoded without replaying the whole table; the
        // bucket records are what make that random access possible.
        var named = entries.Where(entry => !IsSharedName(entry.Name)).ToList();
        var buckets = new List<byte>();
        var nameEntries = new List<byte>();
        var text = new List<byte>();
        var previous = Array.Empty<byte>();
        var previousCodePoint = 0;
        for (var i = 0; i < named.Count; i++)
        {
            var codePoint = named[i].Rune.Value;
            if (i % NameBucketSize == 0)
            {
                WriteUInt24(buckets, codePoint);
                WriteUInt24(buckets, nameEntries.Count);
                WriteUInt24(buckets, text.Count);
                previous = [];
                previousCodePoint = codePoint;
            }

            var bytes = GetAsciiBytes(named[i].Name);
            var sharedPrefixLength = 0;
            var max = Math.Min(previous.Length, bytes.Length);
            while (sharedPrefixLength < max && previous[sharedPrefixLength] == bytes[sharedPrefixLength])
            {
                sharedPrefixLength++;
            }

            WriteVarInt(nameEntries, codePoint - previousCodePoint);
            nameEntries.Add((byte)sharedPrefixLength);
            nameEntries.Add((byte)(bytes.Length - sharedPrefixLength));
            text.AddRange(bytes.AsSpan(sharedPrefixLength));
            previous = bytes;
            previousCodePoint = codePoint;
        }

        tables["RangeNames"] = [.. rangeBytes];
        tables["NameBuckets"] = [.. buckets];
        tables["NameEntries"] = [.. nameEntries];
        tables["NameText"] = [.. text];
        Console.WriteLine($"  {named.Count} unique names ({text.Count} bytes of text), {ranges.Count} ranges of shared names");
    }

    // Whether a name belongs to a range rather than to a single character, such as "<CJK Ideograph>".
    private static bool IsSharedName(string name) => name.Length > 0 && name[0] == '<';

    // Writes the decomposition mappings as a tag and code points rather than as hexadecimal text.
    private static void WriteDecompositions(Dictionary<string, byte[]> tables, List<(int CodePoint, (string? Tag, List<int> CodePoints) Mapping)> decompositions, StringPool strings)
    {
        var records = new List<byte>();
        var mappings = new List<byte>();
        foreach (var (codePoint, (tag, codePoints)) in decompositions)
        {
            WriteUInt24(records, codePoint);
            WriteUInt24(records, mappings.Count);
            mappings.Add(tag is null ? (byte)0 : (byte)(strings.Add(tag) + 1));
            if (codePoints.Count > byte.MaxValue)
                throw new InvalidOperationException($"Decomposition mapping of U+{codePoint:X4} is too long");

            mappings.Add((byte)codePoints.Count);
            foreach (var value in codePoints)
            {
                WriteVarInt(mappings, value);
            }
        }

        tables["Decompositions"] = [.. records];
        tables["DecompositionMappings"] = [.. mappings];
        Console.WriteLine($"  {decompositions.Count} decomposition mappings");
    }

    private static (string? Tag, List<int> CodePoints) ParseDecompositionMapping(string value)
    {
        string? tag = null;
        var rest = value;
        if (value.Length > 0 && value[0] == '<')
        {
            var end = value.IndexOf('>', StringComparison.Ordinal);
            if (end < 0)
                throw new InvalidOperationException("Unterminated decomposition tag: " + value);

            tag = value[..(end + 1)];
            rest = value[(end + 1)..];
        }

        var codePoints = new List<int>();
        foreach (var token in rest.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            codePoints.Add(int.Parse(token, NumberStyles.HexNumber, CultureInfo.InvariantCulture));
        }

        return (tag, codePoints);
    }

    // Writes a property only a few thousand characters have as a sorted side table.
    private static void WriteStringValues(Dictionary<string, byte[]> tables, string name, List<UnicodeDataEntry> entries, Func<UnicodeDataEntry, string?> selector, StringPool strings)
    {
        var present = entries.Where(entry => selector(entry) is not null).ToList();
        foreach (var value in present.Select(entry => selector(entry)!).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
        {
            strings.Add(value);
        }

        var bytes = new List<byte>();
        foreach (var entry in present)
        {
            WriteUInt24(bytes, entry.Rune.Value);
            WriteUInt16(bytes, strings.Add(selector(entry)!));
        }

        tables[name] = [.. bytes];
        Console.WriteLine($"  {name}: {present.Count} entries");
    }

    // The text is emitted as UTF-8 string literals rather than numbers: it is smaller and readable, and the
    // compiler folds the concatenation into a single blob of static data.
    private static void AppendUtf8Literal(StringBuilder sb, byte[] text, IReadOnlyList<int>? lineLengths)
    {
        if (text.Length == 0)
        {
            sb.Append(" [];\n");
            return;
        }

        var lines = new List<string>();
        if (lineLengths is not null)
        {
            var offset = 0;
            foreach (var length in lineLengths)
            {
                lines.Add(Encoding.ASCII.GetString(text, offset, length));
                offset += length;
            }
        }
        else
        {
            for (var offset = 0; offset < text.Length; offset += 100)
            {
                lines.Add(Encoding.ASCII.GetString(text, offset, Math.Min(100, text.Length - offset)));
            }
        }

        var literals = lines.ConvertAll(line => "\"" + line.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"u8");
        sb.Append("\n        ").Append(Concatenate(literals, 0, literals.Count)).Append(";\n");

        // A long chain of + is a deep tree that overflows the stack of some analyzers, so the literals are
        // concatenated as a balanced tree of short chains.
        static string Concatenate(List<string> literals, int start, int end)
        {
            const int MaxChainLength = 16;
            if (end - start <= MaxChainLength)
                return string.Join(" +\n        ", literals.GetRange(start, end - start));

            var middle = start + ((end - start) / 2);
            return "(" + Concatenate(literals, start, middle) + ") +\n        (" + Concatenate(literals, middle, end) + ")";
        }
    }

    private static byte[] GetAsciiBytes(string value)
    {
        // The text tables are emitted as string literals, which can only hold the bytes of printable ASCII
        // characters one for one.
        foreach (var c in value)
        {
            if (c is < ' ' or > '~')
                throw new InvalidOperationException($"Unexpected character U+{(int)c:X4} in \"{value}\"");
        }

        if (value.Length > byte.MaxValue)
            throw new InvalidOperationException("String exceeds the maximum length of 255 bytes: " + value);

        return Encoding.ASCII.GetBytes(value);
    }

    private static void WriteVarInt(List<byte> destination, int value)
    {
        if (value < 0)
            throw new ArgumentOutOfRangeException(nameof(value), value, "The value must not be negative.");

        var remaining = (uint)value;
        while (remaining >= 0x80)
        {
            destination.Add((byte)(remaining | 0x80));
            remaining >>= 7;
        }

        destination.Add((byte)remaining);
    }

    private static void WriteUInt16(List<byte> destination, int value)
    {
        if (value is < 0 or > ushort.MaxValue)
            throw new ArgumentOutOfRangeException(nameof(value), value, "The value does not fit in 16 bits.");

        destination.Add((byte)value);
        destination.Add((byte)(value >> 8));
    }

    private static void WriteUInt24(List<byte> destination, int value)
    {
        if (value is < 0 or > 0xFFFFFF)
            throw new ArgumentOutOfRangeException(nameof(value), value, "The value does not fit in 24 bits.");

        destination.Add((byte)value);
        destination.Add((byte)(value >> 8));
        destination.Add((byte)(value >> 16));
    }

    private static void WriteInt24(List<byte> destination, int value)
    {
        if (value is < -0x800000 or > 0x7FFFFF)
            throw new ArgumentOutOfRangeException(nameof(value), value, "The value does not fit in 24 bits.");

        destination.Add((byte)value);
        destination.Add((byte)(value >> 8));
        destination.Add((byte)(value >> 16));
    }

    /// <summary>Reads back the tables of a file written by <see cref="Generate"/>.</summary>
    /// <returns>The characters, or <see langword="null"/> when the file is not in the current layout.</returns>
    public static Dictionary<Rune, UnicodeDataEntry>? Read(string source)
    {
        var constants = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (Match match in ConstantRegex().Matches(source))
        {
            constants[match.Groups["name"].Value] = int.Parse(match.Groups["value"].Value, NumberStyles.None, CultureInfo.InvariantCulture);
        }

        var tables = new Dictionary<string, byte[]>(StringComparer.Ordinal);
        foreach (Match match in TableRegex().Matches(source))
        {
            var body = match.Groups["body"].Value;
            tables[match.Groups["name"].Value] = body.StartsWith('[', StringComparison.Ordinal)
                ? [.. body.Trim('[', ']').Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Select(value => byte.Parse(value, NumberStyles.None, CultureInfo.InvariantCulture))]
                : [.. Utf8LiteralRegex().Matches(body).SelectMany(literal => Encoding.ASCII.GetBytes(Regex.Unescape(literal.Groups["text"].Value)))];
        }

        if (!TableNames.All(tables.ContainsKey) || !constants.TryGetValue("PropertyIndexShift1", out var shift1) || !constants.TryGetValue("PropertyIndexShift2", out var shift2))
            return null;

        var strings = new List<string>();
        var stringOffsets = tables["StringOffsets"];
        for (var offset = 0; offset + StringOffsetSize < stringOffsets.Length; offset += StringOffsetSize)
        {
            var start = ReadUInt24(stringOffsets, offset);
            strings.Add(Encoding.UTF8.GetString(tables["Strings"].AsSpan(start, ReadUInt24(stringOffsets, offset + StringOffsetSize) - start)));
        }

        var names = new Dictionary<int, string>();
        var rangeNames = tables["RangeNames"];
        for (var offset = 0; offset < rangeNames.Length; offset += RangeNameRecordSize)
        {
            for (var codePoint = ReadUInt24(rangeNames, offset); codePoint <= ReadUInt24(rangeNames, offset + 3); codePoint++)
            {
                names.Add(codePoint, strings[ReadUInt16(rangeNames, offset + 6)]);
            }
        }

        // Reading the names forward replays the front-coding of each bucket, so the bucket records are only needed
        // for the code point a bucket starts at.
        var nameBuckets = tables["NameBuckets"];
        var nameEntries = tables["NameEntries"];
        var nameText = tables["NameText"];
        var buffer = new byte[byte.MaxValue + 1];
        var entryPosition = 0;
        var textPosition = 0;
        var nameCodePoint = 0;
        for (var ordinal = 0; entryPosition < nameEntries.Length; ordinal++)
        {
            if (ordinal % NameBucketSize == 0)
            {
                nameCodePoint = ReadUInt24(nameBuckets, ordinal / NameBucketSize * NameBucketRecordSize);
            }

            nameCodePoint += ReadVarInt(nameEntries, ref entryPosition);
            var sharedPrefixLength = nameEntries[entryPosition];
            var suffixLength = nameEntries[entryPosition + 1];
            entryPosition += 2;
            nameText.AsSpan(textPosition, suffixLength).CopyTo(buffer.AsSpan(sharedPrefixLength));
            textPosition += suffixLength;
            names.Add(nameCodePoint, Encoding.UTF8.GetString(buffer, 0, sharedPrefixLength + suffixLength));
        }

        var decompositionMappings = new Dictionary<int, string>();
        var decompositions = tables["Decompositions"];
        var mappings = tables["DecompositionMappings"];
        for (var offset = 0; offset < decompositions.Length; offset += DecompositionRecordSize)
        {
            var position = ReadUInt24(decompositions, offset + 3);
            var tag = mappings[position];
            var mappingLength = mappings[position + 1];
            position += 2;
            var parts = new List<string>();
            if (tag != 0)
            {
                parts.Add(strings[tag - 1]);
            }

            for (var i = 0; i < mappingLength; i++)
            {
                parts.Add(ReadVarInt(mappings, ref position).ToString("X4", CultureInfo.InvariantCulture));
            }

            decompositionMappings.Add(ReadUInt24(decompositions, offset), string.Join(' ', parts));
        }

        var numericValues = ReadStringValues(tables["NumericValues"], strings);
        var unicode1Names = ReadStringValues(tables["Unicode1Names"], strings);
        var isoComments = ReadStringValues(tables["IsoComments"], strings);

        var stage1 = tables["PropertyIndexStage1"];
        var stage2 = tables["PropertyIndexStage2"];
        var stage3 = tables["PropertyIndexStage3"];
        var properties = tables["Properties"];
        var entries = new Dictionary<Rune, UnicodeDataEntry>();
        for (var codePoint = 0; codePoint < Trie.CodePointCount; codePoint++)
        {
            var block2 = ReadUInt16(stage1, (codePoint >> shift1) * 2);
            var block3 = ReadUInt16(stage2, ((block2 << (shift1 - shift2)) + ((codePoint >> shift2) & ((1 << (shift1 - shift2)) - 1))) * 2);
            var index = ReadUInt16(stage3, ((block3 << shift2) + (codePoint & ((1 << shift2) - 1))) * 2);
            if (index == 0)
                continue;

            var record = properties.AsSpan(index * PropertyRecordSize, PropertyRecordSize);
            var flags = record[FlagsField];
            entries.Add(new Rune(codePoint), new UnicodeDataEntry(
                new Rune(codePoint),
                names.GetValueOrDefault(codePoint, ""),
                (UnicodeCategory)record[CategoryField],
                (UnicodeBidirectionalCategory)record[BidiCategoryField],
                record[CanonicalCombiningClassField],
                decompositionMappings.GetValueOrDefault(codePoint),
                (sbyte)record[DecimalDigitValueField],
                (sbyte)record[DigitValueField],
                numericValues.GetValueOrDefault(codePoint),
                (flags & MirroredFlag) != 0,
                unicode1Names.GetValueOrDefault(codePoint),
                isoComments.GetValueOrDefault(codePoint),
                GetMapping(HasUppercaseFlag, UppercaseDeltaField),
                GetMapping(HasLowercaseFlag, LowercaseDeltaField),
                GetMapping(HasTitlecaseFlag, TitlecaseDeltaField),
                (EmojiProperties)record[EmojiPropertiesField]));

            int GetMapping(byte flag, int field) => (flags & flag) == 0 ? -1 : codePoint + ReadInt24(properties, (index * PropertyRecordSize) + field);
        }

        return entries;
    }

    private static Dictionary<int, string> ReadStringValues(byte[] records, List<string> strings)
    {
        var result = new Dictionary<int, string>();
        for (var offset = 0; offset < records.Length; offset += StringValueRecordSize)
        {
            result.Add(ReadUInt24(records, offset), strings[ReadUInt16(records, offset + 3)]);
        }

        return result;
    }

    [GeneratedRegex(@"const int (?<name>\w+) = (?<value>\d+);", RegexOptions.None, matchTimeoutMilliseconds: 10_000)]
    private static partial Regex ConstantRegex();

    [GeneratedRegex(@"ReadOnlySpan<byte> (?<name>\w+) =>\s*(?<body>\[[^\]]*\]|[(\s]*""(?:[^""\\]|\\.)*""u8(?:[\s()+]*""(?:[^""\\]|\\.)*""u8)*[)\s]*);", RegexOptions.None, matchTimeoutMilliseconds: 10_000)]
    private static partial Regex TableRegex();

    [GeneratedRegex(@"""(?<text>(?:[^""\\]|\\.)*)""u8", RegexOptions.None, matchTimeoutMilliseconds: 10_000)]
    private static partial Regex Utf8LiteralRegex();

    /// <summary>The strings of the tables, each stored once.</summary>
    private sealed class StringPool
    {
        private readonly Dictionary<string, int> _indexes = new(StringComparer.Ordinal);
        private readonly List<byte[]> _values = [];

        public IReadOnlyList<int> Lengths => [.. _values.Select(value => value.Length)];

        public int Add(string value)
        {
            if (!_indexes.TryGetValue(value, out var index))
            {
                index = _values.Count;
                if (index > ushort.MaxValue)
                    throw new InvalidOperationException("Too many distinct strings");

                _indexes.Add(value, index);
                _values.Add(GetAsciiBytes(value));
            }

            return index;
        }

        public void Write(Dictionary<string, byte[]> tables)
        {
            var offsets = new List<byte>();
            var text = new List<byte>();
            foreach (var value in _values)
            {
                WriteUInt24(offsets, text.Count);
                text.AddRange(value);
            }

            WriteUInt24(offsets, text.Count);
            tables["StringOffsets"] = [.. offsets];
            tables["Strings"] = [.. text];
            Console.WriteLine($"  {_values.Count} distinct strings ({text.Count} bytes)");
        }
    }
