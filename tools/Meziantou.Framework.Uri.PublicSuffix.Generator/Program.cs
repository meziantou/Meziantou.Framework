// Generates the rules of src/Meziantou.Framework.Uri/PublicSuffix/PublicSuffixList.g.cs from the copy of the list shared
// with Meziantou.Framework.WebPlatform (tests/Meziantou.Framework.WebPlatform.SpecData/publicsuffix/public_suffix_list.dat),
// so both libraries always embed the same version of the list. That file is downloaded by
// 'dotnet run --project tools/Meziantou.Framework.WebPlatform.SpecUpdate -- update publicsuffix'.
//
//   Generator            regenerate the rules and download the tests of the same commit of the list (exit code 1 when a file changed)
//   Generator --check    fail if the generated rules are out of date (no network access)

var check = args.Contains("--check", StringComparer.Ordinal);

if (!FullPath.CurrentDirectory().TryFindGitRepositoryRoot(out var root))
    throw new InvalidOperationException("Cannot find git root from " + FullPath.CurrentDirectory());

var packagePath = root / "src" / "Meziantou.Framework.Uri";
var outputPath = packagePath / "PublicSuffix";
var generatedFilePath = outputPath / "PublicSuffixList.g.cs";
var csprojPath = packagePath / "Meziantou.Framework.Uri.csproj";
var listFilePath = root / "tests" / "Meziantou.Framework.WebPlatform.SpecData" / "publicsuffix" / "public_suffix_list.dat";
var testDataFilePath = root / "tests" / "Meziantou.Framework.Uri.Tests" / "files" / "public_suffix_tests.txt";

Console.WriteLine("Reading " + listFilePath.MakePathRelativeTo(root));
var listContent = File.ReadAllText(listFilePath);
var (version, commitSha) = ParseHeader(listContent);
var (entries, ruleCount) = ParseList(listContent);
if (entries.Count is 0)
    throw new InvalidOperationException("The public suffix list is empty");

Console.WriteLine($"{ruleCount.ToString(CultureInfo.InvariantCulture)} rules, {entries.Count.ToString(CultureInfo.InvariantCulture)} entries");

// Group by the combined flags so each suffix appears in exactly one group.
// The runtime can then insert without merging, and a suffix that ever gains
// several flags (for instance "foo" as both a rule and a "*.foo" wildcard)
// gets its own group instead of breaking the load.
var groups = entries
    .GroupBy(entry => entry.Value)
    .OrderBy(group => (byte)group.Key)
    .Select(group => (Name: BuildGroupName(group.Key), Flags: group.Key, Suffixes: group.Select(entry => entry.Key).ToList()))
    .ToList();

var body = new StringBuilder();
body.Append("    private static FrozenDictionary<string, PublicSuffixRuleFlags> LoadRules()\n");
body.Append("    {\n");
body.Append("        var entries = new Dictionary<string, PublicSuffixRuleFlags>(EntryCount, StringComparer.Ordinal);\n");
foreach (var group in groups)
{
    body.Append("        AddRules(entries, ").Append(group.Name).Append("(), ").Append(BuildFlagsExpression(group.Flags)).Append(");\n");
}

body.Append("        return entries.ToFrozenDictionary(StringComparer.Ordinal);\n");
body.Append("    }\n");
foreach (var group in groups)
{
    body.Append('\n').Append(BuildGroup(group.Name, group.Suffixes)).Append('\n');
}

var generated = $$"""
    // <auto-generated />
    #nullable enable

    using System.Collections.Frozen;

    namespace Meziantou.Framework;

    static partial class PublicSuffixList
    {
        // Public Suffix List source: https://publicsuffix.org/list/public_suffix_list.dat
        // Version: {{version.ToString("O", CultureInfo.InvariantCulture)}}
        // Commit: https://github.com/publicsuffix/list/commit/{{commitSha}}
        private const int EntryCount = {{entries.Count.ToString(CultureInfo.InvariantCulture)}};
        private const int RuleCountValue = {{ruleCount.ToString(CultureInfo.InvariantCulture)}};
        private const long LastUpdatedTicks = {{version.UtcDateTime.Ticks.ToString(CultureInfo.InvariantCulture)}}L;

    {{body.ToString().TrimEnd('\n')}}
    }
    """.ReplaceLineEndings("\n");

if (check)
{
    if (File.Exists(generatedFilePath) && File.ReadAllText(generatedFilePath).ReplaceLineEndings("\n") == generated)
    {
        Console.WriteLine("The public suffix list is up to date");
        return 0;
    }

    Console.WriteLine($"{generatedFilePath.MakePathRelativeTo(root)} is not up to date: run 'dotnet run --project tools/Meziantou.Framework.Uri.PublicSuffix.Generator'");
    return 1;
}

// The tests of the list are not part of the published file, so they are downloaded from the commit the file was published from
var testsUrl = $"https://raw.githubusercontent.com/publicsuffix/list/{commitSha}/tests/tests.txt";
Console.WriteLine("Downloading " + testsUrl);
var testsContent = await SharedHttpClient.Instance.GetStringAsync(testsUrl);

Directory.CreateDirectory(outputPath);
Directory.CreateDirectory(testDataFilePath.Parent);

var updated = false;
updated |= WriteTextIfChanged(generatedFilePath, generated);
updated |= WriteTextIfChanged(testDataFilePath, testsContent.ReplaceLineEndings("\n"));

if (!updated)
{
    Console.WriteLine("The public suffix list is up to date");
    return 0;
}

Console.WriteLine("The files have been updated");
BumpPackageVersion(csprojPath);
RunGitDiff(root);
return 1;

// The published list starts with the version ("// VERSION: 2026-09-30_20-56-07_UTC") and the commit it was published from
static (DateTimeOffset Version, string CommitSha) ParseHeader(string content)
{
    string? version = null;
    string? commitSha = null;
    foreach (var rawLine in content.ReplaceLineEndings("\n").Split('\n'))
    {
        var line = rawLine.Trim();
        if (line.StartsWith("// VERSION: ", StringComparison.Ordinal))
        {
            version = line["// VERSION: ".Length..];
        }
        else if (line.StartsWith("// COMMIT: ", StringComparison.Ordinal))
        {
            commitSha = line["// COMMIT: ".Length..];
        }
        else if (line.Contains("===BEGIN ICANN DOMAINS===", StringComparison.Ordinal))
        {
            break;
        }
    }

    if (version is null || commitSha is null)
        throw new InvalidOperationException("The public suffix list has no VERSION or COMMIT header");

    var date = DateTimeOffset.ParseExact(version, "yyyy-MM-dd_HH-mm-ss'_UTC'", CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal);
    return (date, commitSha);
}

static (SortedDictionary<string, PublicSuffixRuleFlags> Entries, int RuleCount) ParseList(string content)
{
    var idnMapping = new IdnMapping();
    var entries = new SortedDictionary<string, PublicSuffixRuleFlags>(StringComparer.Ordinal);
    var ruleCount = 0;
    var section = ListSection.None;

    foreach (var rawLine in content.ReplaceLineEndings("\n").Split('\n'))
    {
        var line = rawLine.Trim();
        if (line.StartsWith("//", StringComparison.Ordinal))
        {
            if (line.Contains("===BEGIN ICANN DOMAINS===", StringComparison.Ordinal))
            {
                section = ListSection.Icann;
            }
            else if (line.Contains("===BEGIN PRIVATE DOMAINS===", StringComparison.Ordinal))
            {
                section = ListSection.Private;
            }
            else if (line.Contains("===END ", StringComparison.Ordinal))
            {
                section = ListSection.None;
            }

            continue;
        }

        // A line is only read up to the first whitespace
        var separatorIndex = line.IndexOfAny([' ', '\t']);
        if (separatorIndex >= 0)
        {
            line = line[..separatorIndex];
        }

        if (line.Length is 0)
            continue;

        if (section is ListSection.None)
            throw new InvalidOperationException($"The rule '{line}' is not part of a known section");

        var isException = line[0] is '!';
        if (isException)
        {
            line = line[1..];
        }

        var isWildcard = line.StartsWith("*.", StringComparison.Ordinal);
        if (isWildcard)
        {
            line = line[2..];
        }

        if (line.Contains('*', StringComparison.Ordinal))
            throw new InvalidOperationException($"The rule '{line}' contains a wildcard that is not the leftmost label");

        var suffix = line.ToLowerInvariant();
        if (!Ascii.IsValid(suffix))
        {
            suffix = idnMapping.GetAscii(suffix);
        }

        var flag = (section, isException, isWildcard) switch
        {
            (ListSection.Icann, true, _) => PublicSuffixRuleFlags.IcannException,
            (ListSection.Icann, false, true) => PublicSuffixRuleFlags.IcannWildcard,
            (ListSection.Icann, false, false) => PublicSuffixRuleFlags.IcannRule,
            (ListSection.Private, true, _) => PublicSuffixRuleFlags.PrivateException,
            (ListSection.Private, false, true) => PublicSuffixRuleFlags.PrivateWildcard,
            (ListSection.Private, false, false) => PublicSuffixRuleFlags.PrivateRule,
            _ => throw new InvalidOperationException($"Unsupported rule '{line}'"),
        };

        entries.TryGetValue(suffix, out var flags);
        entries[suffix] = flags | flag;
        ruleCount++;
    }

    return (entries, ruleCount);
}

static IEnumerable<PublicSuffixRuleFlags> EnumerateFlags(PublicSuffixRuleFlags flags)
    => Enum.GetValues<PublicSuffixRuleFlags>().Where(flag => flag is not PublicSuffixRuleFlags.None && (flags & flag) == flag);

static string BuildGroupName(PublicSuffixRuleFlags flags) => "Get" + string.Concat(EnumerateFlags(flags)) + "s";

static string BuildFlagsExpression(PublicSuffixRuleFlags flags)
    => string.Join(" | ", EnumerateFlags(flags).Select(flag => "PublicSuffixRuleFlags." + flag.ToString()));

static string BuildGroup(string name, List<string> suffixes)
{
    var builder = new StringBuilder();
    builder.Append("    private static string[] ").Append(name).Append("() =>\n    [\n");
    foreach (var suffix in suffixes)
    {
        // The suffixes are punycode, so they never need escaping
        builder.Append("        \"").Append(suffix).Append("\",\n");
    }

    builder.Append("    ];");
    return builder.ToString();
}

static bool WriteTextIfChanged(FullPath path, string content)
{
    if (File.Exists(path) && File.ReadAllText(path).ReplaceLineEndings("\n") == content)
        return false;

    File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    return true;
}

static void BumpPackageVersion(FullPath csprojPath)
{
    var document = XDocument.Load(csprojPath, LoadOptions.PreserveWhitespace);
    var versionNode = document.Descendants().First(e => e.Name.LocalName == "Version");
    versionNode.Value = SemanticVersion.Parse(versionNode.Value).NextPatchVersion().ToString();

    var settings = new XmlWriterSettings { OmitXmlDeclaration = true, Indent = false, Encoding = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false) };
    using var writer = XmlWriter.Create(csprojPath, settings);
    document.Save(writer);
}

static void RunGitDiff(FullPath root)
{
    var process = Process.Start(new ProcessStartInfo
    {
        FileName = "git",
        Arguments = "--no-pager diff --stat",
        WorkingDirectory = root,
        UseShellExecute = false,
    });

    process?.WaitForExit();
}

internal enum ListSection
{
    None,
    Icann,
    Private,
}

// Keep in sync with src/Meziantou.Framework.Uri/PublicSuffix/PublicSuffixRuleFlags.cs
[Flags]
internal enum PublicSuffixRuleFlags : byte
{
    None = 0,
    IcannRule = 1,
    PrivateRule = 2,
    IcannWildcard = 4,
    PrivateWildcard = 8,
    IcannException = 16,
    PrivateException = 32,
}
