static async Task<(string Sha, DateTimeOffset Date)> GetLastCommit()
{
    var token = Environment.GetEnvironmentVariable("GITHUB_TOKEN");
    if (string.IsNullOrEmpty(token))
    {
        // gh auth token
        var process = Process.Start(new ProcessStartInfo
        {
            FileName = "gh",
            Arguments = "auth token",
            RedirectStandardOutput = true,
            UseShellExecute = false,
        });
        process!.WaitForExit();
        token = process.StandardOutput.ReadToEnd().Trim();
    }

    using var request = new HttpRequestMessage(HttpMethod.Get, "https://api.github.com/repos/publicsuffix/list/commits?path=public_suffix_list.dat&per_page=1");
    request.Headers.UserAgent.Add(new ProductInfoHeaderValue("Meziantou.Framework.Uri.PublicSuffix.Generator", "1.0"));
    if (!string.IsNullOrEmpty(token))
    {
        request.Headers.Add("Authorization", "Bearer " + token);
    }

    using var response = await SharedHttpClient.Instance.SendAsync(request);
    response.EnsureSuccessStatusCode();
    using var commits = await response.Content.ReadFromJsonAsync<JsonDocument>();
    var lastCommit = commits!.RootElement.EnumerateArray().First();
    var sha = lastCommit.GetProperty("sha").GetString()!;
    var date = lastCommit.GetProperty("commit").GetProperty("committer").GetProperty("date").GetDateTimeOffset();
    return (sha, date);
}

static (SortedDictionary<string, PublicSuffixRuleFlags> Entries, int RuleCount) ParseList(string content)
{
    var idnMapping = new IdnMapping();
    var entries = new SortedDictionary<string, PublicSuffixRuleFlags>(StringComparer.Ordinal);
    var ruleCount = 0;
    var section = ListSection.None;

    foreach (var rawLine in content.ReplaceLineEndings("\n").Split('\n'))
    {
        var line = rawLine.Trim();
        if (line.StartsWith("//", StringComparison.Ordinal))
        {
            if (line.Contains("===BEGIN ICANN DOMAINS===", StringComparison.Ordinal))
            {
                section = ListSection.Icann;
            }
            else if (line.Contains("===BEGIN PRIVATE DOMAINS===", StringComparison.Ordinal))
            {
                section = ListSection.Private;
            }
            else if (line.Contains("===END ", StringComparison.Ordinal))
            {
                section = ListSection.None;
            }

            continue;
        }

        // A line is only read up to the first whitespace
        var separatorIndex = line.IndexOfAny([' ', '\t']);
        if (separatorIndex >= 0)
        {
            line = line[..separatorIndex];
        }

        if (line.Length is 0)
            continue;

        if (section is ListSection.None)
            throw new InvalidOperationException($"The rule '{line}' is not part of a known section");

        var isException = line[0] is '!';
        if (isException)
        {
            line = line[1..];
        }

        var isWildcard = line.StartsWith("*.", StringComparison.Ordinal);
        if (isWildcard)
        {
            line = line[2..];
        }

        if (line.Contains('*', StringComparison.Ordinal))
            throw new InvalidOperationException($"The rule '{line}' contains a wildcard that is not the leftmost label");

        var suffix = line.ToLowerInvariant();
        if (!Ascii.IsValid(suffix))
        {
            suffix = idnMapping.GetAscii(suffix);
        }

        var flag = (section, isException, isWildcard) switch
        {
            (ListSection.Icann, true, _) => PublicSuffixRuleFlags.IcannException,
            (ListSection.Icann, false, true) => PublicSuffixRuleFlags.IcannWildcard,
            (ListSection.Icann, false, false) => PublicSuffixRuleFlags.IcannRule,
            (ListSection.Private, true, _) => PublicSuffixRuleFlags.PrivateException,
            (ListSection.Private, false, true) => PublicSuffixRuleFlags.PrivateWildcard,
            (ListSection.Private, false, false) => PublicSuffixRuleFlags.PrivateRule,
            _ => throw new InvalidOperationException($"Unsupported rule '{line}'"),
        };

        entries.TryGetValue(suffix, out var flags);
        entries[suffix] = flags | flag;
        ruleCount++;
    }

    return (entries, ruleCount);
}

static string BuildGroup(SortedDictionary<string, PublicSuffixRuleFlags> entries, string name, PublicSuffixRuleFlags flag)
{
    var suffixes = entries.Where(entry => (entry.Value & flag) is not PublicSuffixRuleFlags.None).Select(entry => entry.Key).ToList();

    var builder = new StringBuilder();
    builder.Append("    private static string[] ").Append(name).Append("() =>");
    if (suffixes.Count is 0)
    {
        builder.Append(" [];");
        return builder.ToString();
    }

    builder.Append("\n    [\n");
    foreach (var suffix in suffixes)
    {
        // The suffixes are punycode, so they never need escaping
        builder.Append("        \"").Append(suffix).Append("\",\n");
    }

    builder.Append("    ];");
    return builder.ToString();
}

static bool WriteTextIfChanged(FullPath path, string content)
{
    if (File.Exists(path) && File.ReadAllText(path).ReplaceLineEndings("\n") == content)
        return false;

    File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    return true;
}

static void BumpPackageVersion(FullPath csprojPath)
{
    var document = XDocument.Load(csprojPath, LoadOptions.PreserveWhitespace);
    var versionNode = document.Descendants().First(e => e.Name.LocalName == "Version");
    versionNode.Value = SemanticVersion.Parse(versionNode.Value).NextPatchVersion().ToString();

    var settings = new XmlWriterSettings { OmitXmlDeclaration = true, Indent = false, Encoding = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false) };
    using var writer = XmlWriter.Create(csprojPath, settings);
    document.Save(writer);
}

static void RunGitDiff(FullPath root)
{
    var process = Process.Start(new ProcessStartInfo
    {
        FileName = "git",
        Arguments = "--no-pager diff --stat",
        WorkingDirectory = root,
        UseShellExecute = false,
    });

    process?.WaitForExit();
}

internal enum ListSection
{
    None,
    Icann,
    Private,
}

// Keep in sync with src/Meziantou.Framework.Uri/PublicSuffix/PublicSuffixRuleFlags.cs
[Flags]
internal enum PublicSuffixRuleFlags : byte
{
    None = 0,
    IcannRule = 1,
    PrivateRule = 2,
    IcannWildcard = 4,
    PrivateWildcard = 8,
    IcannException = 16,
    PrivateException = 32,
}
