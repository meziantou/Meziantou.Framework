using System.Globalization;
using System.Text;

namespace SpecGen;

internal sealed class CodeWriter
{
    private readonly StringBuilder _builder = new();
    private int _indentation;

    public CodeWriter(string sourceDescription)
    {
        _builder.Append("// <auto-generated>\n");
        _builder.Append("// Generated by tools/Meziantou.Framework.WebPlatform.SpecGen from ").Append(sourceDescription).Append(".\n");
        _builder.Append("// Do not edit manually. Run 'dotnet run --project tools/Meziantou.Framework.WebPlatform.SpecGen' to regenerate.\n");
        _builder.Append("// </auto-generated>\n");
        _builder.Append("#nullable enable\n\n");
    }

    public CodeWriter Line(string text = "")
    {
        // No blank line after an opening brace
        if (text.Length == 0 && _builder.Length >= 2 && _builder[^2] == '{' && _builder[^1] == '\n')
            return this;

        if (text.Length > 0)
        {
            _builder.Append(' ', _indentation * 4);
            _builder.Append(text);
        }

        _builder.Append('\n');
        return this;
    }

    /// <summary>Writes a documentation comment with a summary (the text is XML, e.g. with &lt;c&gt; elements).</summary>
    public CodeWriter Summary(string xml) => Line("/// <summary>" + xml + "</summary>");

    /// <summary>Writes a documentation comment that links to a URL (e.g. the specification of an [IdlMember]).</summary>
    public CodeWriter SeeAlso(string url) => Line("/// <seealso href=\"" + XmlText(url) + "\"/>");

    /// <summary>Escapes a text for a documentation comment.</summary>
    public static string XmlText(string text) => System.Security.SecurityElement.Escape(text);

    public IDisposable Block(string header)
    {
        Line(header);
        Line("{");
        _indentation++;
        return new Scope(this);
    }

    public void Numbers<T>(IEnumerable<T> values, int perLine = 24)
        where T : IFormattable
    {
        var count = 0;
        var line = new StringBuilder();
        foreach (var value in values)
        {
            line.Append(value.ToString(null, CultureInfo.InvariantCulture)).Append(',');
            count++;
            if (count % perLine == 0)
            {
                Line(line.ToString());
                line.Clear();
            }
            else
            {
                line.Append(' ');
            }
        }

        if (line.Length > 0)
        {
            Line(line.ToString().TrimEnd());
        }
    }

    public static string Literal(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                default:
                    if (c < 0x20 || c > 0x7E)
                    {
                        sb.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(c);
                    }

                    break;
            }
        }

        return sb.Append('"').ToString();
    }

    public override string ToString() => _builder.ToString();

    private sealed class Scope(CodeWriter writer) : IDisposable
    {
        public void Dispose()
        {
            writer._indentation--;
            writer.Line("}");
        }
    }
}
