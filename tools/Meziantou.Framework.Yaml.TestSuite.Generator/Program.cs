using System.Text.RegularExpressions;
using Meziantou.Framework;

// Refreshes the yaml-test-suite cases that the parser, emitter and loader tests of Meziantou.Framework.Yaml run.
// Upstream publishes the cases as data-YYYY-MM-DD release tags of the data branch, and asks not to use the branch
// itself: it contains unreleased commits and is force pushed. Like the other generators, it returns 1 when it updated
// the files and 0 when they were up to date.
const string Repository = "yaml/yaml-test-suite";

if (!FullPath.CurrentDirectory().TryFindGitRepositoryRoot(out var root))
    throw new InvalidOperationException("Cannot find git root from " + FullPath.CurrentDirectory());

var filesPath = root / "tests" / "Meziantou.Framework.Yaml.Tests" / "files" / "yaml-test-suite";

var token = GetGitHubToken();
var tag = await GetLatestDataTag(token);
var commitSha = await GetCommitSha(token, tag);
Console.WriteLine($"Latest release: {tag} ({commitSha})");

var archiveUrl = $"https://codeload.github.com/{Repository}/tar.gz/{commitSha}";
Console.WriteLine("Downloading " + archiveUrl);
var files = await DownloadArchive(archiveUrl);

// The data branch has no license file: it is the one of the main branch, which covers the whole repository
var licenseUrl = $"https://raw.githubusercontent.com/{Repository}/main/License";
Console.WriteLine("Downloading " + licenseUrl);
var license = await SharedHttpClient.Instance.GetStringAsync(licenseUrl);

var cases = CreateCases(files);
if (cases.Count is 0)
    throw new InvalidOperationException("The yaml-test-suite archive has no test case");

Console.WriteLine($"{cases.Count.ToString(CultureInfo.InvariantCulture)} test cases");

var readme = $"""
    # YAML test suite

    Offline fixtures from the `{tag}` release of https://github.com/{Repository}
    (https://github.com/{Repository}/tree/{commitSha}), licensed under MIT; see LICENSE.txt.

    cases.json contains the {cases.Count.ToString(CultureInfo.InvariantCulture)} cases of the release. Each case has the upstream case ID, its name (`===`), its input
    (`in.yaml`), its expected events (`test.event`, without the trailing line breaks) and whether it must fail to parse
    (`error`). When upstream provides them, a case also has the JSON value it loads as (`json`, from `in.json`), the
    output of a normalizing emitter (`out`, from `out.yaml`) and the output of an emitter that keeps the styles (`emit`,
    from `emit.yaml`). The other strings are the upstream files, unmodified. These fixtures are independent expected results,
    not outputs generated by this library.

    Do not edit these files. To refresh them, run
    `dotnet run --project tools/Meziantou.Framework.Yaml.TestSuite.Generator`, which the update-yaml-test-suite
    workflow does every week.

    """.ReplaceLineEndings("\n");

var updated = false;
updated |= WriteIfChanged(filesPath / "cases.json", SerializeCases(cases));
updated |= WriteIfChanged(filesPath / "LICENSE.txt", license.ReplaceLineEndings("\n"));
updated |= WriteIfChanged(filesPath / "README.md", readme);

if (!updated)
{
    Console.WriteLine("The yaml-test-suite cases are up to date");
    return 0;
}

Console.WriteLine("The files have been updated");
RunGitDiff(root);
return 1;

static List<TestCase> CreateCases(Dictionary<string, string> files)
{
    // A case is a directory with an in.yaml file. The cases with several variants have one subdirectory per variant
    // (2G84/00, 2G84/01, ...). The name and tags directories only contain symbolic links, which the archive reader
    // skips.
    var cases = new List<TestCase>();
    foreach (var path in files.Keys.Where(path => path.EndsWith("/in.yaml", StringComparison.Ordinal)).Order(StringComparer.Ordinal))
    {
        var id = path[..^"/in.yaml".Length];
        var name = files.TryGetValue(id + "/===", out var nameFile) ? nameFile.Trim() : id;
        var events = files.TryGetValue(id + "/test.event", out var eventFile) ? eventFile.TrimEnd('\n') : throw new InvalidOperationException($"The case {id} has no test.event file");
        cases.Add(new TestCase(
            id,
            name,
            files[path],
            events,
            files.ContainsKey(id + "/error"),
            files.GetValueOrDefault(id + "/in.json"),
            files.GetValueOrDefault(id + "/out.yaml"),
            files.GetValueOrDefault(id + "/emit.yaml")));
    }

    return cases;
}

static string SerializeCases(List<TestCase> cases)
{
    using var stream = new MemoryStream();
    using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true, NewLine = "\n", Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }))
    {
        writer.WriteStartArray();
        foreach (var item in cases)
        {
            writer.WriteStartObject();
            writer.WriteString("id", item.Id);
            writer.WriteString("name", item.Name);
            writer.WriteString("yaml", item.Yaml);
            writer.WriteString("events", item.Events);
            writer.WriteBoolean("error", item.Error);
            WriteOptionalString(writer, "json", item.Json);
            WriteOptionalString(writer, "out", item.Out);
            WriteOptionalString(writer, "emit", item.Emit);
            writer.WriteEndObject();
        }

        writer.WriteEndArray();
    }

    return Encoding.UTF8.GetString(stream.ToArray()) + "\n";

    static void WriteOptionalString(Utf8JsonWriter writer, string propertyName, string? value)
    {
        if (value is not null)
        {
            writer.WriteString(propertyName, value);
        }
    }
}

static async Task<Dictionary<string, string>> DownloadArchive(string url)
{
    // The files are kept in memory with their path relative to the root of the archive, whose first directory is
    // named after the repository and the commit
    var files = new Dictionary<string, string>(StringComparer.Ordinal);
    var encoding = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true);
    await using var response = await SharedHttpClient.Instance.GetStreamAsync(url);
    await using var gzip = new GZipStream(response, CompressionMode.Decompress);
    using var tar = new TarReader(gzip);
    while (tar.GetNextEntry() is { } entry)
    {
        if (entry.EntryType is not (TarEntryType.RegularFile or TarEntryType.V7RegularFile))
            continue;

        var separator = entry.Name.IndexOf('/', StringComparison.Ordinal);
        if (separator < 0)
            continue;

        // An empty file, such as the error marker or an empty input, has no data stream
        using var content = new MemoryStream();
        entry.DataStream?.CopyTo(content);

        // GetString keeps a byte order mark, which some cases test
        files[entry.Name[(separator + 1)..]] = encoding.GetString(content.GetBuffer(), 0, (int)content.Length);
    }

    return files;
}

static string? GetGitHubToken()
{
    var token = Environment.GetEnvironmentVariable("GITHUB_TOKEN");
    if (!string.IsNullOrEmpty(token))
        return token;

    try
    {
        var process = Process.Start(new ProcessStartInfo
        {
            FileName = "gh",
            Arguments = "auth token",
            RedirectStandardOutput = true,
            UseShellExecute = false,
        });
        var output = process!.StandardOutput.ReadToEnd().Trim();
        process.WaitForExit();
        return output;
    }
    catch (System.ComponentModel.Win32Exception)
    {
        // gh is not installed: the anonymous rate limit is enough for the two requests
        return null;
    }
}

static async Task<string> GetLatestDataTag(string? token)
{
    // The tags are named after their date, so the latest one is the greatest in ordinal order
    using var document = await GetGitHubJson(token, $"https://api.github.com/repos/{Repository}/git/matching-refs/tags/data-");
    var tags = document.RootElement.EnumerateArray()
        .Select(element => element.GetProperty("ref").GetString()!["refs/tags/".Length..])
        .Where(name => Regex.IsMatch(name, @"^data-[0-9]{4}-[0-9]{2}-[0-9]{2}$", RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1)))
        .ToList();
    if (tags.Count is 0)
        throw new InvalidOperationException("The yaml-test-suite repository has no data release tag");

    return tags.Max(StringComparer.Ordinal)!;
}

static async Task<string> GetCommitSha(string? token, string tag)
{
    using var document = await GetGitHubJson(token, $"https://api.github.com/repos/{Repository}/commits/{tag}");
    return document.RootElement.GetProperty("sha").GetString()!;
}

static async Task<JsonDocument> GetGitHubJson(string? token, string url)
{
    using var request = new HttpRequestMessage(HttpMethod.Get, url);
    request.Headers.UserAgent.Add(new ProductInfoHeaderValue("Meziantou.Framework.Yaml.TestSuite.Generator", "1.0"));
    if (!string.IsNullOrEmpty(token))
    {
        request.Headers.Add("Authorization", "Bearer " + token);
    }

    using var response = await SharedHttpClient.Instance.SendAsync(request);
    response.EnsureSuccessStatusCode();
    return (await response.Content.ReadFromJsonAsync<JsonDocument>())!;
}

static bool WriteIfChanged(FullPath path, string content)
{
    var bytes = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(content);
    if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
        return false;

    File.WriteAllBytes(path, bytes);
    return true;
}

static void RunGitDiff(FullPath root)
{
    var process = Process.Start(new ProcessStartInfo
    {
        FileName = "git",
        Arguments = "--no-pager diff --stat",
        WorkingDirectory = root,
        UseShellExecute = false,
    });

    process?.WaitForExit();
}

internal sealed record TestCase(string Id, string Name, string Yaml, string Events, bool Error, string? Json, string? Out, string? Emit);
